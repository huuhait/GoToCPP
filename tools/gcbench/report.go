// cmdReport writes the markdown of a JSON file made by a run, so that the
// document can be made again without measuring again.
func cmdReport(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("gcbench report", flag.ContinueOnError)
	fs.SetOutput(stderr)
	in := fs.String("in", "", "the JSON file of a run (required)")
	md := fs.String("md", "", "write the markdown here (empty: print it to stdout)")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if *in == "" {
		fmt.Fprintln(stderr, "gcbench report: -in is required")
		return 2
	}
	data, err := os.ReadFile(*in)
	if err != nil {
		fmt.Fprintln(stderr, "gcbench report:", err)
		return 2
	}
	var r report
	if err := json.Unmarshal(data, &r); err != nil {
		fmt.Fprintln(stderr, "gcbench report:", err)
		return 2
	}
	if r.Schema > schemaVersion {
		fmt.Fprintf(stderr, "gcbench report: %s has schema %d, newer than %d\n", *in, r.Schema, schemaVersion)
		return 2
	}
	out := markdown(&r)
	if *md == "" {
		fmt.Fprint(stdout, out)
		return 0
	}
	if err := os.WriteFile(*md, []byte(out), 0o644); err != nil {
		fmt.Fprintln(stderr, "gcbench report:", err)
		return 2
	}
	return 0
}

// writeJSON writes the report as indented JSON (schema 1). The field order is
// the struct order, so two runs of the same data produce the same file.
func writeJSON(path string, r *report) error {
	data, err := json.MarshalIndent(r, "", "  ")
	if err != nil {
		return err
	}
	if dir := filepath.Dir(path); dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
	}
	return os.WriteFile(path, append(data, '\n'), 0o644)
}

// runCell formats one run for the log: wall time and its spread.
func runCell(rr *runResult) string {
	switch rr.Status {
	case runOK:
		return fmt.Sprintf("%8.1fms ±%4.1f%% cpu %7.1fms rss %6.1fMB", rr.Wall.Median/1e6, 100*rr.Wall.relNoise(), rr.CPU.Median/1e6, rr.RSS.Median/1024)
	case runMismatch:
		return "MISMATCH: " + firstLine(rr.Note)
	default:
		return "FAILED: " + firstLine(rr.Note)
	}
}

// markdown renders the report as the document committed at
// docs/benchmarks/gc-engine-spike.md.
func markdown(r *report) string {
	var b strings.Builder
	b.WriteString("<!-- Generated by `tools/gcbench` (Phase 16, step 16.1h-base). Do not edit by hand. -->\n\n")
	b.WriteString("# GC engine spike: the Go and ARC baselines\n\n")
	if r.Smoke {
		b.WriteString("> **Smoke run.** Tiny sizes and one run per cell: this checks the harness and compares the outputs. The times mean nothing.\n\n")
	}
	b.WriteString("The measurement harness of Phase 16 step 16.1: the same small programs (`bench/gc/`) built by real Go, by gocpp's reference-counting engine (ARC) and, once the GC engine exists, by `gocpp build -gc-engine`, and run at several thread counts. Every run's deterministic output (a checksum or an operation count) is compared across the flavors: a difference is a `MISMATCH` and fails the run.\n\n")

	b.WriteString("## Machine\n\n| | |\n|---|---|\n")
	row := func(k, v string) { fmt.Fprintf(&b, "| %s | %s |\n", k, v) }
	if r.Commit != "" {
		dirty := ""
		if r.Dirty {
			dirty = " (uncommitted changes)"
		}
		row("commit", r.Commit+dirty)
	}
	row("date", r.Generated)
	row("cpu", fmt.Sprintf("%s, %d logical cores, %d GiB", r.Machine.CPU, r.Machine.Cores, r.Machine.MemGiB))
	row("os", r.Machine.OS)
	row("go", r.Machine.Go)
	row("g++", r.Machine.Gxx)
	row("clang++", r.Machine.Clang)
	row("gocpp", r.Machine.Gocpp)
	row("load average (1, 5, 15 min)", fmt.Sprintf("%.2f %.2f %.2f before, %.2f %.2f %.2f after (quiet below %.1f)",
		r.Machine.LoadBefore[0], r.Machine.LoadBefore[1], r.Machine.LoadBefore[2],
		r.Machine.LoadAfter[0], r.Machine.LoadAfter[1], r.Machine.LoadAfter[2], r.Machine.MaxLoad))
	row("setting", fmt.Sprintf("%d measured runs after %d warm-up run(s) per cell, medians; ±N%% is the median absolute deviation as a share of the median; binarytrees depth %d; threads %s; %s",
		r.Reps, r.Warmup, r.Depth, joinInts(r.Threads), smokeSetting(r.Smoke)))
	row("gocpp gate phase", r.GatePhase)
	row("timeout per run", fmt.Sprintf("%d s", r.TimeoutMS/1000))
	if note := r.Machine.busyNote(); note != "" {
		row("noise", note)
	}

	b.WriteString("\n## Commands\n\n```\n")
	b.WriteString(r.Command + "\n```\n\n")
	b.WriteString("That is the tool's own record of its arguments. In this repository it was run from the worktree's dev shell as `scripts/in-devenv go run ./tools/gcbench run <the same arguments>`.\n\n")
	b.WriteString("Every build and run is started with `GOMAXPROCS=16` for the go commands (`go build`, the gocpp build), and the measured Go program gets `GOMAXPROCS` set to the thread count of its row, so that Go's scheduler has as many processors as the ARC program has OS threads. The builds are:\n\n")
	b.WriteString("| flavor | build command | environment |\n|---|---|---|\n")
	seen := map[string]bool{}
	for _, pr := range r.Programs {
		for _, fr := range pr.Flavors {
			if seen[fr.Flavor] || fr.BuildCommand == "" {
				continue
			}
			seen[fr.Flavor] = true
			fmt.Fprintf(&b, "| %s | `%s` | %s |\n", fr.Flavor, fr.BuildCommand, buildEnvNote(fr.Flavor, r.CXX, r.CXXFlags, r.GatePhase))
		}
	}
	b.WriteString("\nThe programs print one deterministic line with `-quiet` (`checksum N` or `ops N`); the timing lines they print without it are not compared, because they differ between engines by design.\n")

	b.WriteString("\n## Builds\n\n")
	b.WriteString("| program | flavor | build (s) | binary (MiB) |\n|---|---|--:|--:|\n")
	for _, pr := range r.Programs {
		for _, fr := range pr.Flavors {
			build, size := "-", "-"
			switch fr.Status {
			case statusOK:
				build = fmt.Sprintf("%.1f", float64(fr.BuildMS)/1000)
				size = fmt.Sprintf("%.1f", float64(fr.BinSize)/(1<<20))
			case statusNotAvailable:
				build, size = "not yet (16.1d/16.1f)", "-"
			case statusBuildFailed:
				build, size = "build failed", "-"
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", pr.Name, fr.Flavor, build, size)
		}
	}
	b.WriteString("\nThe build time is the wall time of that build in this run's shared object cache (the first gocpp build of a run also builds the runtime), not a cold-build measurement; the binary sizes are exact and include the debug information of the default build.\n")

	b.WriteString("\n## Results\n\n")
	b.WriteString("Wall time and CPU time are in milliseconds, the resident set in mebibytes. The median and the median absolute deviation are over the measured runs; a run under 20 ms can have no resident-set figure (`-`), because the kernel's high-water mark cannot be sampled before it ends.\n")
	for _, pr := range r.Programs {
		fmt.Fprintf(&b, "\n### %s\n\n%s\n\n", pr.Name, pr.About)
		b.WriteString(outputLine(pr) + "\n\n")
		b.WriteString(metricTable(pr, r.Threads, "wall"))
		b.WriteString(metricTable(pr, r.Threads, "cpu"))
		b.WriteString(metricTable(pr, r.Threads, "rss"))
	}

	b.WriteString(failuresSection(r))
	b.WriteString("\n## Notes\n\n")
	b.WriteString("- **The GC rows are not available yet (16.1d/16.1f).** `gocpp build -gc-engine` does not exist yet (today it says `flag provided but not defined: -gc-engine`); the harness runs it, records the message and writes `not yet (16.1d/16.1f)` in the GC cells instead of numbers. No GC number is invented.\n")
	b.WriteString("- **The ARC rows are the default build.** They are `gocpp build` with gocpp's own flags (`-O0 -g` today), as the ticket defines the ARC flavor; they are not an optimized-build comparison with Go. `-cxxflags \"-O2 -g0\"` measures the optimized build with the same harness.\n")
	b.WriteString("- **The `parks` row at 1 thread measures only `Sleep`.** A channel hand-off needs a second goroutine, so the channel and `select` phases start at 2 threads; the operation count of every other row includes both phases. The wall time also includes the fixed Sleep phase (200 sleeps of 100 µs per worker), which dominates the low-thread rows: at 1 thread the Go wall time is mostly its Sleep granularity (about 1 ms per Sleep), not the cost of a park.\n")
	b.WriteString("- **The `syscalls` row mixes two calls.** Each round makes one `os.Getpid` (a real system call) and one `time.Now` (the runtime's clock read); the harness does not attribute the cost between them.\n")
	b.WriteString("- **`binarytrees` splits the two big trees at level 4** so that every work item is independent (the classic benchmark cannot split a tree over workers); the printed checksum is the sum of the per-tree checks and is identical for every thread count and both engines, not the classic per-depth printout. Its peak-RSS column is therefore the split program's: the long-lived tree that drives the classic benchmark's peak is never held whole, so the figures are the live subtrees plus the allocator's high-water mark.\n")
	b.WriteString("- **Wall time is not the comparison for `binarytrees`.** The program is allocation-heavy and Go's collector does its work on several threads: Go's CPU time is much larger than its wall time and rises with the thread count, while its wall time barely falls from 1 to 64 threads (see the two tables). Compare the CPU time for the work; a wall-time row puts Go's collector work on other threads, while ARC's reference counting runs on the working thread, so a wall-time ratio between the engines is not an engine comparison here.\n")
	b.WriteString("- **The machine is shared.** The load averages above are recorded with the numbers; when the 1-minute load is over the limit the run is noisy, and the medians and their spreads, not a single run, are what to read. Nothing here is pinned to a set of cpus, and nothing is compared across machines.\n")
	b.WriteString("- **What job 16.1h adds.** The GC columns, once `gocpp build -gc-engine` exists, and the goroutine-count rows that this harness does not have yet: 1,000 and 10,000 goroutines, blocked and running, with realistic stack depths, the stop-the-world pause and the memory per thread.\n")
	b.WriteString("- **No budget and no engine comparison is claimed from these numbers.** They are the Go and ARC baselines that the GC engine's numbers (job 16.1h) will be compared with, and the input to the budgets of step 16.2.\n")
	if r.Smoke {
		b.WriteString("- **This is a smoke run**: its times are not a baseline.\n")
	}
	return b.String()
}

// failuresSection lists every build failure, run failure and mismatch with its
// note, so that a failed cell in a table is never left unexplained.
func failuresSection(r *report) string {
	var lines []string
	for _, pr := range r.Programs {
		for _, fr := range pr.Flavors {
			if fr.Status == statusBuildFailed {
				lines = append(lines, fmt.Sprintf("- `%s` %s: build failed: %s", pr.Name, fr.Flavor, firstLine(fr.Note)))
			}
			for _, rr := range fr.Runs {
				if rr.Status != runOK {
					lines = append(lines, fmt.Sprintf("- `%s` %s at %d threads: %s: %s", pr.Name, fr.Flavor, rr.Threads, rr.Status, firstLine(rr.Note)))
				}
			}
		}
	}
	if len(lines) == 0 {
		return ""
	}
	return "\n## Failures\n\n" + strings.Join(lines, "\n") + "\n"
}

// smokeSetting describes the size setting in the machine table.
func smokeSetting(smoke bool) string {
	if smoke {
		return "smoke sizes"
	}
	return "full sizes"
}

// buildEnvNote describes the environment of a flavor's build.
func buildEnvNote(flavor, cxx, cxxflags, gate string) string {
	switch flavor {
	case "go":
		return "`GOMAXPROCS=16`, `GOTOOLCHAIN=local`, `GOWORK=off`, `CGO_ENABLED=0`, `GOPROXY=off` (no network)"
	case "arc", "gc":
		compiler := "`GOCPP_CXX` unset (gocpp's choice)"
		if cxx != "" {
			compiler = "`GOCPP_CXX=" + cxx + "`"
		}
		flags := "`GOCPP_CXXFLAGS` unset (gocpp's default, `-O0 -g` today)"
		if cxxflags != "" {
			flags = "`GOCPP_CXXFLAGS=" + cxxflags + "`"
		}
		if gate == "" {
			gate = "15"
		}
		note := "`GOMAXPROCS=16`, its own cache in the work folder, `GOCPP_MODCACHE=off`, `GOCPP_OFFLINE=1`, `GOCPP_GATE_PHASE=" + gate + "`, " + compiler + ", " + flags
		if flavor == "gc" {
			note += ", plus `-gc-engine`"
		}
		return note
	}
	return ""
}

// outputLine is the correctness line of a program: the deterministic output
// the flavors printed at the highest thread count, and whether they agree. The
// text may depend on the thread count (parks and syscalls print the number of
// operations they were asked to do), so it is compared per thread count; a
// program whose output must not depend on it (binarytrees' checksum) is also
// compared across the thread counts. "Agree at every thread count" is only
// claimed when every flavor that ran has an OK run at every thread count.
func outputLine(pr programResult) string {
	threads := threadCounts(&pr)
	if len(threads) == 0 {
		return "Output: (no flavor ran)"
	}
	last := threads[len(threads)-1]
	complete := true
	anyMismatch := false
	for i := range pr.Flavors {
		fr := &pr.Flavors[i]
		for _, rr := range fr.Runs {
			if rr.Status == runMismatch {
				anyMismatch = true
			}
		}
		if fr.Status != statusOK {
			continue
		}
		for _, t := range threads {
			if rr := findRun(fr, t); rr == nil || rr.Status != runOK {
				complete = false
			}
		}
	}
	mismatch := false
	for _, t := range threads {
		var outs []string
		for i := range pr.Flavors {
			fr := &pr.Flavors[i]
			if fr.Status != statusOK {
				continue
			}
			rr := findRun(fr, t)
			if rr == nil || rr.Status != runOK {
				continue
			}
			outs = append(outs, rr.Output)
		}
		if len(outs) >= 2 && !allEqual(outs) {
			mismatch = true
		}
	}
	if sameAcrossThreads(pr.Name) {
		var outs []string
		for i := range pr.Flavors {
			fr := &pr.Flavors[i]
			if fr.Status != statusOK {
				continue
			}
			for _, rr := range fr.Runs {
				if rr.Status == runOK {
					outs = append(outs, rr.Output)
				}
			}
		}
		if len(outs) >= 2 && !allEqual(outs) {
			mismatch = true
		}
	}
	var parts []string
	for i := range pr.Flavors {
		fr := &pr.Flavors[i]
		if fr.Status != statusOK {
			continue
		}
		rr := findRun(fr, last)
		if rr == nil || rr.Output == "" {
			continue
		}
		parts = append(parts, fmt.Sprintf("%s `%s`", fr.Flavor, firstLine(rr.Output)))
	}
	if len(parts) == 0 {
		return "Output: (no flavor ran)"
	}
	switch {
	case anyMismatch || mismatch:
		return fmt.Sprintf("Output at %d threads: **MISMATCH** — %s.", last, strings.Join(parts, ", "))
	case !complete:
		return fmt.Sprintf("Output at %d threads: %s — not every flavor has an OK run at every thread count (see Failures).", last, strings.Join(parts, ", "))
	default:
		return fmt.Sprintf("Output at %d threads: %s — the flavors agree at every thread count (the correctness check).", last, strings.Join(parts, ", "))
	}
}

// metricTable renders one table (wall, cpu or rss) of a program.
func metricTable(pr programResult, threads []int, metric string) string {
	var b strings.Builder
	switch metric {
	case "wall":
		b.WriteString("#### Wall time (ms, median ±MAD%)\n\n")
	case "cpu":
		b.WriteString("#### CPU time, user+system (ms, median ±MAD%)\n\n")
	case "rss":
		b.WriteString("#### Peak resident set (MiB, median)\n\n")
	}
	b.WriteString("| threads")
	for _, fr := range pr.Flavors {
		fmt.Fprintf(&b, " | %s", fr.Flavor)
	}
	b.WriteString(" |\n|---|")
	for range pr.Flavors {
		b.WriteString("--:|")
	}
	b.WriteString("\n")
	for _, t := range threads {
		fmt.Fprintf(&b, "| %d", t)
		for i := range pr.Flavors {
			fmt.Fprintf(&b, " | %s", cell(&pr.Flavors[i], t, metric))
		}
		b.WriteString(" |\n")
	}
	b.WriteString("\n")
	return b.String()
}

// cell formats the result of one flavor at one thread count for a metric.
func cell(fr *flavorResult, threads int, metric string) string {
	switch fr.Status {
	case statusNotAvailable:
		return "not yet (16.1d/16.1f)"
	case statusBuildFailed:
		return "build failed"
	}
	rr := findRun(fr, threads)
	if rr == nil {
		return "-"
	}
	switch rr.Status {
	case runMismatch:
		return "**MISMATCH**"
	case runFailed:
		return "**failed**"
	}
	st := rr.Wall
	if metric == "cpu" {
		st = rr.CPU
	} else if metric == "rss" {
		st = rr.RSS
	}
	if st.N == 0 {
		return "-"
	}
	switch metric {
	case "rss":
		return fmt.Sprintf("%.1f", st.Median/1024)
	default:
		return fmt.Sprintf("%.1f ±%.1f%%", st.Median/1e6, 100*st.relNoise())
	}
}

// joinInts formats a list of thread counts.
func joinInts(xs []int) string {
	parts := make([]string, len(xs))
	for i, x := range xs {
		parts[i] = fmt.Sprint(x)
	}
	return strings.Join(parts, ", ")
}
