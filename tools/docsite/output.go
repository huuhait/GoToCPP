//go:embed assets/page.html assets/style.css assets/search.js
var assetFS embed.FS

type navLink struct {
	Href, Title string
	Current     bool
}

type navView struct {
	Title string
	Open  bool
	Items []navLink
}

type pageView struct {
	Title, Root, Source string
	Body                template.HTML
	Nav                 []navView
	Prev, Next          *navLink
}

// siblings returns the pages of a section that are listed in the sidebar, in order.
func (s *site) listed(sec *navSection) []*page {
	var out []*page
	seen := map[*page]bool{}
	for _, e := range sec.entries {
		if e.hidden {
			continue
		}
		for _, pg := range e.pages {
			if !seen[pg] {
				seen[pg] = true
				out = append(out, pg)
			}
		}
	}
	return out
}

func (pg *page) sidebarTitle() string {
	if pg.navTitle != "" {
		return pg.navTitle
	}
	return pg.title
}

// siteMarker is the file that marks a folder as one that docsite wrote.
const siteMarker = ".docsite"

// tempPrefix starts the name of the folder that a site is written to before it is swapped in.
const tempPrefix = ".docsite-new-"

// leftoverAge is how old a temporary folder of an earlier run must be before it is removed, so
// that a run that is going on in the same folder is not disturbed.
const leftoverAge = time.Hour

// removeLeftovers removes the temporary folders that a run which was killed left next to the
// site (".docsite-new-*" and its ".old"): only folders that hold the .docsite marker as a regular
// file, which docsite wrote, and that are older than leftoverAge.
func removeLeftovers(parent string) {
	entries, err := os.ReadDir(parent)
	if err != nil {
		return
	}
	for _, e := range entries {
		if !e.IsDir() || !strings.HasPrefix(e.Name(), tempPrefix) {
			continue
		}
		dir := filepath.Join(parent, e.Name())
		fi, err := os.Lstat(dir)
		if err != nil || time.Since(fi.ModTime()) < leftoverAge {
			continue
		}
		if mi, err := os.Lstat(filepath.Join(dir, siteMarker)); err != nil || !mi.Mode().IsRegular() {
			continue
		}
		_ = os.RemoveAll(dir)
	}
}

// checkOut refuses an output folder that docsite must not replace: one under the docs (the site
// would become part of its own input), one that holds the docs or the repository (it would be
// wiped), a symbolic link, or a folder that is not empty and not a site of an earlier run (a
// mistyped -out must never wipe a folder of the user's).
func (s *site) checkOut(out string) error {
	within := func(dir, p string) bool {
		r, err := filepath.Rel(dir, p)
		return err == nil && r != ".." && !strings.HasPrefix(r, ".."+string(filepath.Separator))
	}
	if within(s.docs, out) {
		return fmt.Errorf("-out %s is inside the docs folder %s", out, s.docs)
	}
	if within(out, s.docs) || within(out, s.repo) || out == filepath.Dir(out) {
		return fmt.Errorf("-out %s contains the docs or the repository: not wiping it", out)
	}
	fi, err := os.Lstat(out)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if !fi.IsDir() { // Lstat: a symbolic link is not a folder
		return fmt.Errorf("-out %s is not a folder (a link or a file)", out)
	}
	entries, err := os.ReadDir(out)
	if err != nil {
		return err
	}
	if len(entries) == 0 {
		return nil
	}
	mi, err := os.Lstat(filepath.Join(out, siteMarker))
	if err != nil || !mi.Mode().IsRegular() {
		return fmt.Errorf("%s is not empty and has no %s file: not a site folder, not touching it", out, siteMarker)
	}
	return nil
}

// write writes the site into out. The new site is written to a folder next to out and swapped
// in when it is complete, so a failure in the middle leaves the old site as it was.
func (s *site) write(out string) error {
	out, err := filepath.Abs(out)
	if err != nil {
		return err
	}
	if err := s.checkOut(out); err != nil {
		return err
	}
	parent := filepath.Dir(out)
	if err := os.MkdirAll(parent, 0o755); err != nil {
		return err
	}
	removeLeftovers(parent)
	tmp, err := os.MkdirTemp(parent, tempPrefix)
	if err != nil {
		return err
	}
	defer os.RemoveAll(tmp) // after a successful swap it is the old site
	if err := s.writeTo(tmp); err != nil {
		return err
	}
	if err := os.Chmod(tmp, 0o755); err != nil {
		return err
	}
	old := tmp + ".old"
	if _, err := os.Lstat(out); err == nil {
		if err := os.Rename(out, old); err != nil {
			return err
		}
		defer os.RemoveAll(old)
	}
	if err := os.Rename(tmp, out); err != nil {
		_ = os.Rename(old, out) // put the old site back
		return err
	}
	return nil
}

// writeTo writes all the files of the site into the empty folder out.
func (s *site) writeTo(out string) error {
	if err := os.WriteFile(filepath.Join(out, siteMarker), []byte("generated by tools/docsite; make clean-docs removes it\n"), 0o644); err != nil {
		return err
	}
	tmpl, err := template.ParseFS(assetFS, "assets/page.html")
	if err != nil {
		return err
	}
	for _, f := range []string{"style.css", "search.js"} {
		b, _ := assetFS.ReadFile("assets/" + f)
		if err := writeFile(filepath.Join(out, "assets", f), b); err != nil {
			return err
		}
	}
	if err := writeFile(filepath.Join(out, "assets", "search-index.js"), s.searchIndex()); err != nil {
		return err
	}
	for _, a := range s.assets {
		b, err := os.ReadFile(filepath.Join(s.docs, filepath.FromSlash(a)))
		if err != nil {
			return err
		}
		if err := writeFile(filepath.Join(out, filepath.FromSlash(a)), b); err != nil {
			return err
		}
	}
	for _, pg := range s.pages {
		var buf bytes.Buffer
		if err := tmpl.Execute(&buf, s.view(pg)); err != nil {
			return err
		}
		if err := writeFile(filepath.Join(out, filepath.FromSlash(pg.out)), buf.Bytes()); err != nil {
			return err
		}
	}
	return nil
}

func writeFile(p string, b []byte) error {
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	return os.WriteFile(p, b, 0o644)
}

// root returns the prefix that leads from the page to the root of the site ("", "../", ...).
func (pg *page) root() string {
	n := strings.Count(pg.out, "/")
	return strings.Repeat("../", n)
}

func (s *site) view(pg *page) pageView {
	v := pageView{Title: pg.title, Root: pg.root(), Body: template.HTML(pg.body)}
	dir := path.Dir(pg.out)
	href := func(t *page) string { return rel(dir, t.out) }
	for _, sec := range s.nav {
		nv := navView{Title: sec.title}
		pages := s.listed(sec)
		for i, p := range pages {
			cur := p == pg
			nv.Items = append(nv.Items, navLink{Href: href(p), Title: p.sidebarTitle(), Current: cur})
			if cur && sec.title == pg.section {
				if i > 0 {
					v.Prev = &navLink{Href: href(pages[i-1]), Title: pages[i-1].sidebarTitle()}
				}
				if i+1 < len(pages) {
					v.Next = &navLink{Href: href(pages[i+1]), Title: pages[i+1].sidebarTitle()}
				}
			}
		}
		nv.Open = pg.section == sec.title
		if len(nv.Items) > 0 {
			v.Nav = append(v.Nav, nv)
		}
	}
	if !pg.generated {
		v.Source = s.repoURL + "/blob/" + s.branch + "/docs/" + pg.src
	}
	return v
}

type searchEntry struct {
	T string `json:"t"`           // the text searched and shown
	U string `json:"u"`           // the URL from the root of the site
	P string `json:"p,omitempty"` // the page, for a heading
	L int    `json:"l"`           // 0 for a page, else the level of the heading
}

// searchIndex returns assets/search-index.js: the pages and their headings.
func (s *site) searchIndex() []byte {
	var idx []searchEntry
	for _, pg := range s.pages {
		idx = append(idx, searchEntry{T: pg.title, U: pg.out})
		for _, h := range pg.headings {
			if h.Level == 1 && h.Text == pg.title {
				continue
			}
			idx = append(idx, searchEntry{T: h.Text, U: pg.out + "#" + h.ID, P: pg.title, L: h.Level})
		}
	}
	for _, pg := range s.pages {
		if !pg.generated || !strings.HasPrefix(pg.out, "stdlib/") || pg.out == "stdlib/index.html" {
			continue
		}
		for id := range pg.ids {
			if strings.HasPrefix(id, "package-") || strings.Contains(id, "-") || stdSections[id] {
				continue
			}
			idx = append(idx, searchEntry{T: strings.TrimSuffix(strings.TrimPrefix(pg.out, "stdlib/"), ".html") + "." + id, U: pg.out + "#" + id, P: pg.title, L: 3})
		}
	}
	sortEntries(idx)
	var buf bytes.Buffer
	buf.WriteString("window.DOCS_INDEX = ")
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(true)
	_ = enc.Encode(idx)
	buf.WriteString(";\n")
	return buf.Bytes()
}

func sortEntries(e []searchEntry) {
	sort.SliceStable(e, func(i, j int) bool { return e[i].U < e[j].U })
}

// stdSections are the ids of the section headings of a package page.
var stdSections = map[string]bool{"constants": true, "variables": true, "functions": true, "types": true, "bugs": true, "examples": true}
