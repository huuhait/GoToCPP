// TestConstValue checks how computed const values are written.
func TestConstValue(t *testing.T) {
	untypedRune := types.Typ[types.UntypedRune]
	untypedFloat := types.Typ[types.UntypedFloat]
	tests := []struct {
		v    constant.Value
		t    types.Type
		want string
	}{
		{constant.MakeInt64(65), untypedRune, `'A'`},
		{constant.MakeInt64(0xFFFD), untypedRune, `'\ufffd'`},
		{constant.MakeInt64(0x10FFFF), untypedRune, `'\U0010ffff'`},
		{constant.MakeInt64(-1), types.Typ[types.Int], `-1`},
		{constant.MakeUint64(1 << 63), types.Typ[types.Uint64], `9223372036854775808`},
		{constant.MakeString("a\"b"), types.Typ[types.String], `"a\"b"`},
		{constant.MakeBool(true), types.Typ[types.UntypedBool], `true`},
		{constant.MakeFloat64(2), untypedFloat, `2.0`},
		{constant.BinaryOp(constant.MakeInt64(1), token.QUO, constant.MakeInt64(3)), untypedFloat, `1.0 / 3`},
	}
	for _, tt := range tests {
		if got := constValue(tt.v, tt.t); got != tt.want {
			t.Errorf("constValue(%s, %s) = %s, want %s", tt.v.ExactString(), tt.t, got, tt.want)
		}
	}
}

// TestProgramsAgree type-checks small programs against the stubs and
// against Go's packages: both must give the same errors. The cases are
// selectors whose result depends on the depth of a promoted method, which
// the helpers keep as in Go (testing.T embeds common).
func TestProgramsAgree(t *testing.T) {
	st := generated(t)
	_, restore := useContext(genRoot)
	defer restore()
	programs := map[string]string{
		// L.Logf is shallower than T.common.Logf, so it wins.
		"shallower": `package p

import "testing"

type L struct{}

func (L) Logf(string, ...any) {}

type S struct {
	*testing.T
	L
}

func f(s S) { s.Logf("x") }
`,
		// Y.Z.Errorf and T.common.Errorf are at the same depth.
		"ambiguous": `package p

import "testing"

type Z struct{}

func (Z) Errorf(string, ...any) {}

type Y struct{ Z }

type S struct {
	*testing.T
	Y
}

func f(s S) { s.Errorf("x") }
`,
		// testing.T implements testing.TB, also its private method, and
		// nothing outside the package can.
		"tb": `package p

import "testing"

var _ testing.TB = (*testing.T)(nil)
var _ testing.TB = (*testing.B)(nil)
var _ testing.TB = (*testing.F)(nil)

type mine struct{ testing.TB }

var _ testing.TB = mine{}

type other struct{}

var _ testing.TB = other{}
`,
		// Selectors through os.File's and io.PipeReader's helpers.
		"files": `package p

import (
	"io"
	"os"
)

func f(r *io.PipeReader, w *io.PipeWriter, file *os.File) {
	_, _ = r.Read(nil)
	_ = w.Close()
	_ = file.Name()
	_ = r.pipe
	_ = file.file
}
`,
	}
	for _, name := range sortedKeys(programs) {
		t.Run(name, func(t *testing.T) {
			stubImp := &memImporter{t: t, fset: token.NewFileSet(), files: st.files, pkgs: make(map[string]*types.Package)}
			got := checkProgram(t, programs[name], stubImp)
			want := checkProgram(t, programs[name], importer.ForCompiler(token.NewFileSet(), "source", nil))
			if !slices.Equal(got, want) {
				t.Errorf("errors with the stubs:\n\t%s\nwith Go's packages:\n\t%s", strings.Join(got, "\n\t"), strings.Join(want, "\n\t"))
			}
			if name != "shallower" && len(want) == 0 {
				t.Errorf("Go reports no error; the case tests nothing")
			}
		})
	}
}

// checkProgram type-checks the file src with imp and returns its errors.
func checkProgram(t *testing.T, src string, imp types.Importer) []string {
	t.Helper()
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "p.go", src, 0)
	if err != nil {
		t.Fatal(err)
	}
	var errs []string
	conf := types.Config{GoVersion: "go1.25", Importer: imp, Error: func(err error) { errs = append(errs, err.Error()) }}
	_, _ = conf.Check("p", fset, []*ast.File{f}, nil)
	return errs
}
