// The tests need the Go tree that the stubs come from: the dev shell's
// GOROOT. They skip when there is no go command, and when its version is
// not the one in the stubs (then they would only find Go's changes).

var (
	genOnce sync.Once
	genRoot string
	genStub *stubs
	genErr  error
	genSkip string
)

// stdlibDir is the folder of the committed stubs.
const stdlibDir = "../../stdlib"

// committedVersion returns the Go version that the committed stubs come
// from, as their header says.
func committedVersion(t *testing.T) string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(stdlibDir, stubFile("fmt")))
	if err != nil {
		t.Fatal(err)
	}
	m := regexp.MustCompile(`(?m)^// Code generated by tools/stubgen from (go[0-9.]+)'s `).FindSubmatch(b)
	if m == nil {
		t.Fatalf("%s has no stubgen header", stubFile("fmt"))
	}
	return string(m[1])
}

// generated runs generate once, on the GOROOT of the go command.
func generated(t *testing.T) *stubs {
	t.Helper()
	want := committedVersion(t)
	genOnce.Do(func() {
		if _, err := exec.LookPath("go"); err != nil {
			genSkip = "no go command"
			return
		}
		b, err := exec.Command("go", "env", "GOROOT").Output()
		if err != nil {
			genErr = err
			return
		}
		genRoot = strings.TrimSpace(string(b))
		v, err := goVersion(genRoot)
		if err != nil {
			genSkip = fmt.Sprintf("no Go tree: %v", err)
			return
		}
		if v != want {
			genSkip = fmt.Sprintf("the go command is %s, the stubs come from %s (run the tests in the dev shell)", v, want)
			return
		}
		genStub, genErr = generate(genRoot)
	})
	if genSkip != "" {
		t.Skip(genSkip)
	}
	if genErr != nil {
		t.Fatal(genErr)
	}
	return genStub
}

// TestStubsUpToDate checks that the stubs in stdlib/ are what the tool
// writes now, and that stdlib/ holds no other generated stub.
func TestStubsUpToDate(t *testing.T) {
	st := generated(t)
	real := make(map[string]bool) // the real packages have no stub file (stubPackage.Real)
	for _, p := range packages {
		if p.Real {
			real[stubFile(p.Path)] = true
		}
	}
	for _, name := range sortedKeys(st.files) {
		if real[name] {
			// (the real package may have a file of the same name: it is not generated)
			if b, err := os.ReadFile(filepath.Join(stdlibDir, filepath.FromSlash(name))); err == nil && bytes.Contains(b, []byte("// Code generated by tools/stubgen")) {
				t.Errorf("stdlib/%s is a stub of a package that is real (stubPackage.Real): remove it", name)
			}
			continue
		}
		got, err := os.ReadFile(filepath.Join(stdlibDir, filepath.FromSlash(name)))
		if err != nil {
			t.Errorf("%v (run go run ./tools/stubgen)", err)
			continue
		}
		if !bytes.Equal(got, st.files[name]) {
			t.Errorf("stdlib/%s is not what tools/stubgen writes (run go run ./tools/stubgen)", name)
		}
	}
	err := filepath.WalkDir(stdlibDir, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(p, ".gp") {
			return err
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(stdlibDir, p)
		if bytes.Contains(b, []byte("// Code generated by tools/stubgen")) && st.files[filepath.ToSlash(rel)] == nil {
			t.Errorf("stdlib/%s is a stub of a package that is not in the tool's list", filepath.ToSlash(rel))
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
}

// TestPackageOrder checks that each package of the list comes after the
// packages that its stub imports.
func TestPackageOrder(t *testing.T) {
	st := generated(t)
	seen := make(map[string]bool)
	for _, p := range packages {
		f, err := parser.ParseFile(token.NewFileSet(), p.Path, st.files[stubFile(p.Path)], parser.ImportsOnly)
		if err != nil {
			t.Fatal(err)
		}
		for _, spec := range f.Imports {
			ip := strings.Trim(spec.Path.Value, `"`)
			if ip != "unsafe" && !seen[ip] {
				t.Errorf("%s imports %s, which comes later in the list", p.Path, ip)
			}
		}
		seen[p.Path] = true
	}
}

// memImporter type-checks the generated stubs from memory.
type memImporter struct {
	t     *testing.T
	fset  *token.FileSet
	files map[string][]byte
	pkgs  map[string]*types.Package
}

func (m *memImporter) Import(p string) (*types.Package, error) {
	if p == "unsafe" {
		return types.Unsafe, nil
	}
	if pkg := m.pkgs[p]; pkg != nil {
		return pkg, nil
	}
	src := m.files[stubFile(p)]
	if src == nil {
		return nil, fmt.Errorf("no stub for %s", p)
	}
	f, err := parser.ParseFile(m.fset, stubFile(p), src, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	var errs []error
	conf := types.Config{GoVersion: "go1.25", Importer: m, Error: func(err error) { errs = append(errs, err) }}
	pkg, _ := conf.Check(p, m.fset, []*ast.File{f}, nil)
	for _, err := range errs {
		m.t.Errorf("stub %s: %v", p, err)
	}
	m.pkgs[p] = pkg
	return pkg, nil
}

// TestStubsMatchGo type-checks the stubs and compares every declaration
// with Go's: each one must have the same type (and a const the same
// value), and each exported declaration of Go must be in the stub or in
// its list of what it leaves out.
func TestStubsMatchGo(t *testing.T) {
	st := generated(t)
	stubImp := &memImporter{t: t, fset: token.NewFileSet(), files: st.files, pkgs: make(map[string]*types.Package)}
	// The source importer reads build.Default (see useContext).
	_, restore := useContext(genRoot)
	defer restore()
	realImp := importer.ForCompiler(token.NewFileSet(), "source", nil)
	for _, p := range packages {
		t.Run(strings.ReplaceAll(p.Path, "/", "_"), func(t *testing.T) {
			stub, err := stubImp.Import(p.Path)
			if err != nil {
				t.Fatal(err)
			}
			real, err := realImp.Import(p.Path)
			if err != nil {
				t.Fatal(err)
			}
			left := make(map[string]bool)
			for _, name := range st.leftOut[p.Path] {
				left[name] = true
			}
			comparePackages(t, stub, real, left)
		})
	}
}

// realNotYet are the exported declarations of the stubs that a real package doesn't have yet,
// by "path.Name", with the step that adds them. Each is a promise: the entry goes away when the
// step lands.
var realNotYet = map[string]string{}

// TestRealPackagesMatchStub type-checks each real package of the list (stubPackage.Real: the
// .gp files of stdlib/<path>, ported from Go's with the parts that need reflectlite replaced by
// native functions) and compares its exported declarations with the stub, which
// TestStubsMatchGo has compared with Go's: the same names, types, consts and methods.
func TestRealPackagesMatchStub(t *testing.T) {
	st := generated(t)
	stubImp := &memImporter{t: t, fset: token.NewFileSet(), files: st.files, pkgs: make(map[string]*types.Package)}
	for _, p := range packages {
		if !p.Real {
			continue
		}
		t.Run(strings.ReplaceAll(p.Path, "/", "_"), func(t *testing.T) {
			if p.Differs != "" {
				t.Skip(p.Differs)
			}
			stub, err := stubImp.Import(p.Path)
			if err != nil {
				t.Fatal(err)
			}
			dir := filepath.Join(stdlibDir, filepath.FromSlash(p.Path))
			fset := token.NewFileSet()
			files, err := parseRealDir(fset, dir)
			if err != nil {
				t.Fatal(err)
			}
			imp := &realImporter{t: t, stubs: stubImp, fset: fset, pkgs: make(map[string]*types.Package)}
			conf := types.Config{GoVersion: "go1.25", Importer: imp, Error: func(err error) { t.Error(err) }}
			realPkg, _ := conf.Check(p.Path, fset, files, nil)
			if realPkg == nil {
				t.Fatal("not type-checked")
			}
			left := make(map[string]bool)
			for _, name := range st.leftOut[p.Path] {
				left[name] = true
			}
			c := &comparison{t: t, left: left, private: map[string]bool{}, realPkg: true}
			missing := make(map[string]bool)
			for _, name := range p.Missing {
				missing[name] = true
			}
			for _, name := range stub.Scope().Names() {
				if !token.IsExported(name) {
					continue
				}
				robj := realPkg.Scope().Lookup(name)
				if robj == nil && realNotYet[p.Path+"."+name] != "" {
					continue // not written yet, for the reason in the map
				}
				if robj == nil {
					if !p.Partial && !missing[name] {
						t.Errorf("%s is in the stub but not in the real package", name)
					}
					continue
				}
				if missing[name] {
					t.Errorf("%s is in Missing of %s but the real package has it: remove it from the list", name, p.Path)
					continue
				}
				c.compareObjects(robj, stub.Scope().Lookup(name))
			}
			for _, name := range realPkg.Scope().Names() {
				if token.IsExported(name) && stub.Scope().Lookup(name) == nil && !gocppAdditions[p.Path+"."+name] {
					t.Errorf("%s is in the real package but not in Go", name)
				}
			}
		})
	}
}

// parseRealDir parses the .gp files of the real package in dir that are built for linux/amd64.
func parseRealDir(fset *token.FileSet, dir string) ([]*ast.File, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var files []*ast.File
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".gp") {
			continue
		}
		src, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			return nil, err
		}
		if !linuxFile(e.Name(), src) {
			continue // a file of another system (time/zoneinfo_windows.gp)
		}
		f, err := parser.ParseFile(fset, e.Name(), src, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		files = append(files, f)
	}
	if len(files) == 0 {
		return nil, fmt.Errorf("no .gp files in %s", dir)
	}
	return files, nil
}

// realImporter imports what a real package imports: the stub of a package that has one, else the
// real package from stdlib/<path> (internal/bytealg, internal/reflectlite, math, ...: the packages
// of the standard library that have no stub because they are not in Go's public API list or were
// never stubbed), type-checked from its .gp files.
type realImporter struct {
	t     *testing.T
	stubs *memImporter
	fset  *token.FileSet
	pkgs  map[string]*types.Package
}

func (m *realImporter) Import(p string) (*types.Package, error) {
	if pkg := m.pkgs[p]; pkg != nil {
		return pkg, nil
	}
	if m.stubs.files[stubFile(p)] != nil || p == "unsafe" {
		return m.stubs.Import(p)
	}
	files, err := parseRealDir(m.fset, filepath.Join(stdlibDir, filepath.FromSlash(p)))
	if err != nil {
		return nil, fmt.Errorf("no stub and no real package for %s: %v", p, err)
	}
	conf := types.Config{GoVersion: "go1.25", Importer: m, Error: func(err error) { m.t.Errorf("real %s: %v", p, err) }}
	pkg, _ := conf.Check(p, m.fset, files, nil)
	m.pkgs[p] = pkg
	return pkg, nil
}

// linuxFile reports whether the .gp file name with the text src is built for linux/amd64: its name
// has no other system or architecture suffix, and its //go:build line (if any) holds.
func linuxFile(name string, src []byte) bool {
	base := strings.TrimSuffix(name, ".gp")
	// Go's rule for names: name_GOOS, name_GOARCH or name_GOOS_GOARCH (the system part of a double
	// suffix counts too: types_windows_amd64.gp is a Windows file, not a Linux one).
	parts := strings.Split(base, "_")
	otherOS := func(s string) bool {
		switch s {
		case "windows", "darwin", "plan9", "js", "wasip1", "freebsd", "netbsd", "openbsd", "aix", "android", "dragonfly", "illumos", "ios", "solaris", "hurd", "zos":
			return true
		}
		return false
	}
	otherArch := func(s string) bool {
		switch s {
		case "arm64", "arm", "386", "loong64", "mips", "mipsle", "mips64", "mips64le", "ppc64", "ppc64le", "riscv64", "s390x", "wasm", "sparc64":
			return true
		}
		return false
	}
	if n := len(parts); n >= 2 {
		last := parts[n-1]
		if otherOS(last) || otherArch(last) {
			return false
		}
		if last == "amd64" && n >= 3 && otherOS(parts[n-2]) {
			return false
		}
	}
	for _, line := range strings.Split(string(src), "\n") {
		if !constraint.IsGoBuild(line) {
			if strings.HasPrefix(line, "package ") {
				break
			}
			continue
		}
		expr, err := constraint.Parse(line)
		if err != nil {
			return false
		}
		return expr.Eval(func(tag string) bool {
			return tag == "linux" || tag == "unix" || tag == "amd64" || tag == "gc" || strings.HasPrefix(tag, "go1.")
		})
	}
	return true
}

// gocppAdditions are the exported names that gocpp's own packages have and Go's do not
// (docs/spec/language.md, D17).
var gocppAdditions = map[string]bool{
	"errors.Wrapf": true, // Phase 10: errors.Wrapf(&err, ...), the context of a ! error
}

// qualifier writes each package by its path, so that the type strings of
// the stub and of Go are the same when the types are.
func qualifier(p *types.Package) string { return p.Path() }

func typeString(t types.Type) string { return types.TypeString(t, qualifier) }

// A comparison compares a stub package with Go's.
type comparison struct {
	t    *testing.T
	left map[string]bool // what the stub leaves out (see pkgState.leftOut)

	// private holds the unexported method names of Go's exported
	// interfaces: the stub must have these methods too.
	private map[string]bool

	// realPkg: the left side is a real package (stubPackage.Real), whose structs may have unexported
	// fields of their own (the stub's have none): they are not compared.
	realPkg bool
}

// comparePackages compares the stub package stub with Go's package real.
func comparePackages(t *testing.T, stub, real *types.Package, left map[string]bool) {
	c := &comparison{t: t, left: left, private: make(map[string]bool)}
	for _, name := range real.Scope().Names() {
		if tn, ok := real.Scope().Lookup(name).(*types.TypeName); ok && tn.Exported() {
			if it, ok := tn.Type().Underlying().(*types.Interface); ok {
				for m := range it.Methods() {
					if !m.Exported() {
						c.private[m.Name()] = true
					}
				}
			}
		}
	}
	// The unexported types that the stub may declare: those that its
	// structs embed (the helpers, see findHelpers).
	helpers := make(map[string]bool)
	for _, name := range stub.Scope().Names() {
		tn, ok := stub.Scope().Lookup(name).(*types.TypeName)
		if !ok || tn.IsAlias() {
			continue
		}
		if st, ok := tn.Type().Underlying().(*types.Struct); ok {
			for f := range st.Fields() {
				if f.Embedded() && !f.Exported() {
					helpers[f.Name()] = true
				}
			}
		}
	}
	for _, name := range real.Scope().Names() {
		robj := real.Scope().Lookup(name)
		if !robj.Exported() {
			continue
		}
		sobj := stub.Scope().Lookup(name)
		if sobj == nil {
			if !left[name] {
				t.Errorf("%s is missing and not in the left-out list", name)
			}
			continue
		}
		if left[name] {
			t.Errorf("%s is in the stub and in the left-out list", name)
		}
		c.compareObjects(sobj, robj)
	}
	for _, name := range stub.Scope().Names() {
		robj := real.Scope().Lookup(name)
		if robj == nil {
			t.Errorf("%s is in the stub but not in Go", name)
			continue
		}
		if !token.IsExported(name) {
			if !helpers[name] {
				t.Errorf("the stub declares the unexported %s, which no struct embeds", name)
				continue
			}
			c.compareObjects(stub.Scope().Lookup(name), robj)
		}
	}
}

func (c *comparison) compareObjects(sobj, robj types.Object) {
	t := c.t
	name := sobj.Name()
	if fmt.Sprintf("%T", sobj) != fmt.Sprintf("%T", robj) {
		t.Errorf("%s is a %T in the stub, a %T in Go", name, sobj, robj)
		return
	}
	switch s := sobj.(type) {
	case *types.Const:
		r := robj.(*types.Const)
		if typeString(s.Type()) != typeString(r.Type()) || !constant.Compare(s.Val(), token.EQL, r.Val()) {
			t.Errorf("const %s is %s = %s in the stub, %s = %s in Go", name, typeString(s.Type()), s.Val().ExactString(), typeString(r.Type()), r.Val().ExactString())
		}
	case *types.Var, *types.Func:
		if a, b := typeString(sobj.Type()), typeString(robj.Type()); a != b {
			t.Errorf("%s is %s in the stub, %s in Go", name, a, b)
		}
	case *types.TypeName:
		c.compareTypes(s, robj.(*types.TypeName))
	}
}

func (c *comparison) compareTypes(s, r *types.TypeName) {
	t, left := c.t, c.left
	name := s.Name()
	if s.IsAlias() != r.IsAlias() {
		t.Errorf("type %s: alias %v in the stub, %v in Go", name, s.IsAlias(), r.IsAlias())
		return
	}
	if s.IsAlias() {
		if a, b := typeString(types.Unalias(s.Type())), typeString(types.Unalias(r.Type())); a != b {
			t.Errorf("type %s = %s in the stub, %s in Go", name, a, b)
		}
		return
	}
	sn, rn := s.Type().(*types.Named), r.Type().(*types.Named)
	if a, b := tparamsString(sn.TypeParams()), tparamsString(rn.TypeParams()); a != b {
		t.Errorf("type %s has the type parameters %s in the stub, %s in Go", name, a, b)
	}
	sst, sok := sn.Underlying().(*types.Struct)
	rst, rok := rn.Underlying().(*types.Struct)
	switch {
	case sok && rok:
		compareStructs(t, name, sst, rst, left, c.realPkg)
		if types.Comparable(sn) != types.Comparable(rn) {
			t.Errorf("type %s: comparable %v in the stub, %v in Go", name, types.Comparable(sn), types.Comparable(rn))
		}
	default:
		if a, b := typeString(sn.Underlying()), typeString(rn.Underlying()); a != b {
			t.Errorf("type %s is %s in the stub, %s in Go", name, a, b)
		}
	}
	// The method sets of T and *T.
	for _, ptr := range []bool{false, true} {
		var st, rt types.Type = sn, rn
		if ptr {
			st, rt = types.NewPointer(sn), types.NewPointer(rn)
		}
		sms, rms := types.NewMethodSet(st), types.NewMethodSet(rt)
		for sel := range rms.Methods() {
			m := sel.Obj()
			if !m.Exported() && !c.private[m.Name()] {
				continue
			}
			ssel := sms.Lookup(s.Pkg(), m.Name())
			if ssel == nil {
				if !left[name+"."+m.Name()] {
					t.Errorf("method %s.%s (pointer %v) is missing and not in the left-out list", name, m.Name(), ptr)
				}
				continue
			}
			if a, b := typeString(ssel.Obj().Type()), typeString(m.Type()); a != b {
				t.Errorf("method %s.%s is %s in the stub, %s in Go", name, m.Name(), a, b)
			}
		}
		for sel := range sms.Methods() {
			if c.realPkg && !sel.Obj().Exported() {
				continue
			}
			if rms.Lookup(r.Pkg(), sel.Obj().Name()) == nil {
				t.Errorf("method %s.%s (pointer %v) is in the stub but not in Go", name, sel.Obj().Name(), ptr)
			}
		}
	}
}

func tparamsString(l *types.TypeParamList) string {
	var parts []string
	for tp := range l.TypeParams() {
		parts = append(parts, tp.Obj().Name()+" "+typeString(tp.Constraint()))
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

// compareStructs compares the fields of the struct type name: the stub's
// fields, without the blank ones (and, in a real package, the unexported ones), are Go's exported and embedded fields, in
// the same order, without the left-out ones.
func compareStructs(t *testing.T, name string, s, r *types.Struct, left map[string]bool, ignorePrivate bool) {
	var want []string
	for f := range r.Fields() {
		if (f.Exported() || f.Embedded()) && !left[name+"."+f.Name()] {
			want = append(want, fmt.Sprintf("%s %s embedded=%v tag=%q", f.Name(), typeString(f.Type()), f.Embedded(), r.Tag(slices.Index(fieldsOf(r), f))))
		}
	}
	var got []string
	for i, f := range fieldsOf(s) {
		if f.Name() == "_" || (ignorePrivate && !f.Exported() && !f.Embedded()) {
			continue
		}
		if ignorePrivate && left[name+"."+f.Name()] {
			continue // a field the stub leaves out (unicode.CaseRange.Delta has an unexported type), but the real package has
		}
		got = append(got, fmt.Sprintf("%s %s embedded=%v tag=%q", f.Name(), typeString(f.Type()), f.Embedded(), s.Tag(i)))
	}
	if !slices.Equal(got, want) {
		t.Errorf("type %s has the fields\n\t%s\nin the stub, want\n\t%s", name, strings.Join(got, "\n\t"), strings.Join(want, "\n\t"))
	}
}

func fieldsOf(s *types.Struct) []*types.Var {
	return slices.Collect(s.Fields())
}

