package main

import (
	"fmt"
	"slices"
	"sort"
	"strings"

	"github.com/huuhait/gocpp/tools/gobench/benchdata"
)

// implTitle is the column title of an implementation.
func implTitle(impl string) string {
	if cxx, fl, ok := benchdata.SplitGocpp(impl); ok {
		return "gocpp " + cxx + " " + fl
	}
	switch impl {
	case benchdata.ImplGo:
		return "Go"
	case benchdata.ImplCppGxx:
		return "C++ g++"
	case benchdata.ImplCppClang:
		return "C++ clang++"
	}
	return impl
}

// gocppImpls returns the gocpp implementations that have a result in r, in table order.
func gocppImpls(r *benchdata.Report) []string {
	var out []string
	for _, x := range r.Results {
		if benchdata.IsGocpp(x.Impl) && !slices.Contains(out, x.Impl) {
			out = append(out, x.Impl)
		}
	}
	sort.SliceStable(out, func(i, j int) bool { return benchdata.ImplRank(out[i]) < benchdata.ImplRank(out[j]) })
	return out
}

// hasImpl reports whether r has a result of impl that is not just skipped.
func hasImpl(r *benchdata.Report, impl string) bool {
	for _, x := range r.Results {
		if x.Impl == impl && x.Status != benchdata.StatusSkipped {
			return true
		}
	}
	return false
}

// tableImpls returns the implementations that have a column in the per-program
// tables: Go, the gocpp builds that ran, the twins that ran.
func tableImpls(r *benchdata.Report) []string {
	out := []string{benchdata.ImplGo}
	for _, i := range gocppImpls(r) {
		if hasImpl(r, i) {
			out = append(out, i)
		}
	}
	for _, i := range []string{benchdata.ImplCppGxx, benchdata.ImplCppClang} {
		if hasImpl(r, i) {
			out = append(out, i)
		}
	}
	return out
}

func anyOptimized(impls []string) bool {
	for _, i := range impls {
		if benchdata.Optimized(i) {
			return true
		}
	}
	return false
}

func ratioStr(x float64) string {
	if x == 0 {
		return "-"
	}
	return fmt.Sprintf("%.2f", x)
}

// fmtMS formats nanoseconds as milliseconds with 3 significant digits.
func fmtMS(ns float64) string {
	ms := ns / 1e6
	switch {
	case ms >= 1000:
		return fmt.Sprintf("%.0f", ms)
	case ms >= 100:
		return fmt.Sprintf("%.0f", ms)
	case ms >= 10:
		return fmt.Sprintf("%.1f", ms)
	case ms >= 1:
		return fmt.Sprintf("%.2f", ms)
	}
	return fmt.Sprintf("%.3f", ms)
}

// timeCell is "median ±noise%" of a result, or why there is none.
func timeCell(r *benchdata.Result) string {
	if r == nil {
		return "-"
	}
	switch r.Status {
	case benchdata.StatusOK:
		st := r.WallStat()
		return fmt.Sprintf("%s ±%.0f%%", fmtMS(st.Median), st.RelNoise()*100)
	case benchdata.StatusSkipped:
		return "skipped"
	case benchdata.StatusMismatch:
		return "**MISMATCH**"
	default:
		return "**FAIL**"
	}
}

func medianOf(r *benchdata.Result) float64 {
	if r == nil || r.Status != benchdata.StatusOK {
		return 0
	}
	return r.WallStat().Median
}

func ratioCell(a, b float64) string {
	r := benchdata.Ratio(a, b)
	if r == 0 {
		return "-"
	}
	s := fmt.Sprintf("%.2f", r)
	if r > 2 {
		s = "**" + s + "**"
	}
	return s
}

// groupRatios returns the geometric mean of impl's median over ref's median
// for the programs of a category ("all": every program), the number of
// programs, and the worst single ratio with its program.
func groupRatios(r *benchdata.Report, group, impl, ref string, skip ...string) (geo float64, n int, worst float64, worstName string) {
	var rs []float64
	for _, p := range r.Programs() {
		if slices.Contains(skip, p) {
			continue
		}
		a, b := r.Find(p, impl), r.Find(p, ref)
		if a == nil || b == nil || (group != "all" && a.Category != group) {
			continue
		}
		x := benchdata.Ratio(medianOf(a), medianOf(b))
		if x == 0 {
			continue
		}
		rs = append(rs, x)
		if x > worst {
			worst, worstName = x, p
		}
	}
	geo, n = benchdata.GeoMean(rs)
	return
}

// Markdown renders a report as docs/benchmarks/runtime.md.
func Markdown(r *benchdata.Report, maxLoad float64) string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	w("<!-- Generated by `make bench` (tools/gobench). Do not edit by hand. -->\n\n")
	w("# Runtime benchmarks\n\n")
	w("gocpp against real Go and against idiomatic C++20 on the same programs (`bench/programs/`, one `.gp` file that also\n")
	w("runs as `.go`; `bench/cpp/` has the C++ twins of the compute kernels). Generated by `make bench` (tools/gobench);\n")
	w("how it measures and how the regression gate works is in [README.md](README.md). Every program's output is\n")
	w("compared across the implementations; a difference fails the run.\n\n")
	if r.Machine.LoadBefore[0] > maxLoad || r.Machine.LoadAfter[0] > maxLoad {
		w("> **Noisy run.** The load average was %.1f before and %.1f after the run (the limit for a quiet machine is %.0f), and the\n", r.Machine.LoadBefore[0], r.Machine.LoadAfter[0], maxLoad)
		w("> machine was shared. Ratios between implementations are more reliable than the times, because the runs of the\n")
		w("> implementations alternate, but nothing here is authoritative: the figures for the release come from a run on a quiet machine.\n\n")
	}
	w("## Machine\n\n| | |\n|---|---|\n")
	m := r.Machine
	w("| commit | %s%s |\n", r.Commit, map[bool]string{true: " (uncommitted changes)", false: ""}[r.Dirty])
	w("| date | %s |\n", r.Date)
	w("| cpu | %s, %d logical cores, %d GiB |\n", m.CPU, m.Cores, m.MemGiB)
	w("| os | %s |\n", m.OS)
	w("| go | %s |\n", m.Go)
	w("| g++ | %s |\n", m.Gxx)
	w("| clang++ | %s |\n", m.Clang)
	w("| gocpp | %s |\n", m.Gocpp)
	w("| load average (1, 5, 15 min) | %.1f %.1f %.1f before, %.1f %.1f %.1f after |\n", m.LoadBefore[0], m.LoadBefore[1], m.LoadBefore[2], m.LoadAfter[0], m.LoadAfter[1], m.LoadAfter[2])
	if m.Pinned != "" {
		w("| pinned to cpus | %s (taskset) |\n", m.Pinned)
	} else {
		w("| pinned to cpus | no |\n")
	}
	w("| setting | %s sizes, %d measured runs per implementation after %d warm-up run(s), medians; ±N%% is the median absolute deviation as a share of the median |\n", r.Size, r.Reps, r.Warmup)
	w("| setting | gocpp built in the flavors named in the columns (default: -O0 -g; O2: GOCPP_CXXFLAGS=\"-O2 -g0\"; release: build -release), the C++ twins with -O2, Go with its default optimizer |\n\n")

	impls := tableImpls(r)
	var gimpls, optimized []string
	for _, i := range impls {
		if benchdata.IsGocpp(i) {
			gimpls = append(gimpls, i)
			if benchdata.Optimized(i) && hasImpl(r, benchdata.CppTwin(i)) {
				optimized = append(optimized, i)
			}
		}
	}
	// The rows: the categories and "all", and the headline rows once more without the programs
	// that flatter gocpp (fib: the C++ optimizer unrolls and inlines the recursion, generic_minmax:
	// the loop folds away), so that the geometric mean cannot hide behind them.
	type row struct {
		label, group string
		skip         []string
	}
	var groups []row
	for _, c := range benchdata.Categories {
		groups = append(groups, row{c, c, nil})
		if c == "cpu" {
			groups = append(groups, row{"cpu without fib", "cpu", []string{"fib"}})
		}
	}
	groups = append(groups, row{"all", "all", nil}, row{"all without fib, generic_minmax", "all", []string{"fib", "generic_minmax"}})
	summary := func(title string, cols []string, ref func(string) string) {
		w("%s\n\n| group | programs |", title)
		for _, c := range cols {
			w(" %s |", implTitle(c))
		}
		w(" worst (optimized builds) |\n|---|--:|")
		for range cols {
			w("--:|")
		}
		w("---|\n")
		for _, g := range groups {
			n := 0
			cells := ""
			worst, worstName, worstImpl := 0.0, "", ""
			for _, c := range cols {
				geo, k, wr, wn := groupRatios(r, g.group, c, ref(c), g.skip...)
				n = max(n, k)
				cells += " " + ratioStr(geo) + " |"
				if wr > worst && (benchdata.Optimized(c) || !anyOptimized(cols)) { // the worst of the optimized builds

					worst, worstName, worstImpl = wr, wn, c
				}
			}
			if n == 0 {
				continue
			}
			wc := ""
			if worst > 0 {
				wc = fmt.Sprintf("%s %.2f (%s)", worstName, worst, implTitle(worstImpl))
			}
			w("| %s | %d |%s %s |\n", g.label, n, cells, wc)
		}
		w("\n")
	}
	w("## Summary\n\nGeometric mean of the time ratios (below 1.00 means gocpp is faster). The goals of Phase 15: the CPU geometric\n")
	w("mean against Go at or below 1.00, and no benchmark more than 2.00 times slower than Go (marked in bold below). The\n")
	w("flavors: `default` is what `gocpp build` does today (-O0 -g), `O2` is GOCPP_CXXFLAGS=\"-O2 -g0\", `release` is\n")
	w("`gocpp build -release` (-O2 and LTO; absent until gocpp has it). Only the optimized flavors are compared with the\n")
	w("optimized C++ twins.\n\n")
	summary("gocpp over Go:", gimpls, func(string) string { return benchdata.ImplGo })
	if len(optimized) > 0 {
		summary("gocpp over the C++ twin built with the same compiler (programs that have a twin):", optimized, benchdata.CppTwin)
	}

	for _, cat := range benchdata.Categories {
		var progs []string
		for _, p := range r.Programs() {
			for _, x := range r.Results {
				if x.Program == p && x.Category == cat {
					progs = append(progs, p)
					break
				}
			}
		}
		if len(progs) == 0 {
			continue
		}
		w("## %s\n\nWall time in ms (median ±MAD), then the ratios to Go (gocpp columns) and to the twin (optimized gocpp columns).\n\n", cat)
		w("| benchmark |")
		for _, i := range impls {
			w(" %s |", implTitle(i))
		}
		for _, i := range gimpls {
			w(" %s / Go |", strings.TrimPrefix(implTitle(i), "gocpp "))
		}
		for _, i := range optimized {
			w(" %s / C++ |", strings.TrimPrefix(implTitle(i), "gocpp "))
		}
		w("\n|---|")
		for n := len(impls) + len(gimpls) + len(optimized); n > 0; n-- {
			w("--:|")
		}
		w("\n")
		for _, p := range progs {
			w("| %s |", p)
			for _, i := range impls {
				w(" %s |", timeCell(r.Find(p, i)))
			}
			goT := medianOf(r.Find(p, benchdata.ImplGo))
			for _, i := range gimpls {
				w(" %s |", ratioCell(medianOf(r.Find(p, i)), goT))
			}
			for _, i := range optimized {
				w(" %s |", ratioCell(medianOf(r.Find(p, i)), medianOf(r.Find(p, benchdata.CppTwin(i)))))
			}
			w("\n")
		}
		w("\n")
	}

	// Memory.
	w("## Memory\n\nPeak resident set in MiB (median of the runs; the VmHWM of the process), and gocpp over Go.\n\n")
	w("| benchmark |")
	for _, i := range impls {
		w(" %s |", implTitle(i))
	}
	for _, i := range gimpls {
		w(" %s / Go |", strings.TrimPrefix(implTitle(i), "gocpp "))
	}
	w("\n|---|")
	for n := len(impls) + len(gimpls); n > 0; n-- {
		w("--:|")
	}
	w("\n")
	rss := func(x *benchdata.Result) float64 {
		if x == nil || x.Status != benchdata.StatusOK {
			return 0
		}
		return x.RSSStat().Median
	}
	cellMiB := func(v float64) string {
		if v == 0 {
			return "-"
		}
		return fmt.Sprintf("%.1f", v/1024)
	}
	rssRatios := map[string][]float64{}
	for _, p := range r.Programs() {
		g := rss(r.Find(p, benchdata.ImplGo))
		w("| %s |", p)
		for _, i := range impls {
			w(" %s |", cellMiB(rss(r.Find(p, i))))
		}
		for _, i := range gimpls {
			x := benchdata.Ratio(rss(r.Find(p, i)), g)
			rssRatios[i] = append(rssRatios[i], x)
			w(" %s |", ratioCell(rss(r.Find(p, i)), g))
		}
		w("\n")
	}
	w("\nGeometric mean of gocpp over Go:")
	for _, i := range gimpls {
		if gm, n := benchdata.GeoMean(rssRatios[i]); n > 0 {
			w(" %s %.2f (%d programs);", strings.TrimPrefix(implTitle(i), "gocpp "), gm, n)
		}
	}
	w("\n\n")

	// Binary sizes.
	w("## Binary size\n\nStripped size in KiB (the raw size is in the JSON file).\n\n")
	w("| benchmark |")
	for _, i := range impls {
		w(" %s |", implTitle(i))
	}
	w("\n|---|")
	for range impls {
		w("--:|")
	}
	w("\n")
	size := func(x *benchdata.Result) string {
		if x == nil || x.Status != benchdata.StatusOK {
			return "-"
		}
		s := x.Stripped
		if s == 0 {
			s = x.BinSize
		}
		return fmt.Sprintf("%.0f", float64(s)/1024)
	}
	for _, p := range r.Programs() {
		w("| %s |", p)
		for _, i := range impls {
			w(" %s |", size(r.Find(p, i)))
		}
		w("\n")
	}
	w("\n")

	// Compile time.
	if len(r.Compile) > 0 {
		w("## Compile time\n\nWall time of the build command in seconds (median of the runs). `cold`: empty caches (gocpp: its runtime is built too;\n")
		w("Go: the standard library is built too); `warm`: the runtime or standard library is cached and one source file of the\n")
		w("program changed; `noop`: nothing changed. `default` is gocpp's current build (-O0 -g), `O2` GOCPP_CXXFLAGS=\"-O2 -g0\", `release` is `build -release`.\n\n")
		w("| program | mode | flavor | Go | gocpp g++ | gocpp clang++ | g++/Go | clang++/Go |\n|---|---|---|--:|--:|--:|--:|--:|\n")
		type key struct{ name, mode, flavor string }
		seen := map[key]bool{}
		var keys []key
		for _, c := range r.Compile {
			if c.Impl == benchdata.ImplGo {
				continue // Go has no flavors: its time is in every row of the gocpp flavors
			}
			k := key{c.Name, c.Mode, c.Flavor}
			if !seen[k] {
				seen[k] = true
				keys = append(keys, k)
			}
		}
		modeRank := map[string]int{"cold": 0, "warm": 1, "noop": 2}
		sort.SliceStable(keys, func(i, j int) bool {
			if keys[i].name != keys[j].name {
				return keys[i].name < keys[j].name
			}
			if modeRank[keys[i].mode] != modeRank[keys[j].mode] {
				return modeRank[keys[i].mode] < modeRank[keys[j].mode]
			}
			return flavorRank(keys[i].flavor) < flavorRank(keys[j].flavor)
		})
		find := func(name, impl, mode, flavor string) *benchdata.Compile {
			for i := range r.Compile {
				c := &r.Compile[i]
				if c.Name == name && c.Impl == impl && c.Mode == mode && (c.Flavor == flavor || impl == benchdata.ImplGo) {
					return c
				}
			}
			return nil
		}
		sec := func(c *benchdata.Compile) (string, float64) {
			if c == nil {
				return "-", 0
			}
			if c.Status == benchdata.StatusSkipped {
				return "skipped", 0
			}
			if c.Status != benchdata.StatusOK {
				return "**FAIL**", 0
			}
			m := benchdata.Median(c.WallNS)
			return fmt.Sprintf("%.2f", m/1e9), m
		}
		for _, k := range keys {
			flavor := k.flavor
			gs, gm := sec(find(k.name, benchdata.ImplGo, k.mode, ""))
			var cells [2]string
			var ms [2]float64
			for i, impl := range []string{"gocpp-g++", "gocpp-clang++"} {
				cells[i], ms[i] = sec(find(k.name, impl, k.mode, flavor))
			}
			w("| %s | %s | %s | %s | %s | %s | %s | %s |\n", k.name, k.mode, flavor, gs, cells[0], cells[1], ratioCell(ms[0], gm), ratioCell(ms[1], gm))
		}
		w("\n")
	}

	// Programs that do not build yet, and failures.
	var notYet, failed, retried []string
	seenNote := map[string]bool{}
	type flavorSkips struct {
		note     string
		impls    []string
		programs map[string]bool
	}
	var flavorSkipList []*flavorSkips
	for _, x := range r.Results {
		if x.Note == "" || x.Note == "no C++ twin" || (x.Status == benchdata.StatusOK && !strings.HasPrefix(x.Note, "built on try")) {
			continue
		}
		switch {
		case x.Status == benchdata.StatusSkipped && strings.HasPrefix(x.Note, "needs "):
			// the whole program is skipped with the same reason in every implementation: one line
			k := x.Program + "\x00" + x.Note
			if !seenNote[k] {
				seenNote[k] = true
				notYet = append(notYet, fmt.Sprintf("- %s/%s: %s", x.Category, x.Program, x.Note))
			}
		case x.Status == benchdata.StatusSkipped:
			// a flavor gocpp cannot build yet: one line for all the programs
			g := &flavorSkips{note: x.Note}
			for _, s := range flavorSkipList {
				if s.note == x.Note {
					g = s
				}
			}
			if g.programs == nil {
				g.programs = map[string]bool{}
				flavorSkipList = append(flavorSkipList, g)
			}
			g.programs[x.Program] = true
			if !slices.Contains(g.impls, implTitle(x.Impl)) {
				g.impls = append(g.impls, implTitle(x.Impl))
			}
		case x.Status == benchdata.StatusOK && x.Note != "":
			retried = append(retried, fmt.Sprintf("- %s/%s [%s]: %s", x.Category, x.Program, implTitle(x.Impl), x.Note))
		default:
			failed = append(failed, fmt.Sprintf("- %s/%s [%s]: %s: %s", x.Category, x.Program, implTitle(x.Impl), x.Status, x.Note))
		}
	}
	for _, g := range flavorSkipList {
		notYet = append(notYet, fmt.Sprintf("- %s (%d programs): %s", strings.Join(g.impls, ", "), len(g.programs), g.note))
	}
	if len(notYet) > 0 {
		w("## Does not build yet\n\nThese programs are in the suite and are skipped, in every implementation, until gocpp can build them\n")
		w("(their header says what they need). They start to be measured when it can.\n\n%s\n\n", strings.Join(notYet, "\n"))
	}
	if len(retried) > 0 {
		w("## Builds that needed a second try\n\nA gocpp build that failed was tried again once (`-build-retries`); these succeeded the second time. The failures\n")
		w("are not about the programs (they build alone): concurrent `gocpp build`s in one cache, as the runner does, fail at random.\n\n%s\n\n", strings.Join(retried, "\n"))
	}
	if len(failed) > 0 {
		w("## Failed\n\n%s\n\n", strings.Join(failed, "\n"))
	}
	return b.String()
}

// flavorRank orders the flavors of the compile table: default, O2, release.
func flavorRank(f string) int { return slices.Index(benchdata.Flavors, f) }
