# Writes runtime/test/math_data.hpp: results of real Go (amd64) for the C++ unit test of gocpp/math.hpp:
# Exp with and without the FMA path (GODEBUG=cpu.fma=off), Log (including subnormal arguments, where Go is
# "wrong"), and FMA with NaN operands. Run in the dev shell: python3 cxxdata.py
import os, subprocess, tempfile, shutil

GO = r'''
package main

import (
	"fmt"
	"math"
)

var state uint64 = 0x243F6A8885A308D3

func next() uint64 {
	state += 0x9E3779B97F4A7C15
	z := state
	z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9
	z = (z ^ (z >> 27)) * 0x94D049BB133111EB
	return z ^ (z >> 31)
}

func inputs() []float64 {
	xs := []float64{0, math.Copysign(0, -1), 1, -1, 0.5, 1e-300, 5e-324, 709.782712893384, 709.7827128933841, 710, -745.1332191019411, -745.2, -746, -1e10, 1e10,
		math.Inf(1), math.Inf(-1), math.NaN(), math.Float64frombits(0x7ff0000000000001), math.Float64frombits(0xfff8000000000001), 0.7071067811865476, 0.7071067811865475, 1.4142135623730951,
		2.2250738585072014e-308, 2.225073858507201e-308, 1e-310, 1.7976931348623157e308, 2, 4, 1 << 62}
	// the comparison of Log's mantissa with sqrt(2)/2, at the exact value and its neighbours, at several exponents
	for _, e := range []int{-3, -1, 0, 1, 2, 10, -1000} {
		h := math.Ldexp(0.7071067811865476, e)
		xs = append(xs, h, math.Nextafter(h, 0), math.Nextafter(h, math.Inf(1)), math.Ldexp(1.4142135623730951, e), math.Ldexp(1.414213562373095, e))
	}
	for i := 0; i < 160; i++ {
		switch i % 4 {
		case 0:
			xs = append(xs, (float64(next()>>11)/(1<<53)*2-1)*800)
		case 1:
			xs = append(xs, math.Float64frombits(next()))
		case 2:
			xs = append(xs, float64(next()>>11)/(1<<53)*4)
		default:
			xs = append(xs, math.Float64frombits(next()>>12))
		}
	}
	return xs
}

func main() {
	xs := inputs()
	fmt.Println("// Generated by tools/mathcorpus/cxxdata.py from real Go; do not edit.")
	fmt.Println("struct F1 { uint64_t x, want; };")
	fmt.Println("static const F1 exp_cases[] = {")
	for _, x := range xs {
		fmt.Printf("    {0x%016x, 0x%016x},\n", math.Float64bits(x), math.Float64bits(math.Exp(x)))
	}
	fmt.Println("};")
	fmt.Println("static const F1 log_cases[] = {")
	for _, x := range xs {
		fmt.Printf("    {0x%016x, 0x%016x},\n", math.Float64bits(x), math.Float64bits(math.Log(x)))
	}
	fmt.Println("};")
	fmt.Println("struct F3 { uint64_t x, y, z, want; };")
	fmt.Println("static const F3 fma_cases[] = {")
	nans := []uint64{0x7ff0000000000001, 0x7ff8000000000000, 0xfff8000000000000, 0x7ff4479c6aacc07a, 0xfff8000000000001, 0x3ff0000000000000, 0x7ff0000000000000, 0}
	for _, a := range nans {
		for _, b := range nans {
			for _, c := range nans {
				fmt.Printf("    {0x%016x, 0x%016x, 0x%016x, 0x%016x},\n", a, b, c, math.Float64bits(math.FMA(math.Float64frombits(a), math.Float64frombits(b), math.Float64frombits(c))))
			}
		}
	}
	for i := 0; i < 150; i++ {
		a, b, c := math.Float64frombits(next()>>2|0x3000000000000000), math.Float64frombits(next()>>2|0x3000000000000000), math.Float64frombits(next()>>2|0x3000000000000000)
		fmt.Printf("    {0x%016x, 0x%016x, 0x%016x, 0x%016x},\n", math.Float64bits(a), math.Float64bits(b), math.Float64bits(c), math.Float64bits(math.FMA(a, b, c)))
	}
	fmt.Println("};")
}
'''

def run(env):
    d = tempfile.mkdtemp()
    open(os.path.join(d, "main.go"), "w").write(GO)
    open(os.path.join(d, "go.mod"), "w").write("module d\ngo 1.25\n")
    e = dict(os.environ); e.update(env)
    r = subprocess.run(["go", "run", "main.go"], cwd=d, capture_output=True, env=e, check=True)
    shutil.rmtree(d)
    return r.stdout.decode()

fma_on = run({})
fma_off = run({"GODEBUG": "cpu.fma=off"})
def rename(txt, suffix):
    return txt.replace("exp_cases", "exp_cases_" + suffix)
on_lines = fma_on.split("\n")
# the exp table of the FMA run and of the other run; the rest (log, fma) is the same in both
def section(txt, name):
    i = txt.index("static const F1 %s[] = {" % name)
    j = txt.index("};", i) + 3
    return txt[i:j]
out = on_lines[0] + "\n// clang-format off\nstruct F1 { uint64_t x, want; };\nstruct F3 { uint64_t x, y, z, want; };\n"
out += section(fma_on, "exp_cases").replace("exp_cases", "exp_fma_cases") + "\n"
out += section(fma_off, "exp_cases").replace("exp_cases", "exp_nofma_cases") + "\n"
out += section(fma_on, "log_cases") + "\n"
i = fma_on.index("static const F3 fma_cases[] = {")
out += fma_on[i:] + "// clang-format on\n"
dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "runtime", "test", "math_data.hpp")
open(dst, "w").write(out)
print("wrote", dst, len(out))
