// The list mode: for each requested package, the files that would be taken,
// the standard packages it imports (the closure), and what blocks the port.
// The steps that port packages (9.2 shims, 9.4 tier 1, 9.11 tier 2) read it
// for the order of their work.

// A ListEntry is one package of the closure.
type ListEntry struct {
	Pkg      string
	Boundary *Boundary // the package is not ported: who provides it
	Missing  bool      // not in the tree (a vendored package, or none)
	Err      error     // the port failed (no files for the target)
	Res      *Result
	Deps     []string // standard imports, sorted, without unsafe
	Blocks   []string // what blocks the port, in words
	Notes    []string // unsafe uses and the like: things to know, not blockers
	Reach    []string // the packages that are not ported, directly or through imports
}

// blockCategory maps a finding to the words of the blocker table.
func blockCategory(kind string) string {
	switch kind {
	case "asm":
		return "asm"
	case "linkname-pull", "linkname-var", "linkname-syntax", "native-todo":
		return "linkname"
	case "embed":
		return "go:embed"
	case "cgo":
		return "cgo"
	}
	return kind
}

// ListResult is the whole closure.
type ListResult struct {
	Roots   []string
	Order   []string // the ported packages of the closure, dependencies first
	Entries map[string]*ListEntry
}

// List computes the closure of the packages.
func (p *Porter) List(roots []string, optsFor func(pkg string) Options) (*ListResult, error) {
	lr := &ListResult{Roots: roots, Entries: make(map[string]*ListEntry)}
	var visit func(pkg string) error
	onStack := make(map[string]bool)
	visit = func(pkg string) error {
		if _, done := lr.Entries[pkg]; done {
			return nil
		}
		e := &ListEntry{Pkg: pkg}
		lr.Entries[pkg] = e
		if b, ok := p.Cfg.Boundary[pkg]; ok {
			e.Boundary = &b
			return nil
		}
		if pkg == "unsafe" || pkg == "C" {
			return nil
		}
		if !packageExists(p.Root, pkg) {
			e.Missing = true
			return nil
		}
		res, err := p.Port(pkg, optsFor(pkg))
		if err != nil {
			e.Err = err
			return nil
		}
		e.Res = res
		for _, imp := range res.Imports {
			if imp == "unsafe" || imp == "C" {
				continue
			}
			e.Deps = append(e.Deps, imp)
		}
		onStack[pkg] = true
		for _, dep := range e.Deps {
			if onStack[dep] {
				return fmt.Errorf("import cycle: %s imports %s", pkg, dep)
			}
			if err := visit(dep); err != nil {
				return err
			}
		}
		onStack[pkg] = false
		lr.Order = append(lr.Order, pkg)
		for _, f := range res.Findings {
			if f.Blocker {
				if c := blockCategory(f.Kind); !slices.Contains(e.Blocks, c) {
					e.Blocks = append(e.Blocks, c)
				}
			}
		}
		var hooks []string
		for _, dep := range e.Deps {
			if d := lr.Entries[dep]; d != nil && d.Boundary != nil {
				hooks = append(hooks, dep)
			}
		}
		if len(hooks) > 0 {
			e.Blocks = append(e.Blocks, "needs "+strings.Join(hooks, ", "))
		}
		for _, f := range res.Findings {
			if f.Kind == "unsafe" || f.Kind == "reflect" {
				if !slices.Contains(e.Notes, f.Kind) {
					e.Notes = append(e.Notes, f.Kind)
				}
			}
		}
		return nil
	}
	for _, r := range roots {
		if err := visit(r); err != nil {
			return nil, err
		}
	}
	for _, pkg := range lr.Order { // dependencies first
		e := lr.Entries[pkg]
		reach := make(map[string]bool)
		for _, dep := range e.Deps {
			d := lr.Entries[dep]
			if d.Res == nil {
				reach[dep] = true
				continue
			}
			for _, r := range d.Reach {
				reach[r] = true
			}
		}
		e.Reach = sortedKeys(reach)
	}
	return lr, nil
}

// stateOf says what stdlib/ has of a package now: "ported", "hand-written",
// "stub" (a Phase 01 declaration stub) or "absent".
func stateOf(out string, index map[string]string, pkg string) string {
	if _, ok := index[pkg]; ok {
		return "ported"
	}
	entries, err := os.ReadDir(pkgDir(out, pkg))
	if err != nil {
		return "absent"
	}
	for _, e := range entries {
		if filepath.Ext(e.Name()) != ".gp" {
			continue
		}
		b, err := os.ReadFile(filepath.Join(pkgDir(out, pkg), e.Name()))
		if err == nil && strings.Contains(string(b[:min(len(b), 400)]), "Code generated by tools/stubgen") {
			return "stub"
		}
		return "hand-written"
	}
	return "absent"
}

// WriteText prints the closure as text. out, when not empty, is the folder
// of stdlib/ for the "now" column.
func (lr *ListResult) WriteText(w io.Writer, out string) {
	index, _ := readIndex(out)
	for _, pkg := range lr.Order {
		e := lr.Entries[pkg]
		now := ""
		if out != "" {
			now = "  [stdlib: " + stateOf(out, index, pkg) + "]"
		}
		fmt.Fprintf(w, "%s%s\n", pkg, now)
		if e.Err != nil {
			fmt.Fprintf(w, "    error: %v\n", e.Err)
			continue
		}
		var files []string
		for _, f := range e.Res.Files {
			files = append(files, f.From)
		}
		fmt.Fprintf(w, "    files:    %s\n", strings.Join(files, " "))
		if len(e.Res.Skipped) > 0 {
			var sk []string
			for _, s := range e.Res.Skipped {
				sk = append(sk, s.File)
			}
			fmt.Fprintf(w, "    skipped:  %s\n", strings.Join(sk, " "))
		}
		fmt.Fprintf(w, "    imports:  %s\n", orNone(e.Deps))
		fmt.Fprintf(w, "    blocks:   %s\n", orNone(e.Blocks))
		fmt.Fprintf(w, "    needs:    %s\n", orNone(e.Reach))
		if len(e.Notes) > 0 {
			fmt.Fprintf(w, "    notes:    %s\n", strings.Join(e.Notes, ", "))
		}
	}
	fmt.Fprintln(w)
	fmt.Fprintln(w, "provided another way (not ported):")
	for _, pkg := range lr.sortedLeaves() {
		e := lr.Entries[pkg]
		switch {
		case e.Boundary != nil:
			fmt.Fprintf(w, "    %-26s %-8s %s\n", pkg, e.Boundary.Owner, e.Boundary.What)
		case e.Missing:
			fmt.Fprintf(w, "    %-26s %-8s %s\n", pkg, "-", "not in the Go tree (vendored or unknown)")
		}
	}
}

func orNone(l []string) string {
	if len(l) == 0 {
		return "none"
	}
	return strings.Join(l, ", ")
}

// sortedLeaves returns the entries that are not ported, sorted.
func (lr *ListResult) sortedLeaves() []string {
	var out []string
	for pkg, e := range lr.Entries {
		if e.Boundary != nil || e.Missing {
			out = append(out, pkg)
		}
	}
	slices.Sort(out)
	return out
}

// WriteMarkdown prints the closure as the markdown of docs/guides: a table
// in port order, and the list of what is provided another way. It has no
// column for the state of stdlib/, so the text only changes when Go's source
// or the tool's tables change.
func (lr *ListResult) WriteMarkdown(w io.Writer, pin Pin, opts Options) {
	fmt.Fprintf(w, "Source: %s, target `%s`, GOARCH `%s`, tags %s. Roots: %s.\n\n",
		pin.Version, strings.Join(opts.OS, ","), opts.Arch, codeList(opts.Tags), codeList(lr.Roots))
	fmt.Fprintln(w, "### Packages to port, dependencies first")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "| # | Package | Files | Imports | Blocks the port | Needs, through imports too (not ported) | Notes |")
	fmt.Fprintln(w, "|--:|---|--:|---|---|---|---|")
	for i, pkg := range lr.Order {
		e := lr.Entries[pkg]
		if e.Err != nil {
			fmt.Fprintf(w, "| %d | `%s` | | | error: %s | | |\n", i+1, pkg, strings.ReplaceAll(e.Err.Error(), "|", "/"))
			continue
		}
		fmt.Fprintf(w, "| %d | `%s` | %d | %s | %s | %s | %s |\n", i+1, pkg, len(e.Res.Files), mdCodeList(e.Deps), mdBlocks(e.Blocks), mdCodeList(e.Reach), strings.Join(e.Notes, ", "))
	}
	fmt.Fprintln(w)
	fmt.Fprintln(w, "### Provided another way (not ported)")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "| Package | Owner | What | Needed by |")
	fmt.Fprintln(w, "|---|---|---|---|")
	for _, pkg := range lr.sortedLeaves() {
		e := lr.Entries[pkg]
		var users []string
		for _, u := range lr.Order {
			if slices.Contains(lr.Entries[u].Deps, pkg) {
				users = append(users, u)
			}
		}
		owner, what := "-", "not in the Go tree (vendored or unknown)"
		if e.Boundary != nil {
			owner, what = e.Boundary.Owner, e.Boundary.What
		}
		fmt.Fprintf(w, "| `%s` | %s | %s | %s |\n", pkg, owner, what, mdCodeList(users))
	}
}

func mdCodeList(l []string) string {
	if len(l) == 0 {
		return "none"
	}
	var q []string
	for _, s := range l {
		q = append(q, "`"+s+"`")
	}
	return strings.Join(q, ", ")
}

func mdBlocks(l []string) string {
	if len(l) == 0 {
		return "none"
	}
	return strings.Join(l, "; ")
}
