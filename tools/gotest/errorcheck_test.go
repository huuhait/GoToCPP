func check(t *testing.T, out string, src string) []Mismatch {
	t.Helper()
	ms, err := ErrorCheck(out, false, []SrcFile{{Short: "x.go", Full: "/abs/x.go", Src: src}})
	if err != nil {
		t.Fatal(err)
	}
	return ms
}

func kinds(ms []Mismatch) string {
	var k []string
	for _, m := range ms {
		k = append(k, m.Kind)
	}
	return strings.Join(k, ",")
}

func TestErrorCheckBasics(t *testing.T) {
	src := "package p\n\nvar a int = \"s\" // ERROR \"cannot use\"\nvar b = c // ERROR \"undefined: c\"\n"
	if ms := check(t, "x.go:3: cannot use \"s\" as int\nx.go:4: undefined: c\n", src); len(ms) != 0 {
		t.Errorf("good output: %v", ms)
	}
	if got := kinds(check(t, "x.go:3: cannot use \"s\" as int\n", src)); got != "missing" {
		t.Errorf("missing error: %q", got)
	}
	if got := kinds(check(t, "x.go:3: cannot use \"s\" as int\nx.go:4: something else\n", src)); got != "nomatch,unmatched" {
		t.Errorf("wrong text: %q", got)
	}
	if got := kinds(check(t, "x.go:3: cannot use \"s\" as int\nx.go:4: undefined: c\nx.go:5: extra\n", src)); got != "unmatched" {
		t.Errorf("extra error: %q", got)
	}
}

func TestErrorCheckMultipleErrorsPerLine(t *testing.T) {
	src := "package p\n\nvar a, b int = 1, \"s\" // ERROR \"first\" \"second\"\n"
	if ms := check(t, "x.go:3: the first one\nx.go:3: the second one\n", src); len(ms) != 0 {
		t.Errorf("two errors, two regexps: %v", ms)
	}
	if got := kinds(check(t, "x.go:3: the first one\n", src)); got != "missing" {
		t.Errorf("one of two: %q", got)
	}
	// two comments for one error line each need their own message
	if got := kinds(check(t, "x.go:3: first and second\n", src)); got != "missing" {
		t.Errorf("one message for two regexps: %q", got)
	}
}

func TestErrorCheckLineRefs(t *testing.T) {
	src := "package p\n\nfunc f() {} // ERROR \"redeclared.*LINE+1\"\nfunc f() {} // ERROR \"other declaration.*LINE-1\"\n"
	out := "x.go:3: f redeclared, see x.go:4\nx.go:4: other declaration of f, see x.go:3\n"
	if ms := check(t, out, src); len(ms) != 0 {
		t.Errorf("LINE+1/LINE-1: %v", ms)
	}
	src2 := "package p\n\nvar x = y // ERROR \"at LINE\"\n"
	if ms := check(t, "x.go:3: at x.go:3\n", src2); len(ms) != 0 {
		t.Errorf("LINE: %v", ms)
	}
}

