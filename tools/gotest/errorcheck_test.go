func TestMatchPrefix(t *testing.T) {
	for _, c := range []struct {
		s, p string
		want bool
	}{
		{"x.go:3: m", "x.go:3", true},
		{"dir/x.go:3: m", "x.go:3", true},
		{"x.go:33: m", "x.go:3", false},
		{"x.go:3[x.go:4]: m", "x.go:3", true},
		{"nothing", "x.go:3", false},
	} {
		if got := matchPrefix(c.s, c.p); got != c.want {
			t.Errorf("matchPrefix(%q, %q) = %v", c.s, c.p, got)
		}
	}
}

func TestNormalizeGocpp(t *testing.T) {
	out := "# command-line-arguments\n./x.gp:6:6: declared and not used: x\n/tmp/w/x.gp:7:20: undefined: y\n./x.gp:8:1: warning: careful\nsomething else\n"
	got := NormalizeGocpp(out, map[string]string{"x.gp": "x.go"})
	want := "x.go:6: declared and not used: x\nx.go:7: undefined: y\nsomething else\n\n"
	if got != want {
		t.Errorf("got %q, want %q", got, want)
	}
}

func TestReplacePrefix(t *testing.T) {
	if got := replacePrefix("/a/x.go:3: see /a/x.go:4\n\t/a/x.go:5", "/a/x.go", "x.go"); got != "x.go:3: see x.go:4\n\tx.go:5" {
		t.Errorf("got %q", got)
	}
	if got := replacePrefix("abc", "", "x"); got != "abc" {
		t.Errorf("empty old: %q", got)
	}
}

func TestNormalizeKeepsContinuationLines(t *testing.T) {
	// gocpp prints the related position of an error on a tab-indented line;
	// it stays a continuation of the error, not an error of its own
	out := "# command-line-arguments\n./x.gp:4:5: x redeclared in this block\n\t./x.gp:3:5: other declaration of x\n"
	norm := NormalizeGocpp(out, map[string]string{"x.gp": "x.go"})
	if want := "x.go:4: x redeclared in this block\n\t./x.gp:3:5: other declaration of x\n\n"; norm != want {
		t.Errorf("normalized:\n%q\nwant\n%q", norm, want)
	}
	src := "package p\n\nvar x int\nvar x string // ERROR \"redeclared\"\n"
	ms, err := ErrorCheck(norm, false, []SrcFile{{Short: "x.go", Full: "x.go", Src: src}})
	if err != nil || len(ms) != 0 {
		t.Errorf("%v %v", ms, err)
	}
}
