package main

import (
	"errors"
	"fmt"
	"go/build/constraint"
	"strconv"
	"strings"
	"unicode"
)

// A Recipe is the first-line directive of a test of Go's test/ folder: what
// to do with the file and with which flags. The syntax and the meaning are
// those of Go's test runner (cmd/internal/testdir), described in
// docs/guides/conformance.md.
type Recipe struct {
	Action    string   // run, errorcheck, compile, ... (the first word)
	Flags     []string // flags for the Go compiler (-gcflags ... are kept as written)
	Args      []string // arguments for the program
	WantError bool     // errorcheck and friends: the compile must fail
	Single    bool     // -s: every file of a directory is a package of its own
	Timeout   int      // -t N: seconds, 0 for the default
	GoExp     []string // -goexperiment X
	GoDebug   []string // -godebug X
	ModVers   string   // -gomodversion
}

// actions lists the directive words, with whether a compile error is
// expected by default.
var actions = map[string]bool{
	"compile": false, "compiledir": false, "build": false, "builddir": false,
	"buildrundir": false, "run": false, "buildrun": false, "runoutput": false,
	"rundir": false, "runindir": false, "asmcheck": false,
	"errorcheckandrundir": false,
	"errorcheck":          true, "errorcheckdir": true, "errorcheckoutput": true,
	"errorcheckwithauto": true,
	"skip":               false,
}

// directiveLine returns the recipe text of a test file: the first non-empty
// line that is not a build constraint, without its "//".
func directiveLine(src string) string {
	for rest := src; rest != ""; {
		var line string
		line, rest, _ = strings.Cut(rest, "\n")
		if constraint.IsGoBuild(line) || constraint.IsPlusBuild(line) {
			continue
		}
		if a := strings.TrimSpace(strings.TrimPrefix(line, "//")); a != "" {
			return a
		}
	}
	return ""
}

// ParseRecipe reads the directive of a test file.
func ParseRecipe(src string) (Recipe, error) {
	var r Recipe
	text := directiveLine(src)
	if text == "" {
		return r, errors.New("execution recipe not found")
	}
	f, err := splitQuoted(text)
	if err != nil {
		return r, fmt.Errorf("invalid test recipe: %v", err)
	}
	r.Action = f[0]
	args := f[1:]
	want, ok := actions[r.Action]
	if !ok {
		return r, fmt.Errorf("unknown pattern: %q", r.Action)
	}
	r.WantError = want
	if r.Action == "errorcheckwithauto" {
		r.Action = "errorcheck" // the auto lines (<autogenerated>) are matched by the compiler only
		r.Flags = append(r.Flags, "-auto")
	}
	for len(args) > 0 && strings.HasPrefix(args[0], "-") {
		switch args[0] {
		case "-1":
			r.WantError = true
		case "-0":
			r.WantError = false
		case "-s":
			r.Single = true
		case "-t", "-goexperiment", "-godebug", "-gomodversion":
			name := args[0]
			if len(args) < 2 {
				return r, fmt.Errorf("%s needs an argument", name)
			}
			args = args[1:]
			switch name {
			case "-t":
				n, err := strconv.Atoi(args[0])
				if err != nil {
					return r, fmt.Errorf("need number of seconds for -t timeout, got %s instead", args[0])
				}
				r.Timeout = n
			case "-goexperiment":
				r.GoExp = append(r.GoExp, args[0])
			case "-godebug":
				r.GoDebug = append(r.GoDebug, args[0])
			case "-gomodversion":
				r.ModVers = args[0]
			}
		default:
			r.Flags = append(r.Flags, args[0])
		}
		args = args[1:]
	}
	r.Args = args
	return r, nil
}

// splitQuoted splits s around white space, with quotes and backslash
// escapes (single and double quotes), like go/build does for its flags. An
// unclosed quote is an error.
func splitQuoted(s string) ([]string, error) {
	var args []string
	arg := make([]rune, len(s))
	escaped, quoted := false, false
	quote := rune(0)
	i := 0
	for _, r := range s {
		switch {
		case escaped:
			escaped = false
		case r == '\\':
			escaped = true
			continue
		case quote != 0:
			if r == quote {
				quote = 0
				continue
			}
		case r == '"' || r == '\'':
			quoted = true
			quote = r
			continue
		case unicode.IsSpace(r):
			if quoted || i > 0 {
				quoted = false
				args = append(args, string(arg[:i]))
				i = 0
			}
			continue
		}
		arg[i] = r
		i++
	}
	if quoted || i > 0 {
		args = append(args, string(arg[:i]))
	}
	if quote != 0 {
		return args, errors.New("unclosed quote")
	}
	if escaped {
		return args, errors.New("unfinished escaping")
	}
	return args, nil
}

// Target is the machine the tests are for: the build tags that hold when a
// test says "//go:build ...".
type Target struct {
	GOOS, GOARCH string
	Minor        int // Go 1.<Minor>: the release tags go1.1 .. go1.<Minor> hold
}

// matchTag is the tag test of Go's test runner: the release tags, GOOS,
// GOARCH, "gc" and "test_run". cgo is off (gocpp has no cgo; D2), and no
// goexperiment holds.
func (t Target) matchTag(name string) bool {
	if name == "" {
		return false
	}
	for _, c := range name {
		if !unicode.IsLetter(c) && !unicode.IsDigit(c) && c != '_' && c != '.' {
			return false
		}
	}
	if rest, ok := strings.CutPrefix(name, "go1."); ok {
		n, err := strconv.Atoi(rest)
		return err == nil && n >= 1 && n <= t.Minor
	}
	switch name {
	case t.GOOS, t.GOARCH, "gc", "test_run":
		return true
	}
	return false
}

// shouldTest looks for build constraints in the header of a test file (the
// lines before the package clause) and reports whether the target runs it;
// why is the constraint that excludes it.
func (t Target) shouldTest(src string) (ok bool, why string) {
	header, _, found := strings.Cut(src, "\npackage")
	if !found {
		header = directiveLine(src) // some files are intentionally malformed
	}
	for _, line := range strings.Split(header, "\n") {
		if strings.HasPrefix(line, "package ") {
			break
		}
		if expr, err := constraint.Parse(line); err == nil {
			if !expr.Eval(t.matchTag) {
				return false, line
			}
		}
	}
	return true, ""
}
