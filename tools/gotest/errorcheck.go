package main

import (
	"fmt"
	"regexp"
	"strconv"
	"strings"
)

// The errorcheck matcher follows the rules of Go's test runner
// (cmd/internal/testdir, "errorCheck"): a line of a source file that should
// give an error has a comment "// ERROR "regexp"" (more than one quoted
// regexp for more than one error; "LINE", "LINE+n" and "LINE-n" in a regexp
// stand for "file:line"); the compiler's output must have, for each
// regexp, an error on that line that matches it, and no error that no
// comment wants. A line with "////" is a disabled comment.

var (
	errRx       = regexp.MustCompile(`// (?:GC_)?ERROR (.*)`)
	errAutoRx   = regexp.MustCompile(`// (?:GC_)?ERRORAUTO (.*)`)
	errQuotesRx = regexp.MustCompile(`"([^"]*)"`)
	lineRx      = regexp.MustCompile(`LINE(([+-])(\d+))?`)
)

// A Want is one expected error of a source file.
type Want struct {
	File   string // the short file name
	Line   int
	ReStr  string // after the LINE substitution
	Re     *regexp.Regexp
	Prefix string // "file:line"
	Auto   bool   // matches an <autogenerated> position
}

// A SrcFile is a test source with the name the compiler prints for it.
type SrcFile struct {
	Short string // the name in the comments' "file:line" (a.go)
	Full  string // a name that the output may use for it instead (replaced by Short)
	Src   string
}

// WantedErrors returns the expected errors of a source.
func WantedErrors(src, short string) ([]Want, error) {
	var out []Want
	cache := map[string]*regexp.Regexp{}
	for i, line := range strings.Split(src, "\n") {
		lineNum := i + 1
		if strings.Contains(line, "////") {
			continue
		}
		auto := false
		m := errAutoRx.FindStringSubmatch(line)
		if m != nil {
			auto = true
		} else {
			m = errRx.FindStringSubmatch(line)
		}
		if m == nil {
			continue
		}
		quoted := errQuotesRx.FindAllStringSubmatch(m[1], -1)
		if quoted == nil {
			return nil, fmt.Errorf("%s:%d: invalid errchk line: %s", short, lineNum, line)
		}
		for _, q := range quoted {
			rx := lineRx.ReplaceAllStringFunc(q[1], func(s string) string {
				n := lineNum
				if strings.HasPrefix(s, "LINE+") {
					d, _ := strconv.Atoi(s[5:])
					n += d
				} else if strings.HasPrefix(s, "LINE-") {
					d, _ := strconv.Atoi(s[5:])
					n -= d
				}
				return fmt.Sprintf("%s:%d", short, n)
			})
			re := cache[rx]
			if re == nil {
				var err error
				re, err = regexp.Compile(rx)
				if err != nil {
					return nil, fmt.Errorf("%s:%d: invalid regexp \"%s\" in ERROR line: %v", short, lineNum, rx, err)
				}
				cache[rx] = re
			}
			out = append(out, Want{File: short, Line: lineNum, ReStr: rx, Re: re,
				Prefix: fmt.Sprintf("%s:%d", short, lineNum), Auto: auto})
		}
	}
	return out, nil
}

// SplitOutput splits compiler output into one string per error. An error
// message continues on lines that start with a tab; lines of the go tool
// ("go tool ...", "# package") and blank lines are dropped, and
// <autogenerated> lines too unless wantAuto.
func SplitOutput(out string, wantAuto bool) []string {
	var res []string
	for _, line := range strings.Split(out, "\n") {
		line = strings.TrimSuffix(line, "\r")
		switch {
		case strings.HasPrefix(line, "\t") && len(res) > 0:
			res[len(res)-1] += "\n" + line
		case strings.HasPrefix(line, "go tool"), strings.HasPrefix(line, "#"),
			!wantAuto && strings.HasPrefix(line, "<autogenerated>"):
		case strings.TrimSpace(line) != "":
			res = append(res, line)
		}
	}
	return res
}

// matchPrefix reports whether s is of the form ^(.*/)?prefix(:|[): the file
// name and the line, followed by ":" or "[", possibly after a folder name.
func matchPrefix(s, prefix string) bool {
	i := strings.Index(s, ":")
	if i < 0 {
		return false
	}
	j := strings.LastIndex(s[:i], "/")
	s = s[j+1:]
	if len(s) <= len(prefix) || s[:len(prefix)] != prefix {
		return false
	}
	return s[len(prefix)] == '[' || s[len(prefix)] == ':'
}

func partitionStrings(prefix string, strs []string) (matched, unmatched []string) {
	for _, s := range strs {
		if matchPrefix(s, prefix) {
			matched = append(matched, s)
		} else {
			unmatched = append(unmatched, s)
		}
	}
	return
}

// replacePrefix replaces old by new where old follows a space, a tab or a
// newline, or starts the string (a file name in a message).
func replacePrefix(s, old, new string) string {
	if old == "" || !strings.Contains(s, old) {
		return s
	}
	s = strings.ReplaceAll(s, " "+old, " "+new)
	s = strings.ReplaceAll(s, "\n"+old, "\n"+new)
	s = strings.ReplaceAll(s, "\n\t"+old, "\n\t"+new)
	if strings.HasPrefix(s, old) {
		s = new + s[len(old):]
	}
	return s
}

// A Mismatch is one difference between the wanted and the reported errors.
type Mismatch struct {
	Kind string // missing, nomatch, unmatched
	File string
	Line int
	Want string   // the regexp (missing, nomatch)
	Got  []string // the messages on that line (nomatch) or the unmatched error (unmatched)
}

func (m Mismatch) String() string {
	switch m.Kind {
	case "missing":
		return fmt.Sprintf("%s:%d: missing error %q", m.File, m.Line, m.Want)
	case "nomatch":
		return fmt.Sprintf("%s:%d: no match for %#q in:\n\t%s", m.File, m.Line, m.Want, strings.Join(m.Got, "\n\t"))
	}
	return "unmatched error: " + strings.Join(m.Got, "\n")
}

// ErrorCheck compares the compiler's output with the ERROR comments of the
// sources and returns the differences (none when the test passes).
func ErrorCheck(output string, wantAuto bool, files []SrcFile) ([]Mismatch, error) {
	out := SplitOutput(output, wantAuto)
	for i := range out {
		for _, f := range files {
			out[i] = replacePrefix(out[i], f.Full, f.Short)
		}
	}
	var want []Want
	for _, f := range files {
		w, err := WantedErrors(f.Src, f.Short)
		if err != nil {
			return nil, err
		}
		want = append(want, w...)
	}
	var ms []Mismatch
	for _, we := range want {
		var msgs []string
		if we.Auto {
			msgs, out = partitionStrings("<autogenerated>", out)
		} else {
			msgs, out = partitionStrings(we.Prefix, out)
		}
		if len(msgs) == 0 {
			ms = append(ms, Mismatch{Kind: "missing", File: we.File, Line: we.Line, Want: we.ReStr})
			continue
		}
		matched := false
		n := len(out)
		for _, msg := range msgs {
			// "file:line: message": match the message only, so that a file name
			// can't match by accident
			text := msg
			if _, suffix, ok := strings.Cut(text, " "); ok {
				text = suffix
			}
			if we.Re.MatchString(text) {
				matched = true
			} else {
				out = append(out, msg)
			}
		}
		if !matched {
			ms = append(ms, Mismatch{Kind: "nomatch", File: we.File, Line: we.Line, Want: we.ReStr, Got: append([]string(nil), out[n:]...)})
		}
	}
	// errors about other files (a generic function instantiated from another
	// package) are not ours
	var local []string
outer:
	for _, e := range out {
		for _, f := range files {
			if strings.HasPrefix(e, f.Full+":") || strings.HasPrefix(e, f.Short+":") {
				local = append(local, e)
				continue outer
			}
		}
	}
	for _, e := range local {
		ms = append(ms, Mismatch{Kind: "unmatched", Got: []string{e}})
	}
	return ms, nil
}

var gocppErrRx = regexp.MustCompile(`^(\S.*?\.gp):(\d+)(?::(\d+))?: (.*)$`)

// NormalizeGocpp turns the output of "gocpp check" into the shape of gc's
// errorcheck output ("file.go:LINE: message", no column): the file names of
// names (gocpp's .gp names to Go's .go names, by base name) are replaced,
// warnings and the "# package" lines are dropped.
func NormalizeGocpp(out string, names map[string]string) string {
	var b strings.Builder
	for _, line := range strings.Split(out, "\n") {
		line = strings.TrimSuffix(line, "\r")
		if strings.HasPrefix(line, "#") {
			continue
		}
		if m := gocppErrRx.FindStringSubmatch(line); m != nil {
			file := m[1]
			if i := strings.LastIndexAny(file, `/\`); i >= 0 {
				file = file[i+1:]
			}
			if g, ok := names[file]; ok {
				file = g
			}
			msg := m[4]
			if strings.HasPrefix(msg, "warning: ") {
				continue
			}
			fmt.Fprintf(&b, "%s:%s: %s\n", file, m[2], msg)
			continue
		}
		b.WriteString(line)
		b.WriteByte('\n')
	}
	return b.String()
}
