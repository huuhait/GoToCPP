package main

import (
	"fmt"
	"math/rand/v2"
	"sort"
	"strconv"
	"strings"
)

// Case is one line of main: c(ID, <expr>).
type Case struct {
	ID   int
	Expr string // the Go expression of type string
	Vals []int  // indexes into the catalog of the values it uses
	Verb string // the first verb, for the clusters
	Fn   string // Sprintf, Sprint, ...
	Desc string // the format and the operand descriptions
}

// Program is the generated program number Index of a seed.
type Program struct {
	Seed  uint64
	Index int
	Cases []Case
	Vals  []Val // the catalog and the random values of this program (the indexes of Case.Vals)
}

// Gen makes the programs. The catalog is shared and read only.
type Gen struct {
	Vals  []Val
	Class map[string][]int
	Extra []int // indexes of the random values of a program
}

func NewGen() *Gen {
	vs := catalog()
	return &Gen{Vals: vs, Class: classOf(vs)}
}

// Program makes program index of the seed with n cases; the same arguments make the same program.
func (g *Gen) Program(seed uint64, index, n int) *Program {
	r := rand.New(rand.NewPCG(seed, uint64(index)*0x9e3779b97f4a7c15+1))
	p := &Program{Seed: seed, Index: index}
	g = g.withExtras(r)
	p.Vals = g.Vals
	for i := 0; i < n; i++ {
		cs := g.makeCase(r)
		cs.ID = i + 1
		p.Cases = append(p.Cases, cs)
	}
	return p
}

// Source returns the Go (and gocpp) source of the program with only the given cases (all when nil).
func (g *Gen) Source(p *Program, only map[int]bool) string {
	var cases []Case
	for _, c := range p.Cases {
		if only == nil || only[c.ID] {
			cases = append(cases, c)
		}
	}
	used := map[int]bool{}
	for _, c := range cases {
		for _, v := range c.Vals {
			used[v] = true
		}
	}
	var idx []int
	for i := range used {
		idx = append(idx, i)
	}
	sort.Ints(idx)
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by tools/fmtdiff (seed %d, program %d); DO NOT EDIT.\n", p.Seed, p.Index)
	b.WriteString(prelude)
	b.WriteString("\n")
	for _, i := range idx {
		if p.Vals[i].Decl != "" {
			b.WriteString(declLine(p.Vals[i]) + "\n")
		}
	}
	b.WriteString("\nfunc main() {\n")
	for _, c := range cases {
		fmt.Fprintf(&b, "\tc(%d, %s)\n", c.ID, c.Expr)
	}
	b.WriteString("}\n")
	return b.String()
}

func pick[T any](r *rand.Rand, xs []T) T { return xs[r.IntN(len(xs))] }

// weighted picks by weights.
func weighted(r *rand.Rand, ws []wv) string {
	t := 0
	for _, w := range ws {
		t += w.w
	}
	x := r.IntN(t)
	for _, w := range ws {
		if x < w.w {
			return w.v
		}
		x -= w.w
	}
	return ws[0].v
}

type wv struct {
	v string
	w int
}

