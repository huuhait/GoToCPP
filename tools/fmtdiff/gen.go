var anyVerbs = []string{"v", "d", "s", "q", "x", "X", "t", "c", "U", "e", "f", "g", "b", "o", "O", "T", "p", "w", "z", "!", "y", "i", "k"}

var widths = []string{"", "", "", "", "0", "1", "2", "3", "5", "8", "12", "20", "*"}
var precs = []string{"", "", "", "", ".", ".0", ".1", ".2", ".3", ".5", ".10", ".*"}

func (g *Gen) pickVal(r *rand.Rand, class string) int {
	if class == "" && len(g.Extra) > 0 && r.IntN(100) < 25 {
		return pick(r, g.Extra)
	}
	if class == "" {
		// any class, weighted by the number of classes (not values) so the small classes show up
		ks := make([]string, 0, len(g.Class))
		for k := range g.Class {
			if k != "err" {
				ks = append(ks, k)
			}
		}
		sort.Strings(ks)
		class = pick(r, ks)
	}
	return pick(r, g.Class[class])
}

// pickNonT picks a value whose address is not printed by some verb: for formats where the verb
// that meets a value is not the one chosen for it (explicit indexes, missing arguments).
func (g *Gen) pickNonT(r *rand.Rand) int {
	for {
		if vi := g.pickVal(r, ""); !g.Vals[vi].TOnly && !g.Vals[vi].PtrIn {
			return vi
		}
	}
}

func (g *Gen) classVerb(r *rand.Rand, class string) string {
	if r.IntN(100) < 12 {
		if class == "err" {
			return pick(r, []string{"v", "s", "q", "x", "X", "z", "w", "T"})
		}
		return pick(r, anyVerbs)
	}
	ws, ok := verbsByClass[class]
	if !ok {
		return pick(r, anyVerbs)
	}
	return weighted(r, ws)
}

func (g *Gen) flags(r *rand.Rand, comp bool) string {
	var f []byte
	switch x := r.IntN(100); {
	case x < 45:
	case x < 65:
		f = append(f, pick(r, []byte("+-# 0")))
	case x < 85:
		f = append(f, pick(r, []byte("+-# 0")), pick(r, []byte("+-# 0")))
	default:
		for i := 0; i < 3+r.IntN(3); i++ {
			f = append(f, pick(r, []byte("+-# 0")))
		}
	}
	if comp && len(f) == 0 && r.IntN(100) < 35 {
		f = append(f, pick(r, []byte("+#")))
	}
	return string(f)
}

// spec is one verb with its operands.
type spec struct {
	text string
	ops  []string // operands consumed, in order
	vals []int
	verb string
}

func (g *Gen) intOp(r *rand.Rand) string {
	return pick(r, []string{"0", "1", "3", "5", "8", "12", "-4", "-1", "20", "int8(6)", "uint8(7)"})
}

func (g *Gen) verbSpec(r *rand.Rand, forcedVal int, multi bool) spec {
	var s spec
	forbidIdx := false
	vi := forcedVal
	if vi < 0 {
		vi = g.pickVal(r, "")
	}
	val := g.Vals[vi]
	verb := g.classVerb(r, val.Class)
	if val.TOnly {
		verb = "T"
	}
	if val.Class == "err" {
		verb = "w"
		if r.IntN(4) == 0 {
			verb = g.classVerb(r, "err")
		}
	}
	if val.PtrIn && !strings.Contains("vsqxXT", verb) {
		verb = pick(r, []string{"v", "s", "q", "x", "X", "T"})
	}
	if val.TOnly || val.PtrIn || verb == "p" {
		forbidIdx = true // an explicit index could aim another verb at a pointer, or %p at one
	}
	if verb == "p" && (multi || g.addrLike(val)) {
		verb = "v" // the address of a non-nil pointer, slice or map is not the same on every run
	}
	var b strings.Builder
	b.WriteByte('%')
	flags := g.flags(r, val.Comp)
	if val.PtrIn && verb == "v" {
		flags = strings.ReplaceAll(flags, "#", "") // %#v prints the address
	}
	b.WriteString(flags)
	nargs := 0
	// explicit argument index, rare
	idx := ""
	if r.IntN(100) < 8 && !forbidIdx {
		idx = "[" + pick(r, []string{"1", "2", "3", "0", "9", "x", ""}) + "]"
	}
	w := pick(r, widths)
	if w == "*" {
		s.ops = append(s.ops, g.starOp(r))
		nargs++
	}
	b.WriteString(w)
	pr := pick(r, precs)
	if pr == ".*" {
		s.ops = append(s.ops, g.starOp(r))
		nargs++
	}
	b.WriteString(pr)
	b.WriteString(idx)
	b.WriteString(verb)
	s.text = b.String()
	s.ops = append(s.ops, val.Op)
	s.vals = []int{vi}
	s.verb = verb
	return s
}

func (g *Gen) starOp(r *rand.Rand) string {
	if r.IntN(100) < 8 {
		return pick(r, []string{`"x"`, "1.5", "nil", "true"}) // BADWIDTH / BADPREC
	}
	return g.intOp(r)
}

var literals = []string{"", "", "", "|", " ", "x", "<", ">", " = ", "%%", "\\n", "é", "[", "]", ", "}

var adversarial = []string{
	"%", "%%", "%5%", "%-5%", "%z", "%!", "%!d", "%[0]d", "%[1]", "%[1", "%[a]d", "%[2]d", "%[1]d %[1]d", "%[3]*d", "%*d", "%.*d", "%*.*d", "%d %d %d", "%-", "%+", "%5", "%.",
	"%.3", "%0-5d", "%-05d", "%+-d", "%++d", "%--d", "%00d", "%  d", "%#+ -0d", "%[2]*[1]d", "%[1]*d", "%.[2]d", "%*[2]d", "%[1]*[1]d", "%d%", "%d%%", "%%%d", "%v%", "%s %", "%[5]v %d", "%99999999999999d", "%.99999999999d",
	"%1000000d", "%.1000s", "%v %[1]T %[1]v", "%T", "%T %T", "%v", "% d", "%+d", "%x", "% x", "%#x", "% #x", "%X", "%#X", "%+q", "%#q", "%#+q", "% q", "%#v", "%+v", "%#+v", "%s", "%q", "%c", "%U", "%#U", "%+U", "%08.3f", "%-8.3f|", "%+.3e", "%#g", "%#.0f", "%# x", "%010s", "%-010s|", "%.0s", "%.1q", "%5.1v",
}

func (g *Gen) makeCase(r *rand.Rand) Case {
	var c Case
	mode := r.IntN(100)
	switch {
	case mode < 62:
		s := g.verbSpec(r, -1, false)
		c = g.buildFmt(r, "Sprintf", []spec{s}, nil, "")
	case mode < 74:
		n := 2 + r.IntN(2)
		var ss []spec
		var lits []string
		for i := 0; i < n; i++ {
			ss = append(ss, g.verbSpec(r, g.pickNonT(r), true))
			lits = append(lits, pick(r, literals))
		}
		c = g.buildFmt(r, "Sprintf", ss, lits, "")
	case mode < 84:
		// adversarial format with random operands
		f := pick(r, adversarial)
		n := r.IntN(4)
		var ops []string
		var vals []int
		for i := 0; i < n; i++ {
			vi := g.pickVal(r, "")
			if r.IntN(3) == 0 {
				ops = append(ops, g.intOp(r))
			} else {
				ops = append(ops, g.Vals[vi].Op)
				vals = append(vals, vi)
			}
		}
		// a non-nil pointer to a scalar or a pointer in a non-%v verb prints an address: the format
		// of the list has no pointer values here (they are replaced)
		ops, vals = g.safeOps(r, ops, vals)
		c = Case{Fn: "Sprintf", Verb: f, Expr: "fmt.Sprintf(" + strconv.Quote(f) + commaJoin(ops) + ")", Vals: vals, Desc: f}
	case mode < 90:
		n := 1 + r.IntN(3)
		var ops []string
		var vals []int
		for i := 0; i < n; i++ {
			vi := g.pickVal(r, "")
			ops = append(ops, g.Vals[vi].Op)
			vals = append(vals, vi)
		}
		ops, vals = g.safeOpsAll(ops, vals)
		fn := pick(r, []string{"Sprint", "Sprintln", "Sprint", "Sprintln", "Append", "Appendln"})
		e := "fmt." + fn + "(" + strings.TrimPrefix(commaJoin(ops), ", ") + ")"
		switch fn {
		case "Append", "Appendln":
			e = "string(fmt." + fn + `([]byte("pre:")` + commaJoin(ops) + "))"
		}
		c = Case{Fn: fn, Verb: "-", Expr: e, Vals: vals, Desc: fn}
	case mode < 92:
		// Fprintf, Fprint and Fprintln to a writer that fails after some bytes
		lim := pick(r, []string{"0", "3", "5", "100"})
		s := g.verbSpec(r, -1, false)
		switch r.IntN(3) {
		case 0:
			c = g.buildFmt(r, "Fprintf", []spec{s}, nil, lim)
		default:
			ops := append([]string(nil), s.ops...)
			fn := pick(r, []string{"Fprint", "Fprintln"})
			vals := s.vals
			if r.IntN(2) == 0 {
				vi := g.pickNonT(r)
				ops = append(ops, g.Vals[vi].Op)
				vals = append(vals, vi)
			}
			ops, vals = g.safeOps(r, ops, vals)
			c = Case{Fn: fn, Verb: "-", Vals: vals, Desc: fn,
				Expr: "func() string { l := &lim{left: " + lim + "}; n, err := fmt." + fn + "(l" + commaJoin(ops) + "); return fp(l, n, err) }()"}
		}
	case mode < 94:
		// Appendf
		s := g.verbSpec(r, -1, false)
		c = g.buildFmt(r, "Appendf", []spec{s}, nil, "")
	default:
		// Errorf with %w
		n := 1 + r.IntN(2)
		var ss []spec
		var lits []string
		for i := 0; i < n; i++ {
			vi := pick(r, g.Class["err"])
			if r.IntN(4) == 0 {
				vi = g.pickNonT(r)
			}
			ss = append(ss, g.verbSpec(r, vi, true))
			lits = append(lits, pick(r, []string{"x ", "wrap: ", ": "}))
		}
		c = g.buildFmt(r, "Errorf", ss, lits, "")
	}
	return c
}

// safeOps replaces the operands that would print an address.
func (g *Gen) safeOps(r *rand.Rand, ops []string, vals []int) ([]string, []int) {
	out := make([]string, len(ops))
	copy(out, ops)
	var nv []int
	for _, vi := range vals {
		if !g.deterministic(vi) {
			for i := range out {
				if out[i] == g.Vals[vi].Op {
					out[i] = "5"
				}
			}
			continue
		}
		nv = append(nv, vi)
	}
	return out, nv
}

func (g *Gen) safeOpsAll(ops []string, vals []int) ([]string, []int) {
	return g.safeOps(nil, ops, vals)
}

// deterministic reports whether any format of the value is the same on every run.
func (g *Gen) deterministic(vi int) bool { return !g.Vals[vi].TOnly && !g.Vals[vi].PtrIn }

// addrLike reports whether %p of the value prints an address (a non-nil pointer, slice, map, ...).
func (g *Gen) addrLike(v Val) bool {
	switch v.Class {
	case "comp", "ptr", "bytes", "iface", "meth", "nil", "err":
		return v.Init != "" && !strings.HasSuffix(v.Init, "nil")
	}
	return false
}

func commaJoin(ops []string) string {
	var b strings.Builder
	for _, o := range ops {
		b.WriteString(", " + o)
	}
	return b.String()
}

func (g *Gen) buildFmt(r *rand.Rand, fn string, ss []spec, lits []string, lim string) Case {
	var f strings.Builder
	var ops []string
	var vals []int
	var verbs []string
	f.WriteString(pick(r, []string{"", "", "", ">", "v="}))
	for i, s := range ss {
		f.WriteString(s.text)
		ops = append(ops, s.ops...)
		vals = append(vals, s.vals...)
		verbs = append(verbs, s.verb)
		if lits != nil {
			f.WriteString(strings.ReplaceAll(lits[i], "%", "%%"))
		}
	}
	f.WriteString(pick(r, []string{"", "", "", "<"}))
	// missing or extra arguments
	switch x := r.IntN(100); {
	case x < 5 && len(ops) > 0:
		ops = ops[:len(ops)-1]
	case x < 9:
		ops = append(ops, pick(r, []string{"1", `"extra"`, "nil", "2.5"}))
	}
	format := f.String()
	var e string
	switch fn {
	case "Sprintf":
		e = "fmt.Sprintf(" + strconv.Quote(format) + commaJoin(ops) + ")"
	case "Appendf":
		e = "string(fmt.Appendf([]byte(\"pre:\"), " + strconv.Quote(format) + commaJoin(ops) + "))"
	case "Fprintf":
		e = "func() string { l := &lim{left: " + lim + "}; n, err := fmt.Fprintf(l, " + strconv.Quote(format) + commaJoin(ops) + "); return fp(l, n, err) }()"
	case "Errorf":
		e = "ef(fmt.Errorf(" + strconv.Quote(format) + commaJoin(ops) + "))"
	}
	return Case{Fn: fn, Verb: strings.Join(verbs, " "), Expr: e, Vals: vals, Desc: format}
}

// caseVals returns the values that the case uses.
func (p *Program) caseVals(c Case) []Val {
	var vs []Val
	for _, vi := range c.Vals {
		vs = append(vs, p.Vals[vi])
	}
	return vs
}
