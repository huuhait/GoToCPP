// The twin of ../main.gp: the same program with every macro expanded by hand
// into the Go code that gocpp generates (Phase 10 §2.2 of the plan). Real Go
// runs this twin to make ../output.txt, and the gocpp program must print the
// same.
//
// A macro becomes a function with a hidden first parameter gp_site, a lazy
// parameter becomes a func() T, and a wrap macro gets the function's code as
// a last parameter gp_body. Each use passes its own static site. On top of a
// func, a start-style macro becomes the first statement, and a wrap-style
// macro gets the function's code as a closure in which a return sets the
// results. Names that start with gp_ stand for names the compiler makes up.
package main

import (
	"encoding/json"
	"fmt"
	"strconv"
	"sync"

	gp_macro "macros/macro"
)

// The uses of macros in ../main.gp, one site each.
var (
	gp_site_1 = gp_macro.Site{File: "main.gp", Line: 90, Func: "main.(*Counter).Add", Args: []string{"&c.mu"}}
	gp_site_2 = gp_macro.Site{File: "main.gp", Line: 103, Func: "main.parseEvent"}
	gp_site_3 = gp_macro.Site{File: "main.gp", Line: 107, Func: "main.parseEvent", Args: []string{"err == nil", `note("bad event %s", data)`}}
	gp_site_4 = gp_macro.Site{File: "main.gp", Line: 111, Func: "main.ratio"}
	gp_site_5 = gp_macro.Site{File: "main.gp", Line: 112, Func: "main.ratio"}
	gp_site_6 = gp_macro.Site{File: "main.gp", Line: 114, Func: "main.ratio", Args: []string{"b != 0", `note("ratio(%d, %d)", a, b)`}}
	gp_site_7 = gp_macro.Site{File: "main.gp", Line: 118, Func: "main.square"}
	gp_site_8 = gp_macro.Site{File: "main.gp", Line: 124, Func: "main.main", Args: []string{"square(3) + square(4)"}}
	gp_site_9 = gp_macro.Site{File: "main.gp", Line: 151, Func: "main.main", Args: []string{"ev.Level"}}
)

// macro Assert(cond bool, msg lazy string)
func Assert(gp_site *gp_macro.Site, cond bool, msg func() string) {
	if !cond {
		panic(fmt.Sprintf("%s:%d: assertion failed: %s: %s", gp_site.Outermost().File, gp_site.Outermost().Line, gp_site.Args[0], msg()))
	}
}

// macro Dbg[T any](v T) T
func Dbg[T any](gp_site *gp_macro.Site, v T) T {
	fmt.Printf("[%s:%d] %s = %v\n", gp_site.Outermost().File, gp_site.Outermost().Line, gp_site.Args[0], v)
	return v
}

// macro Trace() func()
func Trace(gp_site *gp_macro.Site) func() {
	fmt.Println("enter", gp_site.Outermost().Func)
	return func() { fmt.Println("exit ", gp_site.Outermost().Func) }
}

// macro Locked(mu *sync.Mutex) func()
func Locked(gp_site *gp_macro.Site, mu *sync.Mutex) func() {
	mu.Lock()
	return mu.Unlock
}

// macro Recover(): a wrap macro, #body() is gp_body()
func Recover(gp_site *gp_macro.Site, gp_body func()) {
	defer func() {
		if r := recover(); r != nil {
			fmt.Println("recovered in", gp_site.Outermost().Func+":", r)
		}
	}()
	gp_body()
}

// macro InThread(): a wrap macro
func InThread(gp_site *gp_macro.Site, gp_body func()) {
	done := make(chan struct{})
	go func() {
		defer close(done)
		gp_body()
	}()
	<-done
}

type Level int

const (
	Debug Level = iota
	Info
	Warn
	Error
)

// String is generated by #Derive(String), in the style of Go's stringer.
func (l Level) String() string {
	switch l {
	case Debug:
		return "Debug"
	case Info:
		return "Info"
	case Warn:
		return "Warn"
	case Error:
		return "Error"
	}
	return "Level(" + strconv.Itoa(int(l)) + ")"
}

type Event struct {
	ID    int      `json:"id"`
	Name  string   `json:"name"`
	Level Level    `json:"level"`
	Tags  []string `json:"tags,omitempty"`
}

// MarshalJSON and UnmarshalJSON are generated by #Derive(JSON). The real
// derive writes them field by field from the struct tags, without
// reflection; they must behave exactly like encoding/json on the plain
// struct, and that is what the twin uses.
type gp_plainEvent Event

func (e Event) MarshalJSON() ([]byte, error) { return json.Marshal(gp_plainEvent(e)) }

func (e *Event) UnmarshalJSON(data []byte) error {
	return json.Unmarshal(data, (*gp_plainEvent)(e))
}

type Counter struct {
	mu sync.Mutex
	n  map[string]int
}

// #Locked(&c.mu) on top: start style, the first statement.
func (c *Counter) Add(key string, n int) {
	if gp_f := Locked(&gp_site_1, &c.mu); gp_f != nil {
		defer gp_f()
	}
	c.n[key] += n
}

var built int

func note(format string, args ...any) string {
	built++
	return fmt.Sprintf(format, args...)
}

// #Trace() on top: start style.
func parseEvent(data string) Event {
	if gp_f := Trace(&gp_site_2); gp_f != nil {
		defer gp_f()
	}
	var ev Event
	err := json.Unmarshal([]byte(data), &ev)
	Assert(&gp_site_3, err == nil, func() string { return note("bad event %s", data) })
	return ev
}

// #Trace() then #Recover() on top: the first one listed is the outermost, so
// Trace's call comes first and Recover wraps the function's own code.
func ratio(a, b int) (gp_r0 int) {
	if gp_f := Trace(&gp_site_4); gp_f != nil {
		defer gp_f()
	}
	Recover(&gp_site_5, func() {
		Assert(&gp_site_6, b != 0, func() string { return note("ratio(%d, %d)", a, b) })
		gp_r0 = a / b
	})
	return
}

// #InThread() on top: wrap style.
func square(n int) (gp_r0 int) {
	InThread(&gp_site_7, func() {
		gp_r0 = n * n
	})
	return
}

func main() {
	sum := Dbg(&gp_site_8, square(3)+square(4))
	fmt.Println("sum:", sum)

	// square runs on a goroutine of its own, here called from 4 goroutines.
	results := make([]int, 4)
	var wg sync.WaitGroup
	for i := range 4 {
		wg.Go(func() { results[i] = square(i + 1) })
	}
	wg.Wait()
	fmt.Println("squares:", results)

	// 100 Adds at the same time: Locked lets one run at a time.
	c := &Counter{n: map[string]int{}}
	for i := range 100 {
		key := "even"
		if i%2 == 1 {
			key = "odd"
		}
		wg.Go(func() { c.Add(key, i) })
	}
	wg.Wait()
	fmt.Println("counter:", c.n)

	// The assertion in parseEvent passes, so its message is never built.
	ev := parseEvent(`{"id": 1, "name": "start", "level": 1, "tags": ["boot"]}`)
	fmt.Println("event:", ev.ID, ev.Name, ev.Tags)
	fmt.Println("level:", Dbg(&gp_site_9, ev.Level))

	// The derived String and MarshalJSON.
	fmt.Println(Debug, Info, Warn, Error, Level(7))
	data, err := json.Marshal(Event{ID: 2, Name: "stop", Level: Warn})
	fmt.Println(string(data), err)

	// ratio(1, 0) fails its assertion; Recover stops the panic and Trace
	// still prints the exit.
	fmt.Println("ratio:", ratio(8, 2))
	fmt.Println("ratio:", ratio(1, 0))
	fmt.Println("messages built:", built)
}
