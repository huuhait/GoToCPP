package tests

import (
	"os"
	"regexp"
	"testing"
)

// TestMustgenPhaseLines: tests/mustgen writes the phase line of a program that uses only what the finished
// phases have (05; the must forms need no switch since step 10.12, ADR-095) and, for the programs of its
// ord mode, which start goroutines, 08.
func TestMustgenPhaseLines(t *testing.T) {
	for file, want := range map[string]string{"mustgen/main.go": "// phase: 05", "mustgen/ord.go": "// phase: 08"} {
		src, err := os.ReadFile(file)
		if err != nil {
			t.Fatal(err)
		}
		if !regexp.MustCompile(regexp.QuoteMeta(`"` + want + `\n\n// Generated by tests/mustgen`)).Match(src) {
			t.Errorf("%s does not write %q before its generated header", file, want)
		}
		if regexp.MustCompile(`// phase: 10`).Match(src) {
			t.Errorf("%s still writes // phase: 10", file)
		}
	}
}
