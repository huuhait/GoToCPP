package rtfiles_test

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"runtime"
	"strconv"
	"strings"
	"testing"
	"unicode"
)

var updateIsPrint = flag.Bool("update-isprint", false, "rewrite src/isprint.cpp from strconv.IsPrint")

// isPrintFile is the C++ form of strconv.IsPrint, which fmt's %q uses: a rune that isn't
// printable is escaped ( ).
const isPrintFile = "src/isprint.cpp"

// isPrintGo is the Go release that gocpp follows (go.mod, the dev shell): src/isprint.cpp must
// come from its strconv, whatever Go runs the tests.
const isPrintGo = "go1.25"

// TestIsPrintTable checks that src/isprint.cpp says what strconv.IsPrint of Go 1.25 says, for
// every rune. It needs Go 1.25 (another Go may have another Unicode version);
// go test ./runtime -run TestIsPrintTable -update-isprint, run with Go 1.25, rewrites the file.
func TestIsPrintTable(t *testing.T) {
	if v := runtime.Version(); !strings.HasPrefix(v, isPrintGo+".") && v != isPrintGo {
		t.Fatalf("%s must come from strconv.IsPrint of Go 1.25, the Go that gocpp follows, but this is %s: "+
			"run the test with Go 1.25 (the dev shell's: nix develop -c go test ./runtime -run TestIsPrintTable)", isPrintFile, v)
	}
	want := isPrintSource()
	if *updateIsPrint {
		if err := os.WriteFile(isPrintFile, want, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(isPrintFile)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("%s is stale (or edited): run go test ./runtime -run TestIsPrintTable -update-isprint (with Go 1.25)", isPrintFile)
	}
}

// isPrintSource renders src/isprint.cpp: the runs of printable runes above U+00FF (Latin-1 has
// a fast path in the code, as in strconv).
func isPrintSource() []byte {
	type run struct{ lo, hi rune }
	var runs []run
	for r := rune(0x100); r <= unicode.MaxRune; r++ {
		if !strconv.IsPrint(r) {
			continue
		}
		if n := len(runs); n > 0 && runs[n-1].hi == r-1 {
			runs[n-1].hi = r
		} else {
			runs = append(runs, run{r, r})
		}
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, `// Code generated by runtime/isprint_test.go from strconv.IsPrint (Unicode %s); DO NOT EDIT.
// go test ./runtime -run TestIsPrintTable -update-isprint rewrites it.
//
// is_print is strconv.IsPrint, for fmt's %%q (gocpp/fmtshim.hpp): the printable runes are
// Go's letters, marks, numbers, punctuation, symbols and the ASCII space.
#include <gocpp/rt.hpp>

#include <cstddef>
#include <cstdint>

namespace gp::fmtshim::detail {

namespace {

struct rune_run {
    uint32_t lo, hi;
};

// The runs of printable runes above U+00FF, in order.
// clang-format off
constexpr rune_run print_runs[] = {
`, unicode.Version)
	for i, r := range runs {
		if i%4 == 0 {
			b.WriteString("   ")
		}
		fmt.Fprintf(&b, " {0x%X, 0x%X},", r.lo, r.hi)
		if i%4 == 3 || i == len(runs)-1 {
			b.WriteString("\n")
		}
	}
	b.WriteString(`};
// clang-format on

} // namespace

bool is_print(char32_t r) noexcept {
    if (r <= 0xFF) {
        // All of ASCII from the space to ~, and Latin-1 from U+00A1, except the soft hyphen.
        return (0x20 <= r && r <= 0x7E) || (0xA1 <= r && r != 0xAD);
    }
    std::size_t lo = 0, hi = sizeof print_runs / sizeof print_runs[0];
    while (lo < hi) {
        std::size_t mid = lo + (hi - lo) / 2;
        if (print_runs[mid].hi < r) {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    return lo < sizeof print_runs / sizeof print_runs[0] && print_runs[lo].lo <= r;
}

} // namespace gp::fmtshim::detail
`)
	return b.Bytes()
}
