// gocpp export cmake (Phase 06 step 6.11, ADR-044): a folder with a CMakeLists.txt that builds the
// program from the C++ that gocpp wrote, so that it can be built without gocpp.
//
//	<dir>/CMakeLists.txt   the target, the source files, the flags of each group of files, the link
//	<dir>/gen/             a copy of the generated C++ of the program (pkg.hpp, *.gp.cpp, pkg_desc.cpp, pkg_init.cpp)
//	<dir>/runtime/         gocpp's runtime: its headers and sources
//
// The flags of every compile are those of the build that the export was made from, exactly (the
// plan's commands, Plan.Compiles): a group of files with the same flags shares one
// set_source_files_properties(... COMPILE_FLAGS "..."), and the flags are one string that CMake
// puts on the command line as it is, so that it does not reorder or drop a repeated flag
// (gocpp's language flags come last on purpose: the last -std= wins; COMPILE_OPTIONS would
// drop the repeats, and its SHELL: prefix is not read for a source file). The generated files and the runtime are in the folder;
// the project's own C and C++ files, its headers, the libraries of modules and the link flags
// are named by their absolute paths on the machine that made the export (see the limits in
// docs/spec/build.md). The file checks that the compiler is of the family that the flags were
// made for (clang or g++).

// CMakeMarker is the first line of a CMakeLists.txt that gocpp wrote: an export into an existing
// folder replaces only such a folder.
const CMakeMarker = "# Generated by gocpp export cmake"

// cmakeGroup is a set of source files compiled with the same flags.
type cmakeGroup struct {
	comment string
	flags   string // the flags as one SHELL: string, already CMake-escaped
	files   []string
}

// CMakeLists returns the text of CMakeLists.txt for the plan, for the program name. version is
// the gocpp version, for the comment at the top. The runtime and the generated files are named
// as in the folder that ExportCMake writes. An error is a flag that CMake can't carry.
func (p *Plan) CMakeLists(name, version string) (string, error) {
	if p.Link == nil || len(p.Compiles) == 0 {
		return "", fmt.Errorf("the build has no commands to export")
	}
	if strings.ContainsAny(name, "\"\\$;\n") || name == "" {
		return "", fmt.Errorf("the program name %q is not a CMake target name", name)
	}
	const genMark, rtMark = "\x01GEN\x01", "\x01RT\x01"
	mark := func(s string) string {
		if p.GenRoot != "" {
			s = strings.ReplaceAll(s, p.GenRoot, genMark)
		}
		if p.RuntimeDir != "" {
			s = strings.ReplaceAll(s, p.RuntimeDir, rtMark)
		}
		return s
	}
	finish := func(s string) string {
		s = strings.ReplaceAll(s, "\\", "\\\\")
		s = strings.ReplaceAll(s, "\"", "\\\"")
		s = strings.ReplaceAll(s, "$", "\\$")
		s = strings.ReplaceAll(s, genMark, "${GOCPP_EXPORT_DIR}/gen")
		return strings.ReplaceAll(s, rtMark, "${GOCPP_EXPORT_DIR}/runtime")
	}
	check := func(words ...string) error {
		for _, w := range words {
			if strings.Contains(w, ";") || strings.ContainsAny(w, "\n\x00\x01") {
				return fmt.Errorf("the flag %q can't be put in a CMakeLists.txt (a ';' or a line break in a flag)", w)
			}
		}
		return nil
	}

	var groups []*cmakeGroup
	var sources []string
	hasC := false
	for _, c := range p.sortedCompiles() {
		var flags []string
		args := c.CompileArgs()
		for i := 0; i < len(args); i++ {
			switch {
			case args[i] == "-c", args[i] == c.File:
			case args[i] == "-x" && i+1 < len(args):
				i++ // CMake chooses the language by the file's extension
			default:
				flags = append(flags, args[i])
			}
		}
		if err := check(append(slices.Clone(flags), c.File)...); err != nil {
			return "", err
		}
		hasC = hasC || c.Lang == "c"
		shell := make([]string, len(flags))
		for i, f := range flags {
			shell[i] = quoteWord(mark(f))
		}
		text := finish(strings.Join(shell, " "))
		file := finish(mark(c.File))
		sources = append(sources, file)
		i := slices.IndexFunc(groups, func(g *cmakeGroup) bool { return g.flags == text })
		if i < 0 {
			groups = append(groups, &cmakeGroup{comment: describe(c), flags: text})
			i = len(groups) - 1
		}
		groups[i].files = append(groups[i].files, file)
	}
	link := p.Link
	for _, w := range slices.Concat(link.Pre, link.Post) {
		if err := check(w); err != nil {
			return "", err
		}
	}
	var pre []string
	for _, w := range link.Pre {
		pre = append(pre, quoteWord(mark(w)))
	}

	var b strings.Builder
	langs := "CXX"
	if hasC {
		langs = "CXX C"
	}
	fmt.Fprintf(&b, "%s (gocpp %s). It builds the program %s from the C++ that gocpp wrote,\n", CMakeMarker, version, name)
	b.WriteString(`# without gocpp: the files in gen/ are the generated C++, runtime/ is gocpp's runtime.
#
# The flags of every file are the flags of the gocpp build that this file was made from, so the
# compiler must be the same family: clang++ or g++ (this file says which). Set it as usual:
#   cmake -S . -B build -DCMAKE_CXX_COMPILER=<compiler> && cmake --build build
# The project's own C and C++ files, headers, libraries and link flags are named by their paths on
# the machine that made this file. Run gocpp export cmake again after the .gp files change.
cmake_minimum_required(VERSION 3.20)
`)
	fmt.Fprintf(&b, "project(%s LANGUAGES %s)\n\n", name, langs)
	b.WriteString("set(GOCPP_EXPORT_DIR \"${CMAKE_CURRENT_LIST_DIR}\")\n\n")
	b.WriteString(familyCheck("CXX", p.CXX.Family))
	if hasC && p.CC.Family != 0 {
		b.WriteString(familyCheck("C", p.CC.Family))
	}
	fmt.Fprintf(&b, "add_executable(%s\n", name)
	for _, s := range sources {
		fmt.Fprintf(&b, "  \"%s\"\n", s)
	}
	b.WriteString(")\n\n")
	for _, g := range groups {
		fmt.Fprintf(&b, "# %s\nset_source_files_properties(\n", g.comment)
		for _, f := range g.files {
			fmt.Fprintf(&b, "  \"%s\"\n", f)
		}
		fmt.Fprintf(&b, "  PROPERTIES COMPILE_FLAGS \"%s\")\n\n", g.flags)
	}
	fmt.Fprintf(&b, "# The link: these options come before the object files, the libraries after them.\n")
	fmt.Fprintf(&b, "target_link_options(%s PRIVATE \"%s\")\n", name, finish("SHELL:"+strings.Join(pre, " ")))
	if len(link.Post) > 0 {
		fmt.Fprintf(&b, "target_link_libraries(%s PRIVATE\n", name)
		for _, w := range link.Post {
			fmt.Fprintf(&b, "  \"%s\"\n", finish(mark(w)))
		}
		b.WriteString(")\n")
	}
	return b.String(), nil
}

// describe returns the comment of the group of the command c.
func describe(c Command) string {
	switch c.Kind {
	case KindUnit:
		return "the generated C++ of " + c.Pkg
	case KindSource:
		return "the C and C++ files of " + c.Pkg
	case KindLibrary:
		return "a library of a module"
	case KindRuntime:
		return "gocpp's runtime"
	}
	return string(c.Kind)
}

// familyCheck returns the CMake text that stops a configure with a compiler of another family
// than the one that the flags were made for.
func familyCheck(lang string, f Family) string {
	switch f {
	case Clang:
		return fmt.Sprintf("if(NOT CMAKE_%s_COMPILER_ID MATCHES \"Clang\")\n  message(FATAL_ERROR \"this CMakeLists.txt has the flags of clang (gocpp built with it): set CMAKE_%s_COMPILER to clang\")\nendif()\n\n", lang, lang)
	case GCC:
		return fmt.Sprintf("if(NOT CMAKE_%s_COMPILER_ID STREQUAL \"GNU\")\n  message(FATAL_ERROR \"this CMakeLists.txt has the flags of g++ (gocpp built with it): set CMAKE_%s_COMPILER to gcc\")\nendif()\n\n", lang, lang)
	}
	return ""
}

// ExportCMake writes the CMake project of the plan into dir: CMakeLists.txt, a copy of the
// generated files (gen) and the runtime's files (runtime). A folder that exists, is not empty and
// has no CMakeLists.txt that gocpp wrote is an error; in one that has, gen and runtime are
// written again (a file that is no longer generated goes). It returns the name of CMakeLists.txt.
func ExportCMake(p *Plan, dir, name, version string) (string, error) {
	text, err := p.CMakeLists(name, version)
	if err != nil {
		return "", err
	}
	list := filepath.Join(dir, "CMakeLists.txt")
	if entries, err := os.ReadDir(dir); err == nil && len(entries) > 0 {
		old, err := os.ReadFile(list)
		if err != nil || !strings.HasPrefix(string(old), CMakeMarker) {
			return "", fmt.Errorf("%s is not empty and has no CMakeLists.txt that gocpp export cmake wrote: it won't be replaced", dir)
		}
	}
	for _, sub := range []string{"gen", "runtime"} {
		if err := os.RemoveAll(filepath.Join(dir, sub)); err != nil {
			return "", err
		}
	}
	if err := copyTree(p.GenRoot, filepath.Join(dir, "gen")); err != nil {
		return "", fmt.Errorf("copying the generated files: %w", err)
	}
	if err := WriteRuntime(filepath.Join(dir, "runtime")); err != nil {
		return "", fmt.Errorf("writing the runtime: %w", err)
	}
	return list, WriteFileIfChanged(list, []byte(text))
}

// copyTree copies the files of the folder from into the folder to (made if needed).
func copyTree(from, to string) error {
	return filepath.WalkDir(from, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(from, p)
		if err != nil {
			return err
		}
		dst := filepath.Join(to, rel)
		switch {
		case d.IsDir():
			return os.MkdirAll(dst, 0o755)
		case !d.Type().IsRegular() || strings.HasPrefix(d.Name(), ".tmp-"):
			return nil
		}
		data, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		return os.WriteFile(dst, data, 0o644)
	})
}
