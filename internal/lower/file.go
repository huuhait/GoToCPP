// An Error is a problem that stops Package: mostly a construct that lowering can't translate
// yet ("not supported yet: switch statement"). The phase gates of internal/check reject the
// features of later phases with a message for the user, so an Error is a gocpp bug or a
// feature that this phase hasn't built yet (cppgen reports it as an internal error).
type Error struct {
	Pos token.Position // where in the .gp source; may be invalid
	Msg string         // without the position

	// User says that the error is the user's, not gocpp's: a C/C++ name that the imported
	// headers don't declare (std.vectr), which only the C++ compiler's probes find out
	// (interop.go). The check can't see it, so lowering reports it.
	User bool
}

func (e *Error) Error() string {
	if e.Pos.IsValid() {
		return e.Pos.String() + ": " + e.Msg
	}
	return e.Msg
}

// Package returns the C++ translation unit of the type-checked main package pkg, which has
// no errors: one unit for the whole program (the unit layout, which the emitter's own tests use;
// gocpp build writes the split layout of a Program: one file per .gp file and a pkg.hpp). fset holds the
// positions of pkg's files (check.Result.Fset); their names must be absolute, as the loader
// makes them, because they go into the #line directives.
//
// The translation unit (docs/spec/cpp-mapping.md, "A first example") is:
//
//	// hello.gp.cpp: generated by gocpp, do not edit
//	#include <gocpp/rt.hpp>
//
//	namespace gpkg_main {
//	<a prototype of every function, so that their order doesn't matter>
//	<the package variables>
//	<the functions, each line mapped to its .gp line>
//	<gp_var_init and gp_init_funcs, if the package needs them>
//	} // namespace gpkg_main
//
//	<gp_init_all, if the package needs it>
//	int main(int argc, char** argv) {
//	    return gp::run_main(argc, argv, nullptr, &gpkg_main::main);
//	}
//
// A package with header imports (Phase 04) needs in, what the compiler probes found out about
// its C/C++ names (ProbeInterop); then the C/C++ includes follow gocpp's own header, in source
// order, then gocpp/fmtcxx.hpp (fmt's use of the headers' std::formatters), and the macros that
// collide with the names of the generated code are #undef'd after them (macros.go). in may be
// nil for a package without header imports.
//
// For a construct that it can't translate, Package returns an *Error.
func Package(fset *token.FileSet, pkg *check.Package, in *Interop, opts ...Options) (*cppir.File, error) {
	g := newGen(fset, pkg)
	if len(opts) > 0 {
		g.opts = opts[0]
	}
	g.prog = &Program{fset: fset, opts: g.opts, byPkg: map[*types.Package]*gen{pkg.Types: g}, main: g}
	g.interop = in
	if in != nil {
		g.macros = in.macros
	}
	f := g.file()
	if g.err != nil {
		return nil, g.err
	}
	return f, nil
}

// newGen returns the lowering of the checked package pkg.
func newGen(fset *token.FileSet, pkg *check.Package) *gen {
	return &gen{
		fset:  fset,
		pkg:   pkg,
		info:  newTinfo(pkg.Info),
		ns:    NamespaceName(importPath(pkg.Types)),
		names: make(map[types.Object]string),

		uintCounts: make(map[ast.Expr]bool),
	}
}

// errNoMain is the error for a main package without func main, which go build gives too
// (from the linker, which go/types leaves it to).
var errNoMain = errors.New("function main is undeclared in the main package")

// A gen holds the state of one Package call.
type gen struct {
	fset *token.FileSet
	pkg  *check.Package
	info *tinfo

	// out are the declarations that lowering made (outputs).
	out outputs

	// split says that the package is written as a header and several translation units
	// (split.go), not as one unit (file).
	split bool

	// err is the first error, or nil. After an error, lowering goes on (so its code needs no
	// error checks at every step), but its tree is thrown away.
	err *Error

	// viewVars are the hidden string parameters of the macros being lowered (generics.go: viewIndex).
	viewVars map[*types.Var]bool

	// ns is the C++ namespace of the package (gpkg_main).
	ns string

	// names are the C++ names of the package-level objects: functions and variables.
	names map[types.Object]string

	consts   []*types.Const // the exported constants, in source order
	funcs    []*funcInfo    // the functions with bodies, in source order
	vars     []*types.Var   // the package variables, in source order (without _)
	varExprs []ast.Expr     // the initial values of the package variables (their closures declare local types)
	initFns  []string       // the C++ names of the init functions, in source order
	varInits bool           // gp_var_init is needed
	lazyVars []string       // the gp::lazy storage of the package variables of C/C++ classes (lazyVar), in source order

	// uintCounts are the expressions inside a shift count that is untyped but not a
	// constant (markCounts).
	uintCounts map[ast.Expr]bool

	// typeDecls are the package's structs (typedecl.go), or nil before the first one.
	typeDecls *typeDecls

	// implicit are the values that Go converts implicitly to another type, which C++ needs a
	// conversion for, with the type (named.go: noteConversions).
	implicit map[ast.Expr]types.Type

	// ifaces are the interface structs of the package (ifaces.go), descs the type descriptors
	// (typedesc.go).
	ifaces *ifaceTable
	descs  *descTable

	// commaOKFlags are the ok variables of v, ok := x.(T) with a C/C++ type T (cguard.go).
	commaOKFlags map[types.Object]bool

	// localTags are the unique tags of the types declared in functions that have no struct
	// (canon.go: localTag).
	localTags map[*types.TypeName]string

	// localOrdinals numbers the types declared in function bodies of the package in source order (localOrdinal).
	localOrdinals map[token.Pos]int

	// lits are the numbers of the func literals in their functions (closures.go: numberLits).
	lits map[*ast.FuncLit]int

	// The C/C++ names (Phase 04): what the compiler probes found out (interop.go), the uses of
	// header packages and namespaces by their selectors and the probe's answers for each
	// (cnames.go), the names of the C/C++ names that the code writes (macros.go), the type
	// expressions of the parameters and results (cvalues.go: sigTypes), the untyped constants that
	// are C/C++ values (cvalues.go: markCValues), and the type expressions of the composite
	// literals whose type is left out (clits.go: elidedTypes).
	interop  *Interop
	macros   map[string]bool
	cuses    map[*ast.SelectorExpr]*load.CppUse
	useKinds map[*load.CppUse]map[string]interop.Kind
	cNames   map[string]token.Pos
	cNodes   []cppir.Node
	sigExprs map[*types.Var]ast.Expr
	fwds     map[*structInfo][]forwarder // the forwarders of the structs (promote.go)
	fwdNeed  map[*structInfo]bool        // the structs that write them
	opts     Options
	cConsts  map[ast.Expr]bool
	cFuncs   map[ast.Expr]bool // func values that go to C/C++ places: callbacks (ccallback.go)
	elided   map[*ast.CompositeLit]ast.Expr
	holders  map[*types.Var]bool     // the variables that hold a C.cstr holder (cstrings.go)
	wideVars map[*types.Var]bool     // the holders among them that hold a C.wstr holder (cstrings.go)
	tconv    map[ast.Expr]cppir.Type // the conversions of typed mode (typed.go: noteTypedConv)
	parents  map[ast.Node]ast.Node   // the parent of each syntax node (typedargs.go: parentOf)

	cConstKinds   map[ast.Expr]types.BasicKind // known C numeric targets, for exact constant emission
	initialValues map[*types.Var]ast.Expr      // initializers of inferred locals, for known C types

	// awareBodies caches which function bodies call recover (recover.go); funcDecls maps the
	// functions of the package to their declarations, for awareFunc.
	awareBodies map[*ast.BlockStmt]bool
	funcDecls   map[*types.Func]*ast.FuncDecl

	// borrow is the result of the borrowed-parameter analysis (borrow.go), by function.
	borrow   map[*types.Func]*borrowSum
	borrowC  map[types.Type]bool                        // cached foreign-type boundary
	boxCache map[*ast.FuncDecl]map[*types.Var]boxReason // boxedOf
	thr      *threadInfo                                // the thread facts of a package lowered alone (threads.go)

	// inTemplate counts the C++ template arguments being lowered (ctypes.go: templateArg),
	// in which the package's types are fully qualified.
	inTemplate int

	// generics are the generic functions of the package (generics.go), insts the instances that
	// units asked for and instQueue those not lowered yet, ctxt the context that go/types
	// instantiates types with, and unit the translation unit being lowered.
	generics map[*types.Func]*genericFunc
	// genericTypes are the generic types the package declares (insttypes.go), inShared counts the
	// shared instances being made, infoPrivate says that info is the package's own copy.
	genericTypes map[*types.TypeName]*genericType
	inShared     int
	infoPrivate  bool
	insts        map[instKey]*instance
	instQueue    []*instance
	instNames    map[string]string // the C++ name of each instance and the text it was made from (clashes of the hash)
	ctxt         *types.Context
	unit         string

	// cxxNamed are the types that stand for C/C++ type arguments (opaqueInstRef), cxxCount
	// numbers them, and curOpen are the template parameters of the instance being lowered.
	cxxNamed map[*types.Named]cxxInfo
	cxxCount int
	curOpen  map[*types.Named]bool

	// curInst is the C++ name of the instance being lowered, "" outside one (the reason log's Inst).
	curInst string

	// whyReg says that the package was registered with the reason log (Why.register).
	whyReg bool

	// mute, when it is not 0, stops the reason log (quiet).
	mute int

	// prog is the program of the packages lowered together (program.go); it is never nil.
	// global counts the definitions of shared types being written (shared.go): the package's
	// types are fully qualified there too, as they are written outside its namespace.
	prog   *Program
	global int

	// usedShared and sharedList are the shared types (shared.go) that the package uses, rec the
	// list that the shared types being made note the ones they mention in.
	usedShared map[sharedItem]bool
	sharedList []sharedItem
	rec        *[]sharedItem

	// pendingAsserts are the static_asserts of the typed constants that the first translation unit of the
	// package takes (typedconsts.go).
	pendingAsserts []cppir.Decl
}

// errorf records an error at pos, if it is the first.
func (g *gen) errorf(pos token.Pos, format string, args ...any) {
	if g.err == nil {
		g.err = &Error{Pos: g.fset.Position(pos), Msg: fmt.Sprintf(format, args...)}
	}
}

// unsupported records that the construct what at pos is not supported yet.
func (g *gen) unsupported(pos token.Pos, what string) {
	g.errorf(pos, "not supported yet: %s", what)
}

// notYet records an error that is the user's, not gocpp's: the program uses what a later phase
// builds (what is the whole message, "... is not available yet (Phase NN)"), like the checker's
// gates; gocpp build reports it as an error, not as a bug.
func (g *gen) notYet(pos token.Pos, what string) {
	g.errorf(pos, "%s", what)
	if g.err != nil && g.err.Pos == g.fset.Position(pos) && g.err.Msg == what {
		g.err.User = true
	}
}

// pos returns the place of p in the .gp source, for a C++ line: the zero Pos if p is not
// valid.
func (g *gen) pos(p token.Pos) cppir.Pos {
	if !p.IsValid() {
		return cppir.Pos{}
	}
	pp := g.fset.Position(p)
	return cppir.Pos{File: pp.Filename, Line: pp.Line}
}

// outputs are the declarations that lowering made, by what they are: prototypes, package
// variables, the definitions of the functions (also by the file that declares them) and the
// package's initialization. unitFile puts them in one translation unit; the split layout
// (split.go) puts them in different files.
type outputs struct {
	protos []cppir.Decl // the prototypes of the functions
	vars   []cppir.Decl // the definitions of the package variables
	varExt []cppir.Decl // their extern declarations (the split layout's header)
	funcs  []cppir.Decl // the definitions of the functions, in source order
	inits  []cppir.Decl // gp_var_init and gp_init_funcs

	byFile map[string][]cppir.Decl // the definitions of the functions by the .gp file
	files  []string                // the files of byFile, in the order of the first definition

	insts map[string]*instUnit // the instances of generic functions by unit (generics.go)
}

// lower lowers the package: the functions, the variables and the initialization go to g.out,
// the types it needs are found on the way. It reports false after an error.
func (g *gen) lower() bool {
	g.collect()
	if g.err != nil {
		return false
	}
	g.checkCUses() // cguard.go
	if g.err != nil {
		return false
	}
	g.markAllCValues() // cvalues.go
	g.prototypes()
	g.unit = initUnit
	g.packageVars()
	g.drainInstances() // generics.go
	for _, fn := range g.funcs {
		g.unit = g.fileOf(fn.decl.Pos())
		g.funcDecl(fn)
		g.drainInstances()
	}
	g.unit = initUnit
	g.initFuncs()
	g.drainInstances()
	return g.err == nil
}

// file returns the whole translation unit.
func (g *gen) file() *cppir.File {
	if g.pkg.Types.Name() != "main" {
		g.unsupported(g.pkg.Load.Files[0].AST.Name.Pos(), "package "+g.pkg.Types.Name()+": only package main can be built until Phase 06")
		return nil
	}
	mainFn, _ := g.pkg.Types.Scope().Lookup("main").(*types.Func)
	if mainFn == nil {
		g.errorf(g.pkg.Load.Files[0].AST.Name.Pos(), "%v", errNoMain)
		return nil
	}
	if !g.lower() {
		return nil
	}

	f := &cppir.File{}
	f.Decls = append(f.Decls,
		&cppir.Comment{Text: g.outputName() + ": generated by gocpp, do not edit"},
		&cppir.Include{Path: "gocpp/rt.hpp", System: true})
	if incs := g.includes(); len(incs) > 0 {
		if g.interop == nil {
			g.errorf(g.pkg.Load.Files[0].AST.Name.Pos(), "internal error: a package with header imports without the compiler probes (lower.ProbeInterop)")
			return nil
		}
		f.Decls = append(f.Decls, incs...)
		// fmt's std::formatter support, which needs to come after the headers (fmtcxx.hpp).
		f.Decls = append(f.Decls, &cppir.Include{Path: "gocpp/fmtcxx.hpp", System: true})
		f.Decls = append(f.Decls, g.constAsserts()...) // typedconsts.go
	}
	f.Decls = append(f.Decls, &cppir.Blank{})
	ns := &cppir.Namespace{Name: g.ns}
	ns.Decls = append(ns.Decls, &cppir.Blank{})
	ns.Decls = append(ns.Decls, g.structDecls().all()...)
	ns.Decls = append(ns.Decls, g.out.protos...)
	ns.Decls = append(ns.Decls, g.out.allInstDecls(g.instUnitOrder())...)
	ns.Decls = append(ns.Decls, g.out.vars...)
	ns.Decls = append(ns.Decls, g.out.funcs...)
	ns.Decls = append(ns.Decls, g.out.inits...)
	f.Decls = append(f.Decls, ns, &cppir.Blank{})

	init := cppir.Expr(&cppir.Lit{Text: "nullptr"})
	if g.varInits || len(g.initFns) > 0 {
		init = &cppir.Unary{Op: "&", X: cxxName("gp_init_all")}
		body := &cppir.Block{}
		if g.varInits {
			body.Stmts = append(body.Stmts, &cppir.ExprStmt{X: call(g.ns + "::gp_var_init")})
		}
		if len(g.initFns) > 0 {
			body.Stmts = append(body.Stmts, &cppir.ExprStmt{X: call(g.ns + "::gp_init_funcs")})
		}
		f.Decls = append(f.Decls, &cppir.Func{Result: typeName("void"), Name: "gp_init_all", Body: body}, &cppir.Blank{})
	}
	run := call("gp::run_main", cxxName("argc"), cxxName("argv"), init, &cppir.Unary{Op: "&", X: cxxName(g.ns + "::" + g.names[mainFn])})
	f.Decls = append(f.Decls, &cppir.Func{
		Result: typeName("int"),
		Name:   "main",
		Params: []cppir.Param{
			{Type: typeName("int"), Name: "argc"},
			{Type: &cppir.Ptr{Elem: &cppir.Ptr{Elem: typeName("char")}}, Name: "argv"},
		},
		Body: &cppir.Block{Stmts: []cppir.Stmt{&cppir.Return{X: run}}},
	})
	g.protectNames(f) // macros.go
	return f
}

// includes returns the #include lines of the package's header imports (Phase 04 README §2.3),
// which follow gocpp's own headers: each file's, in file order and source order, each header
// once, each mapped to its import, so that an error in a header is reported there. A local
// header ("./physics.h") is found with -iquote and the package's folder (the build's flag,
// as for the probes), so it can't hide a system header: <vector> is never looked up there. A C
// header without a __cplusplus guard, and a header of //gocpp:extern-c, is included inside
// extern "C" { } (§2.9, step 4.14: check decided which, check.Package.ExternC).
func (g *gen) includes() []cppir.Decl {
	var list []cppir.Decl
	for _, ui := range unitIncludes(g.pkg.Load, g.pkg.ExternC) {
		_, externC := interop.SplitExternC(ui.text)
		inc := &cppir.Include{Pos: g.pos(ui.inc.Pos), Path: ui.inc.Target(), ExternC: externC}
		if ui.inc.Kind == load.SystemHeader {
			inc.Path, inc.System = strings.TrimSuffix(strings.TrimPrefix(ui.inc.Path, "<"), ">"), true
		}
		list = append(list, inc)
	}
	return list
}

// outputName returns the name of the generated file for its first line: hello.gp.cpp for
// hello.gp; for a package of several files, "package main (a.gp, b.gp)".
func (g *gen) outputName() string {
	files := g.pkg.Load.Files
	if len(files) == 1 {
		return filepath.Base(files[0].Path) + ".cpp"
	}
	names := make([]string, len(files))
	for i, f := range files {
		names[i] = filepath.Base(f.Path)
	}
	return "package main (" + strings.Join(names, ", ") + ")"
}

// collect walks the package-level declarations: it names the functions, variables and types
// (also the types declared in functions) and rejects the declarations that lowering doesn't have
// yet.
func (g *gen) collect() {
	for _, f := range g.pkg.Load.Files {
		for _, d := range f.AST.Decls {
			switch d := d.(type) {
			case *ast.FuncDecl:
				g.collectFunc(d)
			case *ast.GenDecl:
				g.collectGen(d)
			}
		}
	}
	g.collectLocalTypes() // typedecl.go
}

func (g *gen) collectFunc(d *ast.FuncDecl) {
	switch {
	case d.Recv != nil:
		g.collectMethod(d) // methods.go
		return
	case d.Type.TypeParams != nil:
		g.collectGeneric(d) // generics.go
		return
	case d.Body == nil:
		g.collectNative(d)
		return
	case d.Name.Name == "_":
		return // can't be called: nothing to write
	}
	fn, _ := g.info.Defs[d.Name].(*types.Func)
	if fn == nil {
		g.errorf(d.Pos(), "internal error: no object for func %s", d.Name.Name)
		return
	}
	name := g.escape(d.Name.Name)
	if d.Name.Name == "init" {
		// Go allows many init functions, and nothing can refer to them.
		name = fmt.Sprintf("gp_init_%d", len(g.initFns)+1)
		g.initFns = append(g.initFns, name)
		g.noteInitFunc(d.Name.Pos(), name) // why.go
	}
	g.names[fn] = name
	g.funcs = append(g.funcs, &funcInfo{decl: d, obj: fn, name: name})
}

// collectNative handles a function without a body: a native function of the standard library
// (//gocpp:native, internal/load/native.go) is the runtime's C++ function, called by its
// qualified name from every package; nothing is written for it. Any other function without a
// body is a declaration stub, which no program that gets here has (cmd/gocpp: notLowered).
func (g *gen) collectNative(d *ast.FuncDecl) {
	cxx, ok := load.NativeFunc(d)
	if !ok {
		g.unsupported(d.Pos(), "a function without a body")
		return
	}
	fn, _ := g.info.Defs[d.Name].(*types.Func)
	if fn == nil {
		g.errorf(d.Pos(), "internal error: no object for func %s", d.Name.Name)
		return
	}
	if !strings.HasPrefix(cxx, "::") {
		cxx = "::" + cxx
	}
	g.names[fn] = cxx
}

func (g *gen) collectGen(d *ast.GenDecl) {
	switch d.Tok {
	case token.IMPORT:
		// (fmt's functions are the runtime's: gp::fmt.)
	case token.CONST:
		// Every use of a constant is folded (expr.go), so the code needs no C++ for it. The
		// split layout's header has the exported ones for C++ users (constDecls).
		for _, spec := range d.Specs {
			for _, id := range spec.(*ast.ValueSpec).Names {
				if c, ok := g.info.Defs[id].(*types.Const); ok && c.Exported() {
					g.consts = append(g.consts, c)
				}
			}
		}
	case token.TYPE:
		g.collectTypes(d) // typedecl.go
	case token.VAR:
		for _, spec := range d.Specs {
			g.varExprs = append(g.varExprs, spec.(*ast.ValueSpec).Values...)
			for _, id := range spec.(*ast.ValueSpec).Names {
				if id.Name == "_" {
					continue
				}
				v, _ := g.info.Defs[id].(*types.Var)
				if v == nil {
					g.errorf(id.Pos(), "internal error: no object for var %s", id.Name)
					continue
				}
				g.names[v] = g.escape(id.Name)
				g.vars = append(g.vars, v)
			}
		}
	}
}

// prototypes declares every function: C++ needs a declaration before a use, Go doesn't care
// about the order. A method is declared in its struct (methods.go).
func (g *gen) prototypes() {
	n := 0
	for _, f := range g.funcs {
		f.prepare(g)
		if f.method != nil {
			continue // declared in its struct (methods.go)
		}
		g.out.protos = append(g.out.protos, &cppir.Func{Result: f.result, Name: f.name, Params: f.params})
		n++
	}
	if n > 0 {
		g.out.protos = append(g.out.protos, &cppir.Blank{})
	}
}

// Small constructors of cppir nodes.

// cxxName returns the C++ name s, which may be qualified: gp::len.
func cxxName(s string) *cppir.Name { return &cppir.Name{Name: s} }

// lit returns the C++ literal s.
func lit(s string) *cppir.Lit { return &cppir.Lit{Text: s} }

// call returns the call fun(args...).
func call(fun string, args ...cppir.Expr) *cppir.Call {
	return &cppir.Call{Fun: cxxName(fun), Args: args}
}

// typeName returns the C++ type named s.
func typeName(s string) *cppir.TypeName { return &cppir.TypeName{Name: s} }

// varDecl returns the declaration `typ n = init;` (`typ n{};` for an empty InitList) at pos.
func varDecl(pos cppir.Pos, typ cppir.Type, n string, init cppir.Expr) *cppir.VarDecl {
	return &cppir.VarDecl{Pos: pos, Type: typ, Vars: []cppir.Declarator{{Name: n, Init: init}}}
}

// voidCast returns static_cast<void>(x), which evaluates x and drops its value.
func voidCast(x cppir.Expr) cppir.Expr {
	return &cppir.Cast{Kind: "static_cast", Type: typeName("void"), X: x}
}

// templateCall returns fun<targs...>(args...): gp::make_slice<int64_t>(n).
func templateCall(fun string, targs []cppir.Node, args ...cppir.Expr) *cppir.Call {
	return &cppir.Call{Fun: &cppir.Name{Name: fun, Args: targs}, Args: args}
}

// construct returns typ(args...), a value of the C++ class type typ made by its constructor:
// gp::slice<int64_t>() (nil), gp::ptr<int64_t>(owner, p). typ is a *cppir.TypeName.
func construct(typ cppir.Type, args ...cppir.Expr) cppir.Expr {
	tn, ok := typ.(*cppir.TypeName)
	if !ok {
		return placeholder
	}
	return templateCall(tn.Name, tn.Args, args...)
}
