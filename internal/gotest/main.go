package gotest

import (
	"fmt"
	"strconv"
	"strings"
)

// Main returns the source of the generated main package of the test binary of the package
// importPath, for what Scan found. The package under test is imported as _test, its external test
// package as _xtest, like go test does (a blank import when the main package uses nothing of it,
// so that its init functions run).
func Main(importPath string, f *Found) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by gocpp test. DO NOT EDIT.\n\npackage testmain\n\nimport (\n")
	b.WriteString("\t\"testing\"\n\t\"testing/internal/testdeps\"\n\n")
	imp := func(on, need bool, alias, path string) {
		if !on {
			return
		}
		if !need {
			alias = "_"
		}
		fmt.Fprintf(&b, "\t%s %s\n", alias, strconv.Quote(path))
	}
	imp(f.ImportTest, f.NeedTest, "_test", importPath)
	imp(f.ImportXTest, f.NeedXTest, "_xtest", importPath+"_test")
	b.WriteString(")\n\n")

	list := func(name, typ string, fs []Func, example bool) {
		fmt.Fprintf(&b, "var %s = []testing.%s{\n", name, typ)
		for _, fn := range fs {
			if example {
				fmt.Fprintf(&b, "\t{%s, %s.%s, %s, %v},\n", strconv.Quote(fn.Name), fn.Pkg, fn.Name, strconv.Quote(fn.Output), fn.Unordered)
			} else {
				fmt.Fprintf(&b, "\t{%s, %s.%s},\n", strconv.Quote(fn.Name), fn.Pkg, fn.Name)
			}
		}
		b.WriteString("}\n\n")
	}
	list("tests", "InternalTest", f.Tests, false)
	list("benchmarks", "InternalBenchmark", f.Benchmarks, false)
	list("fuzzTargets", "InternalFuzzTarget", f.Fuzz, false)
	list("examples", "InternalExample", f.Examples, true)

	fmt.Fprintf(&b, "func init() {\n\ttestdeps.ImportPath = %s\n}\n\n", strconv.Quote(importPath))
	b.WriteString("func main() {\n\tm := testing.MainStart(testdeps.TestDeps{}, tests, benchmarks, fuzzTargets, examples)\n")
	if f.TestMain != nil {
		fmt.Fprintf(&b, "\t%s.%s(m)\n", f.TestMain.Pkg, f.TestMain.Name)
	} else {
		b.WriteString("\tm.Run()\n")
	}
	b.WriteString("\ttestdeps.Exit()\n}\n")
	return []byte(b.String())
}
