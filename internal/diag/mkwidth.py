"""mkwidth.py writes widthtable.go: the table of the characters that take
two cells in a terminal. These are the characters whose East Asian Width
is W (wide) or F (full-width) in Unicode. The data comes from the
unicodedata module of Python.

Go's standard library has no East Asian Width data, so the table is
generated. Run it from the repository root, with the dev shell's python3:

    nix develop -c go generate ./internal/diag

It writes widthtable.go next to this script, from any current folder.
After a Python update, the Unicode version in widthtable.go may change.
"""

import os
import unicodedata

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "widthtable.go")


def wide_ranges():
    """Yields (lo, hi) for each run of W or F characters, hi included."""
    lo = None
    for cp in range(0x110000):
        if unicodedata.east_asian_width(chr(cp)) in ("W", "F"):
            if lo is None:
                lo = cp
        elif lo is not None:
            yield lo, cp - 1
            lo = None
    if lo is not None:
        yield lo, 0x10FFFF


def main():
    r16, r32 = [], []
    for lo, hi in wide_ranges():
        if hi <= 0xFFFF:
            r16.append((lo, hi))
        elif lo > 0xFFFF:
            r32.append((lo, hi))
        else:  # a run across U+FFFF: split it
            r16.append((lo, 0xFFFF))
            r32.append((0x10000, hi))
    latin = sum(1 for lo, hi in r16 if hi <= 0xFF)

    out = [
        "// Code generated by mkwidth.py; DO NOT EDIT.",
        "",
        "package diag",
        "",
        'import "unicode"',
        "",
        "// wide holds the characters that take two cells in a terminal: the",
        "// characters whose East Asian Width is W (wide) or F (full-width) in",
        "// Unicode %s." % unicodedata.unidata_version,
        "var wide = &unicode.RangeTable{",
        "\tR16: []unicode.Range16{",
    ]
    out += ["\t\t{0x%04x, 0x%04x, 1}," % r for r in r16]
    out += ["\t},", "\tR32: []unicode.Range32{"]
    out += ["\t\t{0x%x, 0x%x, 1}," % r for r in r32]
    out += ["\t},"]
    if latin:
        out += ["\tLatinOffset: %d," % latin]
    out += ["}", ""]
    with open(OUT, "w") as f:
        f.write("\n".join(out))


main()
