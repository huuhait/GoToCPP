package libgen

import (
	"fmt"
	"path"
	"strings"
	"unicode"
)

// A RootPackage is a package that a cpp-lib offers to C++ programs (a package of the patterns of the
// build): the convenience header includes its pkg.hpp and names its namespace.
type RootPackage struct {
	ImportPath string
	Name       string // the Go package name
	Header     string // gpkg/<import path>/pkg.hpp
	Namespace  string // gpkg_example_dcom__geo
}

// CPPLibInfo is what the files of a cpp-lib say.
type CPPLibInfo struct {
	Name    string
	Version string // gocpp's version, for the pkg-config file
	Roots   []RootPackage

	// Compile are the flags that every translation unit that includes the headers needs: the
	// language flags of gocpp's C++ (-std=c++20, -fwrapv, -fno-strict-aliasing ...), -DGOCPP_NOCHECKS and
	// the sanitizers of the library's own build, and the public flags of the packages whose
	// headers include C or C++ headers.
	Compile []string

	// Link are the libraries and flags that the program needs besides the archive (-lsqlite3, from
	// the packages' directives), without the C++ runtime and the system libraries below.
	Link []string

	// Compiler is the family of the compiler that built the archive: "GNU" or "Clang", CMake's
	// names. The C++ library is the compiler's own, so a consumer built with another family may
	// not link (libstdc++ with both of them works, libc++ does not).
	Compiler string
}

// A File is a file of the installed tree, with its path relative to the prefix.
type File struct {
	Path string
	Data []byte
}

// CPPLibFiles returns the files of the installed tree of a cpp-lib besides the archive and the
// package headers: the convenience header include/<name>.hpp, the CMake package
// lib/cmake/<name>/<name>Config.cmake and the pkg-config file lib/pkgconfig/<name>.pc.
func CPPLibFiles(info CPPLibInfo) []File {
	return []File{
		{Path: path.Join("include", info.Name+".hpp"), Data: convenienceHeader(info)},
		{Path: path.Join("lib", "cmake", info.Name, info.Name+"Config.cmake"), Data: cmakeConfig(info)},
		{Path: path.Join("lib", "pkgconfig", info.Name+".pc"), Data: pkgConfig(info)},
	}
}

// system are the libraries that every program with the library needs: the C++ library, threads
// (goroutines are threads), the dynamic loader and the math library (the runtime uses them).
var system = []string{"-pthread", "-lm", "-ldl"}

func convenienceHeader(info CPPLibInfo) []byte {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	guard := "GOCPP_LIB_" + strings.ToUpper(sanitize(info.Name)) + "_HPP"
	w("// %s.hpp: the C++ API of the gocpp library %s: generated by gocpp, do not edit.\n", info.Name, info.Name)
	w("//\n// Every package of the library is in a C++ namespace of its own (gpkg_...: the import path with\n")
	w("// its characters coded: docs/spec/cpp-mapping.md); the names below are short aliases for them\n")
	w("// (define GOCPP_NO_ALIASES before including this header to leave them out). Call\n")
	w("// %s::init() once before the first call: it runs the package initialization (init functions\n", InitNamespace(info.Name))
	w("// and package variables) in Go's order; it is thread-safe and may be called again.\n")
	w("#ifndef %s\n#define %s\n\n", guard, guard)
	w("#include <gocpp/rt.hpp>\n")
	for _, r := range info.Roots {
		w("#include %q\n", r.Header)
	}
	w("\nnamespace %s {\n// init starts the library: the packages are initialized once, in Go's order.\nvoid init() noexcept;\n}\n", InitNamespace(info.Name))
	var aliases []string
	used := make(map[string]int)
	for _, r := range info.Roots {
		used[r.Name]++
	}
	for _, r := range info.Roots {
		if validAlias(r.Name) && used[r.Name] == 1 {
			aliases = append(aliases, fmt.Sprintf("namespace %s = ::%s; // %s", r.Name, r.Namespace, r.ImportPath))
		}
	}
	if len(aliases) > 0 {
		w("\n#ifndef GOCPP_NO_ALIASES\n%s\n#endif\n", strings.Join(aliases, "\n"))
	}
	w("\n#endif // %s\n", guard)
	return []byte(b.String())
}

// validAlias reports whether a package name is fit to be a C++ namespace alias: a plain name that
// is no C++ word and does not hide gp or std.
func validAlias(name string) bool {
	if name == "" || name == "main" || name == "gp" || name == "std" || !isCIdent(name) || cKeywords[name] {
		return false
	}
	for _, r := range name {
		if r > unicode.MaxASCII {
			return false
		}
	}
	return !strings.HasPrefix(name, "gp") && !strings.HasPrefix(name, "_")
}

func cmakeQuote(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`).Replace(s) + `"`
}

// compileOptions writes the compile flags as CMake generator expressions for C++ only. A flag that
// takes the next word (-iquote dir) goes through SHELL: as one option.
func compileOptions(flags []string) []string {
	var out []string
	for i := 0; i < len(flags); i++ {
		f := flags[i]
		switch f {
		case "-iquote", "-I", "-isystem", "-include", "-D", "-U":
			if i+1 < len(flags) {
				i++
				out = append(out, "$<$<COMPILE_LANGUAGE:CXX>:SHELL:"+f+" "+flags[i]+">")
				continue
			}
		}
		out = append(out, "$<$<COMPILE_LANGUAGE:CXX>:"+f+">")
	}
	return out
}

func cmakeConfig(info CPPLibInfo) []byte {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	tgt := "gocpp::" + info.Name
	w("# %sConfig.cmake: generated by gocpp, do not edit.\n#\n", info.Name)
	w("#   find_package(%s CONFIG REQUIRED)     # with CMAKE_PREFIX_PATH or %s_DIR pointing here\n", info.Name, info.Name)
	w("#   target_link_libraries(app PRIVATE %s)\n#\n", tgt)
	w("# The target carries what the headers need: the include folder, C++20 and gocpp's language flags\n")
	w("# (consumers compile gocpp's inline and template code themselves), the archive, the threads library and\n")
	w("# the libraries of the packages. Use the compiler family that built the archive (%s).\n\n", info.Compiler)
	w("include(CMakeFindDependencyMacro)\nfind_dependency(Threads)\n\n")
	w("if(NOT TARGET %s)\n", tgt)
	w("  get_filename_component(_gocpp_prefix \"${CMAKE_CURRENT_LIST_DIR}/../../..\" ABSOLUTE)\n")
	if info.Compiler != "" {
		w("  if(CMAKE_CXX_COMPILER_ID AND NOT CMAKE_CXX_COMPILER_ID STREQUAL %s)\n", cmakeQuote(info.Compiler))
		w("    message(WARNING \"%s was built with a %s C++ compiler, this project uses ${CMAKE_CXX_COMPILER_ID}: the C++ libraries may not match\")\n", info.Name, info.Compiler)
		w("  endif()\n")
	}
	w("  add_library(%s STATIC IMPORTED)\n", tgt)
	opts := compileOptions(info.Compile)
	var link []string
	link = append(link, "Threads::Threads")
	link = append(link, system[1:]...)
	link = append(link, info.Link...)
	w("  set_target_properties(%s PROPERTIES\n", tgt)
	w("    IMPORTED_LOCATION \"${_gocpp_prefix}/lib/lib%s.a\"\n", info.Name)
	w("    IMPORTED_LINK_INTERFACE_LANGUAGES \"CXX\"\n")
	w("    INTERFACE_INCLUDE_DIRECTORIES \"${_gocpp_prefix}/include\"\n")
	if len(opts) > 0 {
		w("    INTERFACE_COMPILE_OPTIONS %s\n", cmakeQuote(strings.Join(opts, ";")))
	}
	w("    INTERFACE_LINK_LIBRARIES %s)\n", cmakeQuote(strings.Join(link, ";")))
	w("  unset(_gocpp_prefix)\nendif()\n")
	return []byte(b.String())
}

func pkgConfig(info CPPLibInfo) []byte {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	w("# %s.pc: generated by gocpp, do not edit.\n", info.Name)
	w("prefix=${pcfiledir}/../..\nlibdir=${prefix}/lib\nincludedir=${prefix}/include\n\n")
	w("Name: %s\nDescription: a gocpp library (C++ API)\nVersion: %s\n", info.Name, info.Version)
	w("Cflags: -I${includedir} %s\n", strings.Join(info.Compile, " "))
	libs := append([]string{"-L${libdir}", "-l" + info.Name}, system...)
	libs = append(libs, info.Link...)
	w("Libs: %s\n", strings.Join(libs, " "))
	return []byte(b.String())
}

// Dedup returns the words in their first-seen order without repeats (for flag lists).
func Dedup(words []string) []string {
	seen := make(map[string]bool)
	var out []string
	for _, w := range words {
		if !seen[w] {
			seen[w] = true
			out = append(out, w)
		}
	}
	return out
}

// Name returns s as the name of a library: letters, digits, _ and -, so that it is the name of a file, a
// CMake target and, with the other characters as _, a C++ namespace.
func Name(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch {
		case r < unicode.MaxASCII && (unicode.IsLetter(r) || unicode.IsDigit(r)), r == '_', r == '-':
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	if b.Len() == 0 {
		return "lib"
	}
	return b.String()
}
