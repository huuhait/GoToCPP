package libgen

import (
	"fmt"
	"strings"
)

// HeaderInfo is what the C header and the glue say about a library.
type HeaderInfo struct {
	Name    string   // the library's name: the header's guard and its comments
	Mode    string   // "c-archive" or "c-shared", for the comment
	Link    []string // what a program that uses the library must link besides it (-lstdc++ ...)
	Exports []*Export
}

// ReturnStruct is the name of the struct that the C function e returns when it has several
// results (cgo's: <name>_return, with the members r0, r1, ...).
func (e *Export) ReturnStruct() string { return e.Name + "_return" }

// Ret returns the C type that the function returns: void, the type of its one result, or the struct
// of several.
func (e *Export) Ret() string {
	switch len(e.Results) {
	case 0:
		return "void"
	case 1:
		return e.Results[0].C
	}
	return "struct " + e.ReturnStruct()
}

// ParamNames returns the names of the C parameters: the Go names, and pN where a Go name is
// missing, blank, a C word or used already.
func (e *Export) ParamNames() []string {
	used := make(map[string]bool)
	names := make([]string, len(e.Params))
	for i, p := range e.Params {
		n := p.Name
		if n == "" || n == "_" || !isCIdent(n) || cKeywords[n] || reservedNames[n] || used[n] || strings.HasPrefix(n, "gp_") || strings.HasPrefix(n, "gocpp_") {
			n = fmt.Sprintf("p%d", i)
		}
		for used[n] {
			n += "_"
		}
		used[n] = true
		names[i] = n
	}
	return names
}

// Header returns the C header of the library: cgo's types (GoInt, GoString, GoSlice ...), the
// structs of the functions with several results, and the declarations. It is valid C and C++.
func Header(h HeaderInfo) []byte {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	guard := "GOCPP_" + strings.ToUpper(sanitize(h.Name)) + "_H"
	w("/* Code generated by gocpp. DO NOT EDIT. */\n\n")
	w("/* %s, built with gocpp build -buildmode=%s.\n", h.Name, h.Mode)
	if len(h.Link) > 0 {
		w("   Link a program with: %s */\n", strings.Join(h.Link, " "))
	} else {
		w("   */\n")
	}
	w("\n#ifndef %s\n#define %s\n\n", guard, guard)
	w("#include <stddef.h>\n\n")
	w("#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n")
	w("/* The functions are the ones of the Go package marked //export. Go's types are copied at the\n")
	w("   boundary: a GoString or GoSlice parameter is read during the call only; a GoString or\n")
	w("   GoSlice result is a copy in malloc memory that the caller frees with free(). */\n\n")
	w("#ifndef GOCPP_EXPORT\n")
	w("#if defined(_WIN32)\n#define GOCPP_EXPORT __declspec(dllexport)\n")
	w("#elif defined(__GNUC__)\n#define GOCPP_EXPORT __attribute__((visibility(\"default\")))\n")
	w("#else\n#define GOCPP_EXPORT\n#endif\n#endif\n\n")
	w("typedef signed char GoInt8;\ntypedef unsigned char GoUint8;\ntypedef short GoInt16;\ntypedef unsigned short GoUint16;\n")
	w("typedef int GoInt32;\ntypedef unsigned int GoUint32;\ntypedef long long GoInt64;\ntypedef unsigned long long GoUint64;\n")
	w("typedef GoInt64 GoInt;\ntypedef GoUint64 GoUint;\ntypedef size_t GoUintptr;\ntypedef float GoFloat32;\ntypedef double GoFloat64;\n")
	w("#ifndef GO_CGO_GOSTRING_TYPEDEF\n")
	w("typedef struct { const char *p; ptrdiff_t n; } _GoString_;\n")
	w("#endif\ntypedef _GoString_ GoString;\n")
	w("typedef void *GoMap;\ntypedef void *GoChan;\ntypedef struct { void *t; void *v; } GoInterface;\n")
	w("typedef struct { void *data; GoInt len; GoInt cap; } GoSlice;\n\n")
	for _, e := range h.Exports {
		if len(e.Results) > 1 {
			w("struct %s {\n", e.ReturnStruct())
			for i, r := range e.Results {
				w("\t%s r%d;\n", r.C, i)
			}
			w("};\n\n")
		}
	}
	for _, e := range h.Exports {
		if e.Doc != "" {
			w("/* %s\n   (%s) */\n", strings.ReplaceAll(strings.TrimSpace(e.Doc), "\n", "\n   "), e.Pkg.Load.ImportPath+"."+e.Name)
		}
		w("extern GOCPP_EXPORT %s %s(", e.Ret(), e.Name)
		if len(e.Params) == 0 {
			w("void")
		}
		names := e.ParamNames()
		for i, p := range e.Params {
			if i > 0 {
				w(", ")
			}
			w("%s %s", p.C, names[i])
		}
		w(");\n")
		if e.Doc != "" {
			w("\n")
		}
	}
	w("\n#ifdef __cplusplus\n}\n#endif\n\n#endif /* %s */\n", guard)
	return []byte(b.String())
}

// sanitize turns s into letters, digits and _ (for a guard and for names of C++ namespaces).
func sanitize(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case 'a' <= c && c <= 'z', 'A' <= c && c <= 'Z', '0' <= c && c <= '9':
			b.WriteByte(c)
		default:
			b.WriteByte('_')
		}
	}
	return b.String()
}

// VersionScript returns the linker's version script of a shared library: the exported functions are
// global, every other symbol is local (a C++ template that the C++ library's headers instantiate
// is weak and visible otherwise, and merges with the same symbol of another library in the
// process).
func VersionScript(exports []*Export) []byte {
	var b strings.Builder
	b.WriteString("{\n  global:\n")
	for _, e := range exports {
		fmt.Fprintf(&b, "    %s;\n", e.Name)
	}
	b.WriteString("  local:\n    *;\n};\n")
	return []byte(b.String())
}
