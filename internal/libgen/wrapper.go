package libgen

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/huuhait/gocpp/internal/check"
)

// PkgInfo is what the glue needs to know about the C++ of a package: the include line of its
// header, its namespace and the C++ names of its functions (cppgen.PackageFiles).
type PkgInfo struct {
	Header    string            // gpkg/<import path>/pkg.hpp
	Namespace string            // gpkg_main
	Funcs     map[string]string // Go name -> C++ name
}

// GlueInfo is what Glue writes the extern "C" functions from.
type GlueInfo struct {
	Name    string // the library's name
	Header  string // the include line of the C header: gpkg_export/libx.h
	Exports []*Export
	Pkg     func(*check.Package) PkgInfo
}

// InitFunc is the function that the glue starts the program with: the generated gp_init_all of the
// last package (lower.Options.Library).
const InitFunc = "gp_init_all"

// Glue returns the C++ file with the extern "C" functions of the exports (gocpp/lib.hpp says what
// each does): it includes the headers of the packages, then the C header, so that a function's C
// signature is checked against the header's.
func Glue(g GlueInfo) []byte {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	w("// gocpp_export.cpp: the C functions of the //export directives of %s: generated by gocpp, do not edit\n", g.Name)
	seen := make(map[string]bool)
	for _, e := range g.Exports {
		h := g.Pkg(e.Pkg).Header
		if !seen[h] {
			seen[h] = true
			w("#include %q\n", h)
		}
	}
	w("#include <gocpp/lib.hpp>\n#include %q\n\n", g.Header)
	w("void %s(); // the program's package initialization, written into the last package\n\n", InitFunc)
	for _, e := range g.Exports {
		pi := g.Pkg(e.Pkg)
		fn := pi.Namespace + "::" + pi.Funcs[e.Name]
		names := e.ParamNames()
		w("#line %d %s\n", e.Pos.Line, strconv.Quote(e.Pos.Filename))
		w("extern \"C\" GOCPP_EXPORT %s %s(", e.Ret(), e.Name)
		if len(e.Params) == 0 {
			w("void")
		}
		for i, p := range e.Params {
			if i > 0 {
				w(", ")
			}
			w("%s %s", p.C, names[i])
		}
		w(") {\n")
		w("    return gp::lib::guard(&::%s, [&]() -> %s {\n", InitFunc, e.Ret())
		var args []string
		for i := range e.Params {
			args = append(args, fmt.Sprintf("gp::lib::in<&%s, %d>(%s)", fn, i, names[i]))
		}
		call := fn + "(" + strings.Join(args, ", ") + ")"
		switch len(e.Results) {
		case 0:
			w("        %s;\n", call)
		case 1:
			w("        return gp::lib::out<%s>(%s);\n", e.Results[0].C, call)
		default:
			w("        auto r = %s;\n", call)
			var parts []string
			for i, r := range e.Results {
				parts = append(parts, fmt.Sprintf("gp::lib::out<%s>(std::get<%d>(r))", r.C, i))
			}
			w("        return %s{%s};\n", e.ReturnStruct(), strings.Join(parts, ", "))
		}
		w("    });\n}\n\n")
	}
	return []byte(b.String())
}

// InitUnit returns the C++ file of a cpp-lib that starts the program: gocpp_<id>::init(), which a C++
// program calls before it uses the packages (it runs the package initialization once, thread-safe,
// and may be called again).
func InitUnit(name string) []byte {
	return []byte(fmt.Sprintf(`// gocpp_init.cpp: the start of the library %s: generated by gocpp, do not edit
#include <gocpp/lib.hpp>

void %s(); // the program's package initialization, written into the last package

namespace %s {

void init() noexcept {
    gp::lib::enter(&::%s);
}

} // namespace %s
`, name, InitFunc, InitNamespace(name), InitFunc, InitNamespace(name)))
}

// InitNamespace is the C++ namespace of the init function of the library with the name name.
func InitNamespace(name string) string { return "gocpp_" + sanitize(name) }
