// Package doc shows the documentation of gocpp packages, like go doc does
// for Go: "gocpp doc" (cmd/gocpp/doc.go) is a thin command line over it.
//
// What it does follows cmd/doc of Go 1.25.14 (cmd/internal/doc: main.go,
// pkg.go and dirs.go, which this package ports; LICENSE is Go's license):
//
//	gocpp doc                         the package in the current folder
//	gocpp doc <pkg>                   a package: its comment and a summary
//	gocpp doc <sym>[.<methodOrField>] a symbol of the package in the folder
//	gocpp doc [<pkg>.]<sym>[.<methodOrField>]
//	gocpp doc [<pkg>.][<sym>.]<methodOrField>
//	gocpp doc <pkg> <sym>[.<methodOrField>]
//
// with the flags -all, -src, -u, -c, -short and -cmd, and with the same
// rules to find the package (a partial import path is searched in the
// standard library, the main module and the required modules; the first
// match is shown, and a symbol that is not in it is looked for in the next
// match), to match a symbol (a name without capitals matches in either
// case), and to write the result (the declarations are printed by gocpp's
// printer, the comments by go/doc/comment with the same width and
// indentation as go doc). For the same source, the output is the same as
// go doc's, byte for byte; the differential test of this package checks
// that against the real go doc.
//
// What gocpp adds:
//
//   - The source is .gp files, read with gocpp's parser, so the syntax of
//     Phase 10 is documented as written: func f!() T, macro Name(p lazy T),
//     the macros on top of a func or a type (printed above the
//     declaration), and the methods that #Derive(...) generates (listed
//     with the methods of the type, as "generated by #Derive").
//   - The packages are found with gocpp's rules: the standard library
//     (embedded in gocpp, documented from its .gp files), the main module
//     (found by its gocpp.mod file) and the modules it requires (replaced
//     folders, vendor/, and the module cache), with the build constraints
//     of the target (GOOS, GOARCH, Env.Tags).
//   - A C or C++ header is an opaque package: "gocpp doc '<stdio.h>'" says
//     where the header is and which name it gets in a .gp file, and lists
//     the declarations with a Doxygen-style comment (/// //! /** */ /*! */)
//     in front of them, read textually from the header file itself (not
//     from the headers it includes); with a name ("gocpp doc '<vector>'
//     std.vector") it also asks the C++ compiler what the name is (the
//     kind probe of internal/interop). "gocpp doc std" explains the C++
//     namespace std.
//
// Not built: -http (the pkgsite server), and the import comments of Go's
// old GOPATH rules.
//
// Render is the part that an editor can reuse: it writes the documentation
// of one symbol of a Package that the caller read (from the file system,
// or from the buffers of an editor).
package doc

import (
	"context"
	"io"
	"io/fs"
)

// Options are the flags of "gocpp doc".
type Options struct {
	Unexported bool // -u: show unexported symbols as well as exported
	MatchCase  bool // -c: symbol matching honors case (paths not affected)
	All        bool // -all: show all documentation for the package
	Cmd        bool // -cmd: show symbols with package docs even if package is a command
	Src        bool // -src: show the source code for the symbol
	Short      bool // -short: one-line representation for each symbol
	Examples   bool // -examples: list the examples of the _test.gp files (gocpp only)
}

// An Env says where Run finds packages and files.
type Env struct {
	// Dir is the current folder: the folder of "gocpp doc" with no
	// argument, and the folder that relative paths and the module are
	// found from. If it is empty, Run uses the current folder of the
	// process.
	Dir string

	// GOOS and GOARCH are the target of the build constraints; empty
	// means the system that runs Run. Tags are more build tags.
	GOOS, GOARCH string
	Tags         []string

	// Stdlib holds the standard packages, one folder for each import
	// path; nil means the embedded standard library of gocpp (package
	// stdlib). StdlibDir is the folder that names of its files start
	// with in messages and in "-src"; empty means "$GOCPP/stdlib".
	Stdlib    fs.FS
	StdlibDir string

	// Context stops the C++ compiler runs for headers. nil means
	// context.Background().
	Context context.Context

	// Warn, if not nil, receives the messages about folders that the scan
	// for packages cannot read ("gocpp doc: open /x/locked: permission
	// denied"), as go doc logs them; the scan goes on. "gocpp doc" sets
	// it to the standard error; nil drops them (an editor has nobody to
	// tell).
	Warn io.Writer

	// Probe, if not nil, replaces the compiler runs for headers (the
	// tests of this package and of an editor use it): it finds the file
	// of a system header, and asks the kind of a C++ path (see
	// HeaderProbe).
	Probe HeaderProbe
}

// A HeaderProbe asks the C++ compiler about headers. The implementation of
// Env.Probe is nil, which means the compiler of the target (internal/build,
// internal/interop).
type HeaderProbe interface {
	// FindHeader returns the absolute file that the system header name
	// ("stdio.h", "vector": without the <>) is, or "" if it can't be
	// found.
	FindHeader(ctx context.Context, name string) (file string, err error)

	// Kind says what the C++ path (std::vector) is after the include
	// text includes ("<vector>", or "\"/abs/x.h\""): one of "namespace",
	// "type", "template", "value", "value template", "macro", "not found",
	// or "unknown" (with the reason in err when the includes don't work).
	Kind(ctx context.Context, includes []string, path string) (kind string, err error)
}

// A UsageError is an error of the command line: wrong number of arguments,
// or a symbol with too many periods. "gocpp doc" exits with status 2 for
// it, and 1 for any other error.
type UsageError struct{ Msg string }

func (e *UsageError) Error() string { return e.Msg }

// Run is "gocpp doc" without the flag parsing: it finds the package and the
// symbol that args name (zero, one or two arguments, see the package
// comment) and writes their documentation to w.
func Run(w io.Writer, env *Env, opts Options, args []string) error {
	r := newRunner(w, env, opts)
	return r.run(args)
}

// Render writes the documentation of one symbol of pkg to w, the part of
// Run that an editor can reuse (hover, completion details): pkg comes from
// the caller, who read the files from the file system or from the buffers of
// an editor, so Render needs no Env.
//
// symbol is what the user would type after the package: "" for the package
// itself, "Name" for a const, var, func, macro or type, "Type.Method" or
// "Type.Field" for a method or a field. As in the command line, a name
// without capitals matches in either case unless opts.MatchCase is set. A
// symbol that pkg does not have is an error that reads like the one of
// "gocpp doc" ("no symbol X in package P"). The output is what "gocpp doc"
// prints for the same package and symbol, flags included.
func Render(w io.Writer, pkg *Package, symbol string, opts Options) error {
	sym, method, err := parseSymbol(symbol)
	if err != nil {
		return err
	}
	s, err := newSession(w, opts, pkg, pkg.ImportPath)
	if err != nil {
		return err
	}
	found, err := s.render(sym, method)
	if ferr := s.flush(); ferr != nil && err == nil {
		err = ferr
	}
	if err != nil {
		return err
	}
	if !found {
		return failMessage([]string{s.prettyPath()}, sym, method)
	}
	return nil
}

// ReadDir reads the package in the folder rel of fsys (slash-separated, "."
// for the root), with the build constraints of the target of e, and gives it
// the import path importPath. It is how a caller that has no buffers (the
// tests, a tool) makes a Package for Render. Messages name the folder by
// its path in fsys.
func (e *Env) ReadDir(fsys fs.FS, rel, importPath string) (*Package, error) {
	return e.readPackage(fsys, rel, rel, importPath, false)
}
