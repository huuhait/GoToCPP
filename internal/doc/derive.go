package doc

import (
	"go/ast"
	godoc "go/doc"
	"sort"
	"strings"
	"unicode"
	"unicode/utf8"

	"github.com/huuhait/gocpp/internal/syntax/parser"
)

// derivedMethods are the methods that each #Derive(...) name generates, as
// Phase 10's README (§2.2) says: the signature follows from the derive name,
// so a caller type-checks before the bodies exist. %R is the receiver name
// and %T the type with its type parameters.
var derivedMethods = map[string][]struct{ sig, name string }{
	"String": {{"func (%R %T) String() string", "String"}},
	"Equal":  {{"func (%R %T) Equal(other %T) bool", "Equal"}},
	"Clone":  {{"func (%R %T) Clone() %T", "Clone"}},
	"JSON": {
		{"func (%R %T) MarshalJSON() ([]byte, error)", "MarshalJSON"},
		{"func (%R *%T) UnmarshalJSON(data []byte) error", "UnmarshalJSON"},
	},
}

// addDerived adds the methods that the lines "#Derive(String, Equal)" on top
// of a type generate to the methods of the type, in the order of the names,
// with a doc comment that says where they come from: the methods are in no
// .gp file until gocpp expand writes them. A method that the package
// declares itself is not added.
func (s *session) addDerived() {
	for _, typ := range s.doc.Types {
		var names []string
		for _, call := range s.ps.onTopCalls[typ.Decl] {
			if id, ok := call.Fun.(*ast.Ident); !ok || id.Name != "#Derive" {
				continue
			}
			for _, a := range call.Args {
				if id, ok := a.(*ast.Ident); ok {
					names = append(names, id.Name)
				}
			}
		}
		if len(names) == 0 {
			continue
		}
		tname := typ.Name
		if spec := s.findTypeSpec(typ.Decl, typ.Name); spec != nil && spec.TypeParams.NumFields() > 0 {
			var params []string
			for _, f := range spec.TypeParams.List {
				for _, n := range f.Names {
					params = append(params, n.Name)
				}
			}
			tname += "[" + strings.Join(params, ", ") + "]"
		}
		r, _ := utf8.DecodeRuneInString(typ.Name)
		recv := string(unicode.ToLower(r))
		for _, d := range names {
			for _, m := range derivedMethods[d] {
				if hasMethod(typ, m.name) {
					continue
				}
				src := strings.NewReplacer("%R", recv, "%T", tname).Replace(m.sig)
				f, err := parser.ParseFile(s.fs, "derive:"+typ.Name+"."+m.name, "package p\n"+src, parseMode)
				if err != nil || len(f.Decls) != 1 {
					continue
				}
				decl, ok := f.Decls[0].(*ast.FuncDecl)
				if !ok {
					continue
				}
				typ.Methods = append(typ.Methods, &godoc.Func{
					Doc:  m.name + " is generated by #Derive(" + d + ").\n",
					Name: m.name,
					Decl: decl,
					Recv: tname,
					Orig: typ.Name,
				})
			}
		}
		sort.SliceStable(typ.Methods, func(i, j int) bool { return typ.Methods[i].Name < typ.Methods[j].Name })
	}
}

// hasMethod reports whether typ has a method with this name.
func hasMethod(typ *godoc.Type, name string) bool {
	for _, m := range typ.Methods {
		if m.Name == name {
			return true
		}
	}
	return false
}
