package typedinterop

import "testing"

func TestClangLocalHeaders(t *testing.T) {
	runCases(t, []clangCase{
		{name: "struct fields", imports: libImport, header: `struct S { int a; const char* name; double d; unsigned char u[4]; };`,
			body: "\tvar s lib.S\n\tx := s.a\n\ty := s.name\n\tz := s.d\n\tw := s.u\n\t_, _, _, _ = x, y, z, w",
			want: []expect{{"s.a", "lvalue int"}, {"s.name", "lvalue const char *"}, {"s.d", "lvalue double"}, {"s.u", "lvalue unsigned char [4]"}}},
		{name: "field through a pointer", imports: libImport, header: `struct S { int a; };`,
			body: "\tvar p *lib.S\n\tx := p.a\n\t_ = x",
			want: []expect{{"p.a", "lvalue int"}}},
		{name: "const and non-const members", imports: libImport, header: `struct C { int get() const; int set(int); const int& cref() const; int& ref(); };`,
			body: "\tvar c lib.C\n\ta := c.get()\n\tb := c.set(1)\n\tr := c.cref()\n\ts := c.ref()\n\t_, _, _, _ = a, b, r, s",
			want: []expect{{"c.get()", "prvalue int"}, {"c.set(1)", "prvalue int"}, {"c.cref()", "lvalue const int"}, {"c.ref()", "lvalue int"}}},
		{name: "static members", imports: libImport, header: `struct Z { static int count; static constexpr int K = 5; static int twice(int x); }; inline int Z::count = 0;`,
			body: "\tconst k = lib.Z.K\n\tc := lib.Z.count\n\ttw := lib.Z.twice(4)\n\t_, _, _ = k, c, tw",
			want: []expect{{"C.Z.K", "lvalue const int = 5"}, {"C.Z.count", "lvalue int"}, {"C.Z.twice(4)", "prvalue int"}}},
		{name: "unscoped enum", imports: libImport, header: `enum Color { Red = 1, Green = 2, Blue = 4 };`,
			body: "\tconst g = lib.Green\n\tvar c lib.Color = lib.Blue\n\t_, _ = g, c",
			want: []expect{{"C.Green", "prvalue Color = 2"}, {"C.Blue", "prvalue Color"}}},
		{name: "scoped enum", imports: libImport, header: `enum class Mode : unsigned char { A = 3, B = 250 };`,
			body: "\tconst a = lib.Mode.A\n\t_ = a",
			want: []expect{{"C.Mode.A", "prvalue Mode = 3"}}},
		{name: "union", imports: libImport, header: `union U { int i; float f; };`,
			body: "\tvar u lib.U\n\tx := u.f\n\ty := u.i\n\t_, _ = x, y",
			want: []expect{{"u.f", "lvalue float"}, {"u.i", "lvalue int"}}},
		{name: "bit fields", imports: libImport, header: `struct B { unsigned a : 3; unsigned b : 5; };`,
			body: "\tvar b lib.B\n\tx := b.a\n\t_ = x",
			want: []expect{{"b.a", "lvalue unsigned int"}}},
		{name: "references and pointers", imports: libImport, header: `inline int g = 0; int& ref(int& x) { return x; } const int& cref(const int& x) { return x; } int* ptr(int* p) { return p; }`,
			body: "\tvar k C.int\n\tvar q *C.int\n\ta := lib.ref(k)\n\tb := lib.cref(1)\n\tc := lib.ptr(q)\n\t_, _, _ = a, b, c",
			want: []expect{{"C.ref(k)", "lvalue int"}, {"C.cref(1)", "lvalue const int"}, {"C.ptr(q)", "prvalue int *"}}},
		{name: "a lvalue reference does not bind a temporary", imports: libImport + impString, header: `#include <string>
void take(std::string& s);`,
			body: "\ts := std.string(\"a\")\n\tlib.take(s)\n\tlib.take(std.string(\"b\"))",
			want: []expect{{"C.take(s)", "prvalue void"}, {"C.take(C.std.string(\"b\"))", "~error: "}}},
		{name: "a reference parameter does not take a Go int", imports: libImport, header: `int& ref(int& x);`,
			body: "\tk := 3\n\tx := lib.ref(k)\n\t_ = x",
			want: []expect{{"C.ref(k)", "~error: non-const lvalue reference to type 'int' cannot bind"}}},
		{name: "overloads", imports: libImport, header: `int f(int); double f(double); const char* f(const char*);`,
			body: "\ta := lib.f(1)\n\tb := lib.f(1.5)\n\tc := lib.f(\"x\")\n\t_, _, _ = a, b, c",
			want: []expect{{"C.f(1)", "prvalue int"}, {"C.f(1.5)", "prvalue double"}, {"C.f(\"x\")", "prvalue const char *"}}},
		{name: "an ambiguous call lists its candidates", imports: libImport, header: `int f(int); double f(double); float f(float);`,
			body: "\tk := 3\n\tx := lib.f(k)\n\t_ = x",
			want: []expect{{"C.f(k)", "error: call to 'f' is ambiguous"}}},
		{name: "operators", imports: libImport, header: `struct V { int x; V operator+(const V&) const; bool operator==(const V&) const; int operator[](int) const; V operator-() const; };`,
			body: "\tvar a, b lib.V\n\tc := a + b\n\td := a == b\n\te := a[1]\n\tf := -a\n\t_, _, _, _ = c, d, e, f",
			want: []expect{{"a + b", "prvalue V"}, {"a == b", "prvalue bool"}, {"a[1]", "prvalue int"}, {"-a", "prvalue V"}}},
		{name: "conversion operators", imports: libImport, header: `struct W { operator int() const; };`,
			body: "\tvar w lib.W\n\tn := int(w)\n\tm := w + 1\n\t_, _ = n, m",
			want: []expect{{"int(w)", "prvalue long"}, {"w + 1", "prvalue int"}}},
		{name: "templates with default arguments", imports: libImport, header: `template <class T, class U = int> struct P { T a; U b; };`,
			body: "\tvar p lib.P[C.long]\n\tx := p.b\n\ty := p.a\n\t_, _ = x, y",
			want: []expect{{"p.b", "lvalue int"}, {"p.a", "lvalue long"}}},
		{name: "auto return", imports: libImport, header: `inline auto mk() { return 3.5; } inline auto gen(int n) { return n + 1L; }`,
			body: "\tx := lib.mk()\n\ty := lib.gen(2)\n\t_, _ = x, y",
			want: []expect{{"C.mk()", "prvalue double"}, {"C.gen(2)", "prvalue long"}}},
		{name: "incomplete and deleted", imports: libImport, header: `struct Inc; Inc* mkp(); void del() = delete;`,
			body: "\tp := lib.mkp()\n\tlib.del()\n\t_ = p",
			want: []expect{{"C.mkp()", "prvalue Inc *"}, {"C.del()", "~error: attempt to use a deleted function"}}},
		{name: "sfinae failure", imports: libImport, header: `#include <type_traits>
template <class T> std::enable_if_t<std::is_integral_v<T>, T> only(T x);`,
			body: "\ta := lib.only(2)\n\tb := lib.only(2.5)\n\t_, _ = a, b",
			want: []expect{{"C.only(2)", "prvalue int"}, {"C.only(2.5)", "~error: no matching function for call to 'only'"}}},
		{name: "nested types", imports: libImport, header: `struct Outer { struct In { int v; }; using T = long; enum E { X = 4 }; };`,
			body: "\tvar i lib.Outer.In\n\tvar t lib.Outer.T\n\tconst x = lib.Outer.X\n\t_, _, _ = i, t, x",
			want: []expect{{"C.Outer.In", "type Outer::In"}, {"C.Outer.T", "type long"}, {"C.Outer.X", "prvalue Outer::E = 4"}}},
		{name: "typedefs", imports: libImport, header: `typedef unsigned int u32; using Handle = struct Impl*;`,
			body: "\tvar a lib.u32\n\tvar h lib.Handle\n\t_, _ = a, h",
			want: []expect{{"C.u32", "type unsigned int"}, {"C.Handle", "type Impl *"}}},
		{name: "function pointers", imports: libImport, header: `typedef int (*cb)(int); cb get_cb();`,
			body: "\tf := lib.get_cb()\n\t_ = f",
			want: []expect{{"C.get_cb()", "prvalue int (*)(int)"}}},
		{name: "arrays", imports: libImport, header: `inline int table[4] = {1, 2, 3, 4};`,
			body: "\tx := lib.table[2]\n\tt := lib.table\n\t_, _ = x, t",
			want: []expect{{"C.table[2]", "lvalue int"}, {"C.table", "lvalue int [4]"}}},
		{name: "member of a returned struct is an xvalue", imports: libImport, header: `struct Pt { int x; int y; }; Pt mk();`,
			body: "\tx := lib.mk().x\n\t_ = x",
			want: []expect{{"C.mk().x", "xvalue int"}}},
		{name: "constructors", imports: libImport, header: `struct K { K(int); K(const char*); int n; };`,
			body: "\ta := lib.K(3)\n\tb := lib.K(\"s\")\n\t_, _ = a, b",
			want: []expect{{"C.K(3)", "prvalue K"}, {"C.K(\"s\")", "prvalue K"}}},
		{name: "keyed literal", imports: libImport, header: `struct Rect { int x, y, w, h; };`,
			body: "\tr := lib.Rect{x: 1, y: 2, w: 3, h: 4}\n\t_ = r",
			want: []expect{{"C.Rect{…}", "prvalue Rect"}}},
		{name: "function-like macro", imports: libImport, header: `#define SQ(x) ((x) * (x))`,
			body: "\tn := lib.SQ(3)\n\t_ = n",
			want: []expect{{"C.SQ(3)", "prvalue int"}}},
		{name: "string macro", imports: libImport, header: `#define NAME "My" "App"`,
			body: "\tconst s = lib.NAME\n\t_ = s",
			want: []expect{{"C.NAME", `~= "MyApp"`}}},
		{name: "float macros are exact", imports: libImport, header: `#define TAU 6.283185307179586
#define HALF (TAU / 2)
#define TINY 1e-300`,
			body: "\tconst a = lib.TAU\n\tconst b = lib.HALF\n\tconst c = lib.TINY\n\t_, _, _ = a, b, c",
			want: []expect{{"C.TAU", "prvalue double = 6.283185307179586"}, {"C.HALF", "prvalue double = 3.141592653589793"}, {"C.TINY", "prvalue double = 1e-300"}}},
		{name: "unsigned long long macro", imports: libImport, header: `#define BIG 18446744073709551615ULL
#define NEG (-(1 << 4))
#define SHIFT (1 << 3)`,
			body: "\tconst a = lib.BIG\n\tconst b = lib.NEG\n\tconst c = lib.SHIFT\n\t_, _, _ = a, b, c",
			want: []expect{{"C.BIG", "prvalue unsigned long long = 18446744073709551615"}, {"C.NEG", "prvalue int = -16"}, {"C.SHIFT", "prvalue int = 8"}}},
		{name: "a macro of an enumerator", imports: libImport, header: `enum E { One = 1, Two = 2 };
#define DEFAULT_E Two`,
			body: "\tvar d [lib.DEFAULT_E]int\n\t_ = d",
			want: []expect{{"C.DEFAULT_E", "prvalue E = 2"}}},
		{name: "constexpr function in a constant context", imports: libImport, header: `constexpr int sq(int x) { return x * x; }`,
			body: "\tconst k = lib.sq(4)\n\t_ = k",
			want: []expect{{"C.sq(4)", "prvalue int = 16"}}},
		{name: "unknown function", imports: libImport, header: `int known();`,
			body: "\tx := lib.nosuch(1)\n\t_ = x",
			want: []expect{{"C.nosuch(1)", "~nosuch"}}},
		{name: "unknown member", imports: libImport, header: `struct S { int a; };`,
			body: "\tvar s lib.S\n\tx := s.nosuch\n\t_ = x",
			want: []expect{{"s.nosuch", "error: no member named 'nosuch' in 'S'"}}},
		{name: "chain of locals", imports: libImport, header: `struct H { int get() const; }; H mk();`,
			body: "\tx := lib.mk()\n\ty := x.get()\n\tz := y + 1\n\t_ = z",
			want: []expect{{"local:z", "type int"}, {"local:x", "type H"}, {"x.get()", "prvalue int"}}},
		{name: "address of and dereference", imports: libImport, header: `struct S { int a; };`,
			body: "\tvar s lib.S\n\tp := &s\n\tq := *p\n\t_, _ = p, q",
			want: []expect{{"&s", "prvalue S *"}, {"*p", "lvalue S"}}},
		{name: "Go string to string_view", imports: libImport, header: `#include <string_view>
void sv(std::string_view); void cs(const char*);`,
			body: "\tgs := \"abc\"\n\tlib.sv(gs)\n\tlib.cs(gs)",
			want: []expect{{"C.sv(gs)", "prvalue void"}, {"C.cs(gs)", "~error: no viable conversion from 'gocpp_probe_internal_pr::string' to 'const char *'"}}},
		{name: "cgo tag names", imports: libImport, header: `struct pair_s { int a; int b; }; int sum(struct pair_s p);`,
			body: "\tvar p lib.struct_pair_s\n\tn := lib.sum(p)\n\t_ = n",
			want: []expect{{"C.struct_pair_s", "type pair_s"}, {"C.sum(p)", "prvalue int"}}},
		{name: "keyed literal of a non-aggregate", imports: "\t\"<utility>\"\n",
			body: "\tp := std.pair[C.int, C.double]{second: 2.5, first: 3}\n\t_ = p",
			want: []expect{{"C.std.pair[C.int, C.double]{…}", "prvalue std::pair<int, double>"}}},
		{name: "multi-word C types in a conversion", imports: libImport, header: `long long twice(long long x);`,
			body: "\tf := 2.5\n\tn := lib.twice(C.longlong(f))\n\t_ = n",
			want: []expect{{"C.twice(C.longlong(f))", "prvalue long long"}, {"C.longlong(f)", "prvalue long long"}}},
		{name: "string of a std::string", imports: libImport + impString, header: `#include <string>
std::string name();`,
			body: "\ts := string(lib.name())\n\t_ = s",
			want: []expect{{"string(C.name())", "~prvalue gocpp_probe_internal_pr::string"}}},
		{name: "index of a pointer result", imports: libImport + impVector, header: `#include <vector>
std::vector<int>& vec();`,
			body: "\tx := lib.vec().data()[1]\n\t_ = x",
			want: []expect{{"C.vec().data()[1]", "lvalue int"}}},
		{name: "inline namespaces", imports: libImport + "\tinner \"::outer::inner\"\n", header: `namespace outer { namespace inner { int f(); } inline namespace v1 { int g(); } }`,
			body: "\ta := inner.f()\n\t_ = a",
			want: []expect{{"C.inner.f()", "prvalue int"}}},
	})
}
