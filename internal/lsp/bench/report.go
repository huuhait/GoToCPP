func oneLine(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	if len(s) > 200 {
		s = s[:200] + "..."
	}
	return s
}

func sortByOrder(names []string) []string {
	set := map[string]bool{}
	for _, n := range names {
		set[n] = true
	}
	return orderedNames(set)
}

func thousands(n int) string {
	s := strconv.Itoa(n)
	var out []byte
	for i, c := range s {
		if i > 0 && (len(s)-i)%3 == 0 {
			out = append(out, ',')
		}
		out = append(out, byte(c))
	}
	return string(out)
}

// scenarioOf is r.Scenario for a result that may be nil.
func scenarioOf(r *ProjectResult, name string) *ScenarioResult {
	if r == nil {
		return nil
	}
	return r.Scenario(name)
}
