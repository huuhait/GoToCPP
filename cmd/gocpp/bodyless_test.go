package main

import (
	"strings"
	"testing"
)

const bodylessProgram = "package main\n\nfunc add(a, b int32) int32\n\nfunc main() {}\n"

const bindgenViewMark = "// Code generated by gocpp bindgen from <lib.h>. DO NOT EDIT.\n\n"

// TestBodylessFunctionCheck: gocpp check refuses a function without a body, unless
// GOCPP_ALLOW_BODYLESS=1, which the runner of Go's own test files sets (tools/gotest).
func TestBodylessFunctionCheck(t *testing.T) {
	t.Chdir(t.TempDir())
	writeFiles(t, ".", map[string]string{"gocpp.mod": "module example.com/m\n", "main.gp": bodylessProgram})

	t.Run("default", func(t *testing.T) {
		r := gocppRun("", false, "check", ".")
		if r.code != 1 || !strings.Contains(r.stderr, "main.gp:3:6: missing function body") {
			t.Errorf("exit %d, stderr %q, want exit 1 and the missing body", r.code, r.stderr)
		}
	})
	t.Run("allowed", func(t *testing.T) {
		t.Setenv("GOCPP_ALLOW_BODYLESS", "1")
		if r := gocppRun("", false, "check", "."); r.code != 0 || r.stderr != "" {
			t.Errorf("exit %d, stderr %q, want a clean check", r.code, r.stderr)
		}
	})
}

// TestBuildBindgenView: a view that gocpp bindgen wrote passes gocpp check and is not built; the
// build says so, without "this is a bug in gocpp".
func TestBuildBindgenView(t *testing.T) {
	t.Chdir(t.TempDir())
	writeFiles(t, ".", map[string]string{
		"gocpp.mod": "module example.com/m\n",
		"main.gp":   bindgenViewMark + bodylessProgram,
	})
	if r := gocppRun("", false, "check", "."); r.code != 0 || r.stderr != "" {
		t.Fatalf("check: exit %d, stderr %q, want a clean check", r.code, r.stderr)
	}

	r := gocppRun("", false, "build", "-o", "view", ".")
	want := "main.gp:5:6: missing function body (a gocpp bindgen view is for reading; it is not built)"
	if r.code != 1 || !strings.Contains(r.stderr, want) {
		t.Errorf("build: exit %d, stderr %q, want exit 1 and %q", r.code, r.stderr, want)
	}
	if strings.Contains(r.stderr, "bug in gocpp") {
		t.Errorf("build: the error is the user's, not a bug: %q", r.stderr)
	}
}
