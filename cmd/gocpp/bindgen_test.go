// bindgenHeaders is the folder with the headers of the tests of the generator.
func bindgenHeaders(t *testing.T) string {
	t.Helper()
	dir, err := filepath.Abs(filepath.Join("..", "..", "internal", "typedinterop", "bindgen", "testdata"))
	if err != nil {
		t.Fatal(err)
	}
	return dir
}

// inHeaders makes the folder of the test headers the current folder.
func inHeaders(t *testing.T) {
	t.Helper()
	dir := bindgenHeaders(t)
	t.Chdir(filepath.Join(dir, "headers"))
}

func requireClang(t *testing.T) {
	t.Helper()
	if _, err := os.Stat(os.Getenv("GOCPP_CLANG")); err == nil {
		return
	}
	if r := gocppRun("", false, "bindgen", "c_basic.h"); r.code == 3 {
		t.Skip("no clang++")
	}
}

func TestBindgenStdout(t *testing.T) {
	inHeaders(t)
	requireClang(t)
	r := gocppRun("", false, "bindgen", "c_basic.h")
	if r.code != 0 || r.stderr != "" {
		t.Fatalf("exit %d, stderr %q", r.code, r.stderr)
	}
	want, err := os.ReadFile(filepath.Join("..", "golden", "c_basic.gp"))
	if err != nil {
		t.Fatal(err)
	}
	if r.stdout != string(want) {
		t.Errorf("the output is not the golden file of the generator's tests:\n%s", r.stdout)
	}
	// the same with the flags after the header, spelled as the C compiler spells them
	r2 := gocppRun("", false, "bindgen", "c_basic.h", "-o", "-")
	if r2.stdout != r.stdout {
		t.Error("-o - and the standard output differ")
	}
}

func TestBindgenOutputFile(t *testing.T) {
	inHeaders(t)
	requireClang(t)
	out := filepath.Join(t.TempDir(), "view.gp")
	r := gocppRun("", false, "bindgen", "-o", out, "-pkg", "view", "c_macros.h")
	if r.code != 0 || r.stdout != "" || r.stderr != "" {
		t.Fatalf("exit %d, stdout %q, stderr %q", r.code, r.stdout, r.stderr)
	}
	data, err := os.ReadFile(out)
	if err != nil || !strings.HasPrefix(string(data), "// Code generated by gocpp bindgen from c_macros.h. DO NOT EDIT.\n\npackage view\n") {
		t.Fatalf("%v\n%s", err, data)
	}
	// the file is what gocpp fmt keeps, and gocpp check accepts it
	if r := gocppRun("", false, "fmt", "-l", out); r.code != 0 || r.stdout != "" {
		t.Errorf("gocpp fmt -l: exit %d, %q %q", r.code, r.stdout, r.stderr)
	}
	if r := gocppRun("", false, "check", filepath.Dir(out)); r.code != 0 || r.stdout != "" || r.stderr != "" {
		t.Errorf("gocpp check: exit %d, %q %q", r.code, r.stdout, r.stderr)
	}
	// an output that cannot be written is an error, after the view was made
	r = gocppRun("", false, "bindgen", "-o", filepath.Join(t.TempDir(), "no", "such", "dir.gp"), "c_macros.h")
	if r.code != 1 || !strings.HasPrefix(r.stderr, "gocpp bindgen: open ") {
		t.Errorf("unwritable: exit %d, stderr %q", r.code, r.stderr)
	}
}

func TestBindgenFlags(t *testing.T) {
	inHeaders(t)
	requireClang(t)
	r := gocppRun("", false, "bindgen", "flags.h", "-Iinc", "-DFEATURE_X", "-DLEVEL=7", "-std=c++23", "-v")
	if r.code != 0 {
		t.Fatalf("exit %d: %s", r.code, r.stderr)
	}
	for _, want := range []string{`FEATURE_NAME = "x"`, "LEVEL_VALUE  = 7", "STANDARD     = 23", "func feature_x() C.int"} {
		if !strings.Contains(r.stdout, want) {
			t.Errorf("the view lacks %q:\n%s", want, r.stdout)
		}
	}
	if !strings.Contains(r.stderr, "gocpp bindgen: package flags: 0 types, 1 functions, 0 variables, 3 constants") {
		t.Errorf("-v: %q", r.stderr)
	}
	// the same flags with a space, and the patterns
	r = gocppRun("", false, "bindgen", "-I", "inc", "-D", "FEATURE_X", "-include", "^feature", "flags.h")
	if r.code != 0 || strings.Contains(r.stdout, "FEATURE_NAME") || !strings.Contains(r.stdout, "feature_x") {
		t.Errorf("-include: exit %d\n%s%s", r.code, r.stdout, r.stderr)
	}
	r = gocppRun("", false, "bindgen", "-exclude", "^FEATURE", "-exclude", "^STANDARD$", "-I", "inc", "flags.h")
	if r.code != 0 || strings.Contains(r.stdout, "FEATURE_NAME") || strings.Contains(r.stdout, "STANDARD") || !strings.Contains(r.stdout, "no_feature") {
		t.Errorf("-exclude: exit %d\n%s%s", r.code, r.stdout, r.stderr)
	}
	r = gocppRun("", false, "bindgen", "-scope", "tree", "umbrella/umbrella.h")
	if r.code != 0 || !strings.Contains(r.stdout, "func deep(x C.int) C.int") {
		t.Errorf("-scope tree: exit %d\n%s%s", r.code, r.stdout, r.stderr)
	}
	r = gocppRun("", false, "bindgen", "-scope=header", "umbrella/umbrella.h")
	if r.code != 0 || strings.Contains(r.stdout, "part_a") || !strings.Contains(r.stdout, "UMBRELLA_VERSION") {
		t.Errorf("-scope header: exit %d\n%s%s", r.code, r.stdout, r.stderr)
	}
}

func TestBindgenPkgConfig(t *testing.T) {
	inHeaders(t)
	requireClang(t)
	r := gocppRun("", false, "bindgen", "-pkg-config", "sqlite3", "<sqlite3.h>")
	if r.code != 0 {
		t.Skipf("sqlite3 is not installed: exit %d, %s", r.code, r.stderr)
	}
	if !strings.Contains(r.stdout, "package sqlite3\n") || !strings.Contains(r.stdout, "func sqlite3_open(") {
		t.Errorf("sqlite3:\n%.500s", r.stdout)
	}
	r = gocppRun("", false, "bindgen", "-pkg-config", "no-such-package-for-gocpp", "<sqlite3.h>")
	if r.code != 1 || !strings.Contains(r.stderr, "no-such-package-for-gocpp") {
		t.Errorf("unknown package: exit %d, stderr %q", r.code, r.stderr)
	}
}

func TestBindgenErrors(t *testing.T) {
	inHeaders(t)
	requireClang(t)
	for _, c := range []struct {
		name string
		args []string
		code int
		want string
	}{
		{"no header", []string{"bindgen"}, 2, "gocpp bindgen: expected one header\nusage: gocpp bindgen [flags] header\n"},
		{"two headers", []string{"bindgen", "c_basic.h", "c_macros.h"}, 2, "expected one header"},
		{"unknown flag", []string{"bindgen", "-frob", "c_basic.h"}, 2, "flag provided but not defined: -frob"},
		{"missing file", []string{"bindgen", "nothere.h"}, 1, "gocpp bindgen: cannot find header nothere.h\n"},
		{"missing system header", []string{"bindgen", "<nothere.h>"}, 1, "gocpp bindgen: cannot find header <nothere.h>\n"},
		{"broken header", []string{"bindgen", "broken.h"}, 1, "gocpp bindgen: header broken.h doesn't compile: broken.h:2:1: error: expected unqualified-id\n"},
		{"bad package", []string{"bindgen", "-pkg", "type", "c_basic.h"}, 1, `gocpp bindgen: "type" is a Go keyword`},
		{"name without a package", []string{"bindgen", "<map>"}, 1, `"map" is a Go keyword: choose a package name with -pkg`},
		{"bad pattern", []string{"bindgen", "-include", "(", "c_basic.h"}, 1, "bad include pattern"},
		{"bad scope", []string{"bindgen", "-scope", "all", "c_basic.h"}, 1, `unknown scope "all"`},
		{"old standard", []string{"bindgen", "-std", "c++11", "c_basic.h"}, 1, "C++20 or newer"},
	} {
		t.Run(c.name, func(t *testing.T) {
			r := gocppRun("", false, c.args...)
			if r.code != c.code || r.stdout != "" || !strings.Contains(r.stderr, c.want) {
				t.Errorf("exit %d, stdout %q, stderr %q; want exit %d and stderr with %q", r.code, r.stdout, r.stderr, c.code, c.want)
			}
		})
	}
	r := gocppRun("", false, "bindgen", "-h")
	if r.code != 0 || !strings.Contains(r.stderr, "usage: gocpp bindgen [flags] header") || !strings.Contains(r.stderr, "-scope") {
		t.Errorf("-h: exit %d, stderr %q", r.code, r.stderr)
	}
}

// Without clang++ the command says so (the fallback message of the typed interop
// commands) and exits with status 3.
func TestBindgenNoClang(t *testing.T) {
	inHeaders(t)
	t.Setenv("GOCPP_CLANG", filepath.Join(t.TempDir(), "no-such-clang"))
	r := gocppRun("", false, "bindgen", "c_basic.h")
	if r.code != 3 || r.stdout != "" || !strings.HasPrefix(r.stderr, "gocpp bindgen: typed interop needs clang++: ") {
		t.Errorf("exit %d, stdout %q, stderr %q", r.code, r.stdout, r.stderr)
	}
}

func TestBindgenSplitFlags(t *testing.T) {
	in := []string{"-Dx=1", "-D", "y", "-Iinc", "-I", "z", "-std=c++20", "-DFOO", "-pkg-config", "p", "h.h"}
	want := []string{"-D", "x=1", "-D", "y", "-I", "inc", "-I", "z", "-std=c++20", "-D", "FOO", "-pkg-config", "p", "h.h"}
	if got := splitCompilerFlags(in); strings.Join(got, " ") != strings.Join(want, " ") {
		t.Errorf("splitCompilerFlags(%v) = %v, want %v", in, got, want)
	}
	if len(splitCompilerFlags(nil)) != 0 {
		t.Error("nil")
	}
}
