var update = flag.Bool("update", false, "rewrite std.txt from go list std")

// stdHeader is the comment at the top of std.txt.
const stdHeader = `# The import paths of Go's standard packages: what "go list std" prints
# with the dev shell's Go (%s), without the vendor/ packages.
# stdlib.IsStd reads this file. Don't edit it by hand: to make it again,
# run this in the dev shell (nix develop):
#
#	go test ./stdlib -run TestStdList -update
`

// goListStd returns what "go list std" prints, without the vendor/
// packages, and the version of the go command. It skips the test when
// there is no go command.
func goListStd(t *testing.T) ([]string, string) {
	t.Helper()
	if _, err := exec.LookPath("go"); err != nil {
		t.Skip("no go command")
	}
	out, err := exec.Command("go", "list", "std").Output()
	if err != nil {
		t.Fatalf("go list std: %v", err)
	}
	var paths []string
	for _, p := range strings.Fields(string(out)) {
		if !strings.HasPrefix(p, "vendor/") {
			paths = append(paths, p)
		}
	}
	v, err := exec.Command("go", "env", "GOVERSION").Output()
	if err != nil {
		t.Fatalf("go env GOVERSION: %v", err)
	}
	return paths, strings.TrimSpace(string(v))
}

// fileVersion returns the Go version that the file name (in this folder)
// names: the first match of re's group.
func fileVersion(t *testing.T, name string, re *regexp.Regexp) string {
	t.Helper()
	b, err := os.ReadFile(name)
	if err != nil {
		t.Fatal(err)
	}
	m := re.FindSubmatch(b)
	if m == nil {
		t.Fatalf("%s names no Go version", name)
	}
	return string(m[1])
}

// TestStdList checks that std.txt has the paths that "go list std"
// prints, without the vendor/ ones. It skips when the go command is not
// the Go that std.txt comes from, because then it would only find Go's
// changes.
//
// With -update it writes std.txt. It does that only with the Go that the
// stubs come from (their headers say which), so that std.txt never comes
// from a go command that happens to be in PATH. To move to a new Go: in
// its dev shell, run go run ./tools/stubgen first, then the -update.
func TestStdList(t *testing.T) {
	want, version := goListStd(t)
	if *update {
		stubs := fileVersion(t, "fmt/fmt.gp", regexp.MustCompile(`(?m)^// Code generated by tools/stubgen from (go[0-9.]+)'s `))
		if version != stubs {
			t.Fatalf("not writing std.txt: the go command is %s, but the stubs come from %s (run the dev shell's go, or go run ./tools/stubgen first)", version, stubs)
		}
		text := strings.Replace(stdHeader, "%s", version, 1) + "\n" + strings.Join(want, "\n") + "\n"
		if err := os.WriteFile("std.txt", []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Skip("wrote std.txt; run the tests again")
	}
	if from := fileVersion(t, "std.txt", regexp.MustCompile(`the dev shell's Go \((go[0-9.]+)\)`)); version != from {
		t.Skipf("the go command is %s, but std.txt comes from %s (run the tests in the dev shell)", version, from)
	}
	got := stdlib.Std()
	for _, p := range want {
		if !slices.Contains(got, p) {
			t.Errorf("%s is a standard package of %s but not in std.txt", p, version)
		}
	}
	for _, p := range got {
		if !slices.Contains(want, p) {
			t.Errorf("%s is in std.txt but not a standard package of %s", p, version)
		}
	}
}

func TestIsStd(t *testing.T) {
	for _, p := range []string{"fmt", "encoding/json", "unsafe", "internal/bytealg", "crypto/internal/fips140", "math/rand/v2", "regexp/syntax"} {
		if !stdlib.IsStd(p) {
			t.Errorf("IsStd(%q) = false, want true", p)
		}
	}
	for _, p := range []string{"", "C", "std", "cmd/go", "fmt/", "vendor/golang.org/x/net/dns/dnsmessage",
		"golang.org/x/net/dns/dnsmessage", "example.com/multi-pkg/geom", "<vector>", "fmtt", "Fmt"} {
		if stdlib.IsStd(p) {
			t.Errorf("IsStd(%q) = true, want false", p)
		}
	}
	// Std returns a sorted copy without duplicates.
	s := stdlib.Std()
	if !slices.IsSorted(s) || len(slices.Compact(slices.Clone(s))) != len(s) {
		t.Error("Std is not sorted or has duplicates")
	}
	s[0] = "changed"
	if stdlib.Std()[0] == "changed" {
		t.Error("Std returns its own slice")
	}
}

// TestFSHasEveryFile checks that the embedded FS holds every file of this
// folder except the Go package's own (files.go, its tests, README.md and
// std.txt). So a new kind of file (a native .cpp file, a PORT.md) fails
// here until someone decides whether it ships, and so does a .gp file
// that no //go:embed pattern reaches.
func TestFSHasEveryFile(t *testing.T) {
	var want []string
	err := fs.WalkDir(os.DirFS("."), ".", func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		switch {
		case p == "files.go", p == "README.md", p == "std.txt":
		case path.Dir(p) == "." && strings.HasSuffix(p, "_test.go"):
		default:
			want = append(want, p)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	err = fs.WalkDir(stdlib.FS(), ".", func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		got = append(got, p)
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	if !slices.Equal(got, want) {
		t.Errorf("the embedded FS holds\n\t%s\nwant\n\t%s\n(files.go's //go:embed patterns take .gp files up to two folders deep, and LICENSE)",
			strings.Join(got, "\n\t"), strings.Join(want, "\n\t"))
	}
}
